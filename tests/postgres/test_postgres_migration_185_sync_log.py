def test_rejects_wrong_columns():
    with pytest.raises(RuntimeError, match="columns incompatible"):
        apply_sync_log(FakeConnection(columns=[]))


def test_rejects_wrong_counter_default():
    cols = good_columns()
    for c in cols:
        if c["column_name"] == "record_count":
            c["column_default"] = None
    with pytest.raises(RuntimeError, match="columns incompatible"):
        apply_sync_log(FakeConnection(columns=cols))


