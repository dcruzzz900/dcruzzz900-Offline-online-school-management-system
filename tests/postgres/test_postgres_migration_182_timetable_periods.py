def test_rejects_wrong_school_sort_order_index():
    bad = [
        {"indexname": "timetable_periods_pkey", "indexdef": "x"},
        {"indexname": "idx_timetable_periods_school", "indexdef": "CREATE UNIQUE INDEX i ON t USING btree (school_id, sort_order)"},
        {"indexname": "idx_timetable_periods_client_uuid", "indexdef": "CREATE UNIQUE INDEX i ON t USING btree (client_uuid) WHERE (client_uuid IS NOT NULL)"},
    ]
    with pytest.raises(RuntimeError, match="school/sort_order lookup index"):
        apply_timetable_periods(FakeConnection(indexes=bad))


