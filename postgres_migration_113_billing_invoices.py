"""PostgreSQL-native migration 113: billing_invoices.

Ports the reviewed effective SQLite table. The school foreign key targets the
baseline INTEGER schools.id key. Invoice numbers remain globally unique;
timestamp values remain TEXT for application compatibility.
"""
from __future__ import annotations

from postgres_migrations import PostgresMigration

MIGRATION_VERSION = 113
MIGRATION_NAME = "create_billing_invoices"

MIGRATION_STATEMENTS = (
    r'''CREATE TABLE IF NOT EXISTS billing_invoices (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        school_id INTEGER NOT NULL,
        invoice_number TEXT NOT NULL,
        plan_code TEXT NOT NULL,
        amount_ngn DOUBLE PRECISION NOT NULL DEFAULT 0,
        billing_days INTEGER NOT NULL DEFAULT 365,
        status TEXT NOT NULL DEFAULT 'pending',
        issued_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
        due_at TEXT,
        paid_at TEXT,
        payment_reference TEXT,
        notes TEXT,
        created_by TEXT,
        CONSTRAINT uq_billing_invoices_invoice_number UNIQUE (invoice_number),
        CONSTRAINT fk_billing_invoices_school FOREIGN KEY (school_id) REFERENCES schools(id)
    )''',
    "CREATE INDEX IF NOT EXISTS idx_billing_invoices_status ON billing_invoices (status)",
    "CREATE INDEX IF NOT EXISTS idx_billing_invoices_school ON billing_invoices (school_id)",
)
MIGRATION_SOURCE = ";\n\n".join(MIGRATION_STATEMENTS)

_EXPECTED_COLUMNS = {
    "id": ("bigint", True),
    "school_id": ("integer", True),
    "invoice_number": ("text", True),
    "plan_code": ("text", True),
    "amount_ngn": ("double precision", True),
    "billing_days": ("integer", True),
    "status": ("text", True),
    "issued_at": ("text", True),
    "due_at": ("text", False),
    "paid_at": ("text", False),
    "payment_reference": ("text", False),
    "notes": ("text", False),
    "created_by": ("text", False),
}


def apply_billing_invoices(conn) -> None:
    school = conn.execute(
        "SELECT column_name, data_type FROM information_schema.columns "
        "WHERE table_schema = current_schema() AND table_name = ? AND column_name = ?",
        ("schools", "id"),
    ).fetchone()
    if school is None or str(school["data_type"]).lower() != "integer":
        raise RuntimeError("billing_invoices requires schools.id INTEGER in the current schema")

    for statement in MIGRATION_STATEMENTS:
        conn.execute(statement)

    rows = conn.execute(
        "SELECT column_name, data_type, is_nullable FROM information_schema.columns "
        "WHERE table_schema = current_schema() AND table_name = ? ORDER BY ordinal_position",
        ("billing_invoices",),
    ).fetchall()
    actual = {
        str(row["column_name"]): (str(row["data_type"]).lower(), str(row["is_nullable"]).upper() == "NO")
        for row in rows
    }
    missing = sorted(set(_EXPECTED_COLUMNS) - set(actual))
    wrong = {name: {"actual": actual[name], "expected": expected}
             for name, expected in _EXPECTED_COLUMNS.items()
             if name in actual and actual[name] != expected}
    if missing or wrong:
        raise RuntimeError(
            "billing_invoices schema is incompatible; "
            f"missing columns={missing}, incompatible columns={wrong}"
        )

    fk = conn.execute(
        "SELECT kcu.column_name, ccu.table_name AS foreign_table_name, "
        "ccu.column_name AS foreign_column_name "
        "FROM information_schema.table_constraints tc "
        "JOIN information_schema.key_column_usage kcu ON tc.constraint_name = kcu.constraint_name "
        "AND tc.constraint_schema = kcu.constraint_schema "
        "JOIN information_schema.constraint_column_usage ccu ON ccu.constraint_name = tc.constraint_name "
        "AND ccu.constraint_schema = tc.constraint_schema "
        "WHERE tc.constraint_type = 'FOREIGN KEY' AND tc.table_schema = current_schema() "
        "AND tc.table_name = ?",
        ("billing_invoices",),
    ).fetchall()
    actual_fks = {(str(r["column_name"]), str(r["foreign_table_name"]), str(r["foreign_column_name"])) for r in fk}
    if actual_fks != {("school_id", "schools", "id")}:
        raise RuntimeError(f"billing_invoices foreign keys are incompatible: {sorted(actual_fks)}")

    index_rows = conn.execute(
        "SELECT indexname, indexdef FROM pg_indexes "
        "WHERE schemaname = current_schema() AND tablename = ?",
        ("billing_invoices",),
    ).fetchall()
    indexes = {str(r["indexname"]): str(r["indexdef"]).lower().replace('"', '') for r in index_rows}
    expected = {
        "billing_invoices_pkey",
        "uq_billing_invoices_invoice_number",
        "idx_billing_invoices_status",
        "idx_billing_invoices_school",
    }
    if set(indexes) != expected:
        raise RuntimeError(f"billing_invoices indexes are incompatible: {sorted(indexes)}")
    checks = {
        "uq_billing_invoices_invoice_number": "(invoice_number)",
        "idx_billing_invoices_status": "(status)",
        "idx_billing_invoices_school": "(school_id)",
    }
    for name, fragment in checks.items():
        if fragment not in indexes[name]:
            raise RuntimeError(f"billing_invoices index {name} has an incompatible definition")
    if "unique index" not in indexes["uq_billing_invoices_invoice_number"]:
        raise RuntimeError("billing_invoices invoice-number index must be unique")

    triggers = conn.execute(
        "SELECT trigger_name FROM information_schema.triggers "
        "WHERE trigger_schema = current_schema() AND event_object_table = ?",
        ("billing_invoices",),
    ).fetchall()
    if triggers:
        raise RuntimeError("billing_invoices has unexpected triggers")


def migration() -> PostgresMigration:
    return PostgresMigration(version=MIGRATION_VERSION, name=MIGRATION_NAME,
                             apply=apply_billing_invoices, source=MIGRATION_SOURCE)
