from pathlib import Path
import re

import pytest

from tools.build_postgres_base_schema import build_postgres_baseline

ROOT = Path(__file__).resolve().parents[2]


def test_baseline_schema_converts_identity_columns_and_preserves_constraints():
    source = (ROOT / "schema.sql").read_text(encoding="utf-8")
    result = build_postgres_baseline(source)
    assert "INTEGER PRIMARY KEY AUTOINCREMENT" not in result
    assert "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in result
    assert "FOREIGN KEY(school_id) REFERENCES schools(id)" in result
    assert "CHECK(status IN ('present','absent'))" in result
    assert "WHERE subdomain IS NOT NULL" in result


def test_baseline_schema_rejects_untranslated_sqlite_features():
    with pytest.raises(ValueError, match="Unsupported SQLite syntax remains"):
        build_postgres_baseline(
            "CREATE TABLE IF NOT EXISTS sample (id INTEGER PRIMARY KEY AUTOINCREMENT);\nPRAGMA foreign_keys=ON;"
        )


def test_generated_baseline_matches_source_table_and_identity_counts():
    source = (ROOT / "schema.sql").read_text(encoding="utf-8")
    generated = (ROOT / "postgres_schema_base.sql").read_text(encoding="utf-8")
    source_tables = len(re.findall(r"\bCREATE\s+TABLE\s+IF\s+NOT\s+EXISTS\b", source, re.I))
    generated_tables = len(re.findall(r"\bCREATE\s+TABLE\s+IF\s+NOT\s+EXISTS\b", generated, re.I))
    source_ids = len(re.findall(r"\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b", source, re.I))
    generated_ids = len(re.findall(r"\bGENERATED\s+BY\s+DEFAULT\s+AS\s+IDENTITY\b", generated, re.I))
    assert source_tables == generated_tables == 24
    assert source_ids == generated_ids
    assert "Baseline only" in generated
