"""PostgreSQL-native migration 182: timetable_periods.

Ports the effective SQLite table of named timetable periods (with optional
start/end times, a sort order and a break flag), shared school-wide. This is
one of the two original (`migration_038`) timetable tables, predating the
`_v2` family ported in migrations 166-180.

A first read of `migration_038_timetable()` alone suggested this table has
no `tenant_id`, unlike the `_v2` tables. That was wrong: checking the actual
effective schema snapshot (`postgres_effective_schema_snapshot.json`, 11
columns) showed an 11th column, `tenant_id TEXT`, added later by
`migration_051_registration_security_spec()`'s generic `direct=[...]` table
list -- a nullable column, backfilled from `schools.tenant_id` via
`school_id`, and kept populated by a SQLite `AFTER INSERT` trigger
(`trg_timetable_periods_tenant_stamp`) that fills it only when NULL/empty.
This migration adds that column (`tenant_id TEXT`, nullable, no FK, no
NOT NULL -- unlike the `_v2` tables' NOT NULL `tenant_id`, which the
application always supplies itself at insert).

Three existing, not-yet-executed helper scripts already reference this
table by name: `postgres_tombstone_triggers.sql` (a correct
`trg_timetable_periods_tombstone`, keyed off `OLD.school_id`/
`OLD.client_uuid`, both of which this migration creates), and
`postgres_tenant_triggers.sql` (a correct `app_stamp_tenant_timetable_periods()`
+ `trg_timetable_periods_tenant_stamp_pg`, a `BEFORE INSERT` re-implementation
of the SQLite `AFTER INSERT` backfill, same condition and same source
column). Both were checked line by line against the real source behavior
above and are correct for this table (unlike the generic, table-agnostic
`postgres_sync_timestamp_triggers.sql`, whose overlap with migrations
166-180 was flagged, not resolved, in Stage 110's notes). This migration
therefore creates the table, its two indexes, and only the generic
client_uuid/updated_at sync-default/touch triggers (same pattern as
migration 166); it deliberately does NOT add its own tenant-stamp or
tombstone trigger, to avoid duplicating those two scripts' already-correct,
table-specific triggers. This answers the Stage 110 "decide the
trigger-overlap question" item for this specific table: rely on the two
dedicated scripts, don't re-implement them here. It does not alter SQLite
startup, SQLite migrations, or offline sync.
"""
from __future__ import annotations

from postgres_migrations import PostgresMigration

MIGRATION_VERSION = 182
MIGRATION_NAME = "create_timetable_periods"

MIGRATION_STATEMENTS = (
    """CREATE TABLE IF NOT EXISTS timetable_periods (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        school_id INTEGER NOT NULL,
        name TEXT NOT NULL,
        start_time TEXT,
        end_time TEXT,
        sort_order BIGINT NOT NULL DEFAULT 0,
        is_break BIGINT NOT NULL DEFAULT 0,
        client_uuid TEXT,
        updated_at TEXT,
        is_deleted BIGINT DEFAULT 0,
        tenant_id TEXT,
        CONSTRAINT fk_timetable_periods_school FOREIGN KEY (school_id) REFERENCES schools(id)
    )""",
    "CREATE INDEX IF NOT EXISTS idx_timetable_periods_school "
    "ON timetable_periods (school_id, sort_order)",
    "CREATE UNIQUE INDEX IF NOT EXISTS idx_timetable_periods_client_uuid "
    "ON timetable_periods (client_uuid) WHERE client_uuid IS NOT NULL",
    """CREATE OR REPLACE FUNCTION sync_timetable_periods_fields()
    RETURNS trigger LANGUAGE plpgsql AS $$
    DECLARE current_stamp TEXT; old_stamp TIMESTAMP;
    BEGIN
        IF TG_OP = 'INSERT' THEN
            IF NEW.client_uuid IS NULL THEN
                NEW.client_uuid := md5(random()::text || clock_timestamp()::text || pg_backend_pid()::text);
            END IF;
            IF NEW.updated_at IS NULL THEN
                NEW.updated_at := to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS');
            END IF;
            RETURN NEW;
        END IF;
        IF NEW.updated_at IS NOT DISTINCT FROM OLD.updated_at THEN
            current_stamp := to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS');
            IF OLD.updated_at IS NULL OR current_stamp > OLD.updated_at THEN
                NEW.updated_at := current_stamp;
            ELSE
                BEGIN
                    old_stamp := OLD.updated_at::timestamp;
                    NEW.updated_at := to_char(old_stamp + INTERVAL '1 second', 'YYYY-MM-DD"T"HH24:MI:SS');
                EXCEPTION WHEN others THEN
                    NEW.updated_at := current_stamp;
                END;
            END IF;
        END IF;
        RETURN NEW;
    END;
    $$""",
    "DROP TRIGGER IF EXISTS trg_timetable_periods_sync_defaults ON timetable_periods",
    "CREATE TRIGGER trg_timetable_periods_sync_defaults BEFORE INSERT ON timetable_periods "
    "FOR EACH ROW EXECUTE FUNCTION sync_timetable_periods_fields()",
    "DROP TRIGGER IF EXISTS trg_timetable_periods_sync_touch ON timetable_periods",
    "CREATE TRIGGER trg_timetable_periods_sync_touch BEFORE UPDATE ON timetable_periods "
    "FOR EACH ROW EXECUTE FUNCTION sync_timetable_periods_fields()",
)
MIGRATION_SOURCE = ";\n\n".join(MIGRATION_STATEMENTS)

_EXPECTED_COLUMNS = {
    "id": ("bigint", True), "school_id": ("integer", True), "name": ("text", True),
    "start_time": ("text", False), "end_time": ("text", False), "sort_order": ("bigint", True),
    "is_break": ("bigint", True), "client_uuid": ("text", False),
    "updated_at": ("text", False), "is_deleted": ("bigint", False), "tenant_id": ("text", False),
}
_EXPECTED_TRIGGERS = {"trg_timetable_periods_sync_defaults", "trg_timetable_periods_sync_touch"}


def apply_timetable_periods(conn) -> None:
    row = conn.execute(
        "SELECT column_name, data_type FROM information_schema.columns "
        "WHERE table_schema = current_schema() AND table_name = ? AND column_name = ?",
        ("schools", "id"),
    ).fetchone()
    if row is None or str(row["data_type"]).lower() != "integer":
        raise RuntimeError("timetable_periods requires schools.id INTEGER")

    for statement in MIGRATION_STATEMENTS:
        conn.execute(statement)

    rows = conn.execute(
        "SELECT column_name, data_type, is_nullable FROM information_schema.columns "
        "WHERE table_schema = current_schema() AND table_name = ? ORDER BY ordinal_position",
        ("timetable_periods",),
    ).fetchall()
    actual = {str(r["column_name"]): (str(r["data_type"]).lower(), str(r["is_nullable"]).upper() == "NO") for r in rows}
    missing = sorted(set(_EXPECTED_COLUMNS) - set(actual))
    wrong = {n: {"actual": actual[n], "expected": e} for n, e in _EXPECTED_COLUMNS.items() if n in actual and actual[n] != e}
    if missing or wrong or set(actual) != set(_EXPECTED_COLUMNS):
        raise RuntimeError(f"timetable_periods columns incompatible: missing={missing}, wrong={wrong}")

    fk_rows = conn.execute(
        "SELECT kcu.column_name, ccu.table_name AS foreign_table_name, ccu.column_name AS foreign_column_name "
        "FROM information_schema.table_constraints tc "
        "JOIN information_schema.key_column_usage kcu ON tc.constraint_name = kcu.constraint_name AND tc.constraint_schema = kcu.constraint_schema "
        "JOIN information_schema.constraint_column_usage ccu ON ccu.constraint_name = tc.constraint_name AND ccu.constraint_schema = tc.constraint_schema "
        "WHERE tc.constraint_type = 'FOREIGN KEY' AND tc.table_schema = current_schema() AND tc.table_name = ?",
        ("timetable_periods",),
    ).fetchall()
    actual_fks = {(str(r["column_name"]), str(r["foreign_table_name"]), str(r["foreign_column_name"])) for r in fk_rows}
    if actual_fks != {("school_id", "schools", "id")}:
        raise RuntimeError(f"timetable_periods foreign keys incompatible: {sorted(actual_fks)}")

    unique_rows = conn.execute(
        "SELECT tc.constraint_name, kcu.column_name, kcu.ordinal_position "
        "FROM information_schema.table_constraints tc "
        "JOIN information_schema.key_column_usage kcu ON tc.constraint_name = kcu.constraint_name AND tc.constraint_schema = kcu.constraint_schema "
        "WHERE tc.constraint_type = 'UNIQUE' AND tc.table_schema = current_schema() AND tc.table_name = ? "
        "ORDER BY tc.constraint_name, kcu.ordinal_position",
        ("timetable_periods",),
    ).fetchall()
    if unique_rows:
        raise RuntimeError("timetable_periods unique constraints incompatible: unexpected UNIQUE constraint")

    check_rows = conn.execute(
        "SELECT conname FROM pg_constraint WHERE conrelid = 'timetable_periods'::regclass AND contype = 'c'"
    ).fetchall()
    if check_rows:
        raise RuntimeError("timetable_periods CHECK constraints incompatible: unexpected CHECK constraint")

    index_rows = conn.execute(
        "SELECT indexname, indexdef FROM pg_indexes WHERE schemaname = current_schema() AND tablename = ?",
        ("timetable_periods",),
    ).fetchall()
    indexes = {str(r["indexname"]): str(r["indexdef"]).lower().replace('"', "") for r in index_rows}
    expected_indexes = {"timetable_periods_pkey", "idx_timetable_periods_school", "idx_timetable_periods_client_uuid"}
    if set(indexes) != expected_indexes:
        raise RuntimeError(f"timetable_periods indexes incompatible: {sorted(indexes)}")
    school_idx = indexes["idx_timetable_periods_school"]
    if "unique" in school_idx or "(school_id, sort_order)" not in school_idx:
        raise RuntimeError("timetable_periods school/sort_order lookup index is incompatible")
    client_idx = indexes["idx_timetable_periods_client_uuid"]
    if "unique index" not in client_idx or "(client_uuid)" not in client_idx or "where (client_uuid is not null)" not in client_idx:
        raise RuntimeError("timetable_periods client UUID partial index is incompatible")

    trigger_rows = conn.execute(
        "SELECT trigger_name FROM information_schema.triggers WHERE trigger_schema = current_schema() AND event_object_table = ?",
        ("timetable_periods",),
    ).fetchall()
    actual_triggers = {str(r["trigger_name"]) for r in trigger_rows}
    if actual_triggers != _EXPECTED_TRIGGERS:
        raise RuntimeError(f"timetable_periods triggers incompatible: {sorted(actual_triggers)}")


def migration() -> PostgresMigration:
    return PostgresMigration(version=MIGRATION_VERSION, name=MIGRATION_NAME,
                             apply=apply_timetable_periods, source=MIGRATION_SOURCE)
