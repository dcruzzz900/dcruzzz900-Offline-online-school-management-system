import pytest

from postgres_migration_100_security_events import (
    MIGRATION_NAME,
    MIGRATION_SOURCE,
    MIGRATION_VERSION,
    apply_security_events,
    migration,
)
from postgres_migration_registry import POSTGRES_MIGRATIONS


class Result:
    def __init__(self, rows):
        self.rows = rows

    def fetchall(self):
        return self.rows

    def fetchone(self):
        return self.rows[0] if self.rows else None


class FakeConnection:
    def __init__(self, columns=None):
        self.columns = columns if columns is not None else [
            {"column_name": name, "data_type": data_type}
            for name, data_type in {
                "id": "bigint", "event_name": "text", "actor_user_id": "bigint",
                "actor_role": "text", "actor_name": "text", "school_id": "bigint",
                "tenant_id": "text", "resource_type": "text", "resource_id": "bigint",
                "decision": "text", "details": "text", "request_id": "text",
                "created_at": "text",
            }.items()
        ]
        self.calls = []

    def execute(self, sql, params=()):
        self.calls.append((sql, params))
        if "information_schema.columns" in sql:
            return Result(self.columns)
        if "FROM pg_indexes" in sql:
            return Result([{"indexdef": "CREATE INDEX idx_security_events_school_time ON public.security_events USING btree (school_id, created_at)"}])
        return Result([])


def test_migration_has_expected_version_and_name():
    item = migration()
    assert (item.version, item.name) == (100, "create_security_events")
    assert item.source == MIGRATION_SOURCE
    assert MIGRATION_VERSION == 100
    assert MIGRATION_NAME == "create_security_events"


def test_registry_contains_explicitly_reviewed_migrations_in_order():
    assert [item.version for item in POSTGRES_MIGRATIONS] == list(range(100, 143))


def test_creates_standalone_table_and_validates_shape():
    conn = FakeConnection()
    apply_security_events(conn)
    executed = "\n".join(sql for sql, _ in conn.calls)
    assert "GENERATED BY DEFAULT AS IDENTITY" in executed
    assert "REFERENCES" not in executed
    assert "clock_timestamp() AT TIME ZONE 'UTC'" in executed
    assert "CREATE INDEX IF NOT EXISTS idx_security_events_school_time" in executed
    assert "ON security_events (school_id, created_at)" in executed
    assert "trg_security_events_no_delete" in executed
    assert "trg_security_events_no_update" in executed
    assert "ERRCODE = '55000'" in executed
    assert "information_schema.columns" in conn.calls[-2][0]
    assert "FROM pg_indexes" in conn.calls[-1][0]


def test_incompatible_existing_column_type_fails_closed():
    columns = FakeConnection().columns
    columns = [dict(row) for row in columns]
    columns[1]["data_type"] = "character varying"
    with pytest.raises(RuntimeError, match="schema is incompatible"):
        apply_security_events(FakeConnection(columns))


def test_missing_existing_column_fails_closed():
    columns = [row for row in FakeConnection().columns if row["column_name"] != "request_id"]
    with pytest.raises(RuntimeError, match="missing columns"):
        apply_security_events(FakeConnection(columns))


def test_wrong_existing_index_definition_fails_closed():
    class WrongIndexConnection(FakeConnection):
        def execute(self, sql, params=()):
            if "FROM pg_indexes" in sql:
                self.calls.append((sql, params))
                return Result([{"indexdef": "CREATE UNIQUE INDEX idx_security_events_school_time ON public.security_events (school_id)"}])
            return super().execute(sql, params)

    with pytest.raises(RuntimeError, match="index has an incompatible definition"):
        apply_security_events(WrongIndexConnection())
