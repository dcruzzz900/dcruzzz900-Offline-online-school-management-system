"""PostgreSQL-native migration 166: school_days_v2.

Ports the effective SQLite table of per-school timetable days (Monday-Saturday
by default, each with a stable `day_code`). The source declares a single
foreign key (`school_id` -> `schools.id`) and the composite uniqueness
`(tenant_id, school_id, day_code)`. The offline-sync columns that SQLite's
`_make_syncable()` adds later (`client_uuid`, `updated_at`, `is_deleted`), the
partial unique client-UUID index, and the sync default/touch triggers are
recreated here so the effective table matches the schema snapshot. This is a
leaf table: `schedule_slots`, `fixed_activities_v2`, `teacher_availability_v2`
and `timetable_entries_v2` reference `day_id` columns that point at it, which
is why it is ported before them. The default Monday-Saturday rows that the
SQLite application seeds per school are data, not schema, and are not created
here. `school_id` stays INTEGER to match `schools.id`; other INTEGER columns
map to BIGINT and 0/1 flags to BIGINT, as elsewhere in this series. This
migration does not alter SQLite startup, SQLite migrations, or offline sync.
"""
