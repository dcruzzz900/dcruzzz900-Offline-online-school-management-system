"""Standalone PostgreSQL migration 157 for signup workflow records.

Ports the effective SQLite ``signups`` table created by migration_052_auth_signup_audit_spec.
This migration is independent of SQLite startup, SQLite migrations, and offline sync.
"""
from __future__ import annotations

from postgres_migrations import PostgresMigration

MIGRATION_VERSION = 157
MIGRATION_NAME = "create_signups"
MIGRATION_STATEMENTS = (
    """CREATE TABLE IF NOT EXISTS signups (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id BIGINT,
        signup_type TEXT NOT NULL,
        signup_status TEXT NOT NULL DEFAULT 'pending',
        submitted_at TEXT DEFAULT CURRENT_TIMESTAMP,
        verified_at TEXT,
        approved_at TEXT,
        rejected_at TEXT,
        correction_requested_at TEXT,
        school_id BIGINT,
        tenant_id TEXT,
        request_id TEXT,
        notes TEXT,
        CONSTRAINT fk_signups_user FOREIGN KEY (user_id) REFERENCES users(id),
        CONSTRAINT fk_signups_school FOREIGN KEY (school_id) REFERENCES schools(id)
    )""",
    "CREATE INDEX IF NOT EXISTS idx_signups_school_status ON signups (school_id, signup_status)",
)
MIGRATION_SOURCE = ";\n\n".join(MIGRATION_STATEMENTS)

_EXPECTED_COLUMNS = {
    "id": ("bigint", True), "user_id": ("bigint", False),
    "signup_type": ("text", True), "signup_status": ("text", True),
    "submitted_at": ("text", False), "verified_at": ("text", False),
    "approved_at": ("text", False), "rejected_at": ("text", False),
    "correction_requested_at": ("text", False), "school_id": ("bigint", False),
    "tenant_id": ("text", False), "request_id": ("text", False),
    "notes": ("text", False),
}


def apply_signups(conn) -> None:
    for statement in MIGRATION_STATEMENTS:
        conn.execute(statement)

    rows = conn.execute(
        "SELECT column_name, data_type, is_nullable FROM information_schema.columns "
        "WHERE table_schema=current_schema() AND table_name=? ORDER BY ordinal_position",
        ("signups",),
    ).fetchall()
    actual = {
        str(row["column_name"]): (str(row["data_type"]).lower(), str(row["is_nullable"]).upper() == "NO")
        for row in rows
    }
    missing = sorted(set(_EXPECTED_COLUMNS) - set(actual))
    wrong = {name: {"actual": actual[name], "expected": expected}
             for name, expected in _EXPECTED_COLUMNS.items() if name in actual and actual[name] != expected}
    if missing or wrong or set(actual) != set(_EXPECTED_COLUMNS):
        raise RuntimeError(f"signups columns incompatible: missing={missing}, wrong={wrong}")

    constraint_rows = conn.execute(
        "SELECT constraint_name, constraint_type FROM information_schema.table_constraints "
        "WHERE table_schema=current_schema() AND table_name=?", ("signups",),
    ).fetchall()
    constraints = {str(row["constraint_name"]): str(row["constraint_type"]).upper() for row in constraint_rows}
    expected_constraints = {
        "signups_pkey": "PRIMARY KEY",
        "fk_signups_user": "FOREIGN KEY",
        "fk_signups_school": "FOREIGN KEY",
    }
    if constraints != expected_constraints:
        raise RuntimeError(f"signups constraints incompatible: {constraints}")

    index_rows = conn.execute(
        "SELECT indexname, indexdef FROM pg_indexes WHERE schemaname=current_schema() AND tablename=?",
        ("signups",),
    ).fetchall()
    indexes = {str(row["indexname"]): str(row["indexdef"]).lower() for row in index_rows}
    expected_indexes = {"signups_pkey", "idx_signups_school_status"}
    if set(indexes) != expected_indexes:
        raise RuntimeError(f"signups indexes incompatible: {sorted(indexes)}")
    if not all(part in indexes["idx_signups_school_status"] for part in ("school_id", "signup_status")):
        raise RuntimeError("signups school/status index is incompatible")

    triggers = conn.execute(
        "SELECT trigger_name FROM information_schema.triggers "
        "WHERE trigger_schema=current_schema() AND event_object_table=?", ("signups",),
    ).fetchall()
    if triggers:
        raise RuntimeError("signups has unexpected triggers")


def migration() -> PostgresMigration:
    return PostgresMigration(version=MIGRATION_VERSION, name=MIGRATION_NAME,
                             apply=apply_signups, source=MIGRATION_SOURCE)
