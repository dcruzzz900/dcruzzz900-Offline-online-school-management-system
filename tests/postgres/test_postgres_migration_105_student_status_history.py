import pytest
from postgres_migration_105_student_status_history import (
    MIGRATION_NAME, MIGRATION_SOURCE, MIGRATION_VERSION,
    apply_student_status_history, migration,
)
from postgres_migration_registry import POSTGRES_MIGRATIONS

class Result:
    def __init__(self, rows): self.rows = rows
    def fetchall(self): return self.rows
    def fetchone(self): return self.rows[0] if self.rows else None

class FakeConnection:
    def __init__(self, columns=None, fk=False, indexes=None, triggers=None):
        types = {
            "id":"bigint", "school_id":"bigint", "tenant_id":"text", "student_id":"bigint",
            "previous_status":"text", "new_status":"text", "effective_date":"text",
            "destination_school":"text", "previous_school":"text", "reason":"text",
            "changed_by":"bigint", "changed_by_name":"text", "changed_by_role":"text", "server_timestamp":"text",
        }
        required = {"id", "school_id", "student_id", "new_status", "server_timestamp"}
        self.columns = columns if columns is not None else [
            {"column_name":n,"data_type":t,"is_nullable":"NO" if n in required else "YES"} for n,t in types.items()]
        self.fk = fk
        self.indexes = indexes if indexes is not None else [{"indexname":"student_status_history_pkey"},{"indexname":"idx_student_status_history"}]
        self.triggers = triggers if triggers is not None else [
            {"trigger_name":"trg_student_status_history_no_update"},{"trigger_name":"trg_student_status_history_no_delete"}]
        self.calls=[]
    def execute(self, sql, params=()):
        self.calls.append((sql,params))
        if "information_schema.columns" in sql: return Result(self.columns)
        if "constraint_type = 'FOREIGN KEY'" in sql: return Result([{"x":1}] if self.fk else [])
        if "FROM pg_indexes" in sql: return Result(self.indexes)
        if "information_schema.triggers" in sql: return Result(self.triggers)
        return Result([])

def test_metadata_registry_and_schema_port():
    m=migration()
    assert (m.version,m.name,m.source)==(105,MIGRATION_NAME,MIGRATION_SOURCE)
    assert MIGRATION_VERSION==105 and MIGRATION_NAME=="create_student_status_history"
    assert [x.version for x in POSTGRES_MIGRATIONS]==list(range(100, 143))
    conn=FakeConnection(); apply_student_status_history(conn)
    sql="\n".join(s for s,_ in conn.calls)
    assert "GENERATED BY DEFAULT AS IDENTITY" in sql
    assert "idx_student_status_history" in sql
    assert "History is append-only" in sql

def test_rejects_missing_column_and_wrong_index():
    cols=[dict(r) for r in FakeConnection().columns if r["column_name"]!="student_id"]
    with pytest.raises(RuntimeError,match="missing columns"):
        apply_student_status_history(FakeConnection(columns=cols))
    with pytest.raises(RuntimeError,match="indexes are incompatible"):
        apply_student_status_history(FakeConnection(indexes=[{"indexname":"student_status_history_pkey"}]))

def test_rejects_unexpected_foreign_key_or_missing_trigger():
    with pytest.raises(RuntimeError,match="unexpected foreign-key"):
        apply_student_status_history(FakeConnection(fk=True))
    with pytest.raises(RuntimeError,match="append-only triggers are missing"):
        apply_student_status_history(FakeConnection(triggers=[]))
