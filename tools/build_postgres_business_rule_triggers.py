#!/usr/bin/env python3
"""Generate reviewed PostgreSQL ports for two remaining SQLite business-rule triggers."""
from __future__ import annotations
import argparse, json, re
from pathlib import Path

EXPECTED = {'trg_schools_school_code_permanent', 'trg_users_signup_name_init'}

def validate(plan: dict, snapshot: dict) -> None:
    items = [x for x in plan['triggers'] if x.get('category') == 'business_rule_or_other']
    if len(items) != 2 or {x.get('name') for x in items} != EXPECTED:
        raise ValueError('Expected exactly the two reviewed business-rule triggers')
    by_name = {x['name']: x for x in items}
    school = re.sub(r'\s+', ' ', by_name['trg_schools_school_code_permanent']['source_sql']).lower()
    signup = re.sub(r'\s+', ' ', by_name['trg_users_signup_name_init']['source_sql']).lower()
    for token in ('before update of school_code on schools', "old.school_code is not null", "old.school_code<>''", 'new.school_code is not old.school_code', "raise(abort,'the school id is permanent')"):
        if token not in school: raise ValueError(f'Unexpected school-code trigger source; missing {token!r}')
    for token in ('after insert on users', "new.signup_name is null or new.signup_name=''", 'update users set signup_name=new.name where id=new.id'):
        if token not in signup: raise ValueError(f'Unexpected signup-name trigger source; missing {token!r}')
    tables = {t['name']: {c['name'] for c in t['columns']} for t in snapshot['tables']}
    required = {'schools': {'school_code'}, 'users': {'id','name','signup_name'}}
    for table, cols in required.items():
        if table not in tables or not cols <= tables[table]:
            raise ValueError(f'{table} missing required columns: {sorted(cols - tables.get(table, set()))}')

def generate(plan: dict, snapshot: dict) -> str:
    validate(plan, snapshot)
    return '''-- Generated by tools/build_postgres_business_rule_triggers.py
-- Reviewed ports of the two remaining SQLite business-rule triggers.
-- Apply only after reviewing POSTGRES_BUSINESS_RULE_TRIGGERS.md.

CREATE OR REPLACE FUNCTION app_guard_permanent_school_code()
RETURNS trigger
LANGUAGE plpgsql
AS $function$
BEGIN
  IF OLD.school_code IS NOT NULL
     AND OLD.school_code <> ''
     AND NEW.school_code IS DISTINCT FROM OLD.school_code THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'The School ID is permanent';
  END IF;
  RETURN NEW;
END;
$function$;

DROP TRIGGER IF EXISTS trg_schools_school_code_permanent_pg ON schools;
CREATE TRIGGER trg_schools_school_code_permanent_pg
BEFORE UPDATE OF school_code ON schools
FOR EACH ROW EXECUTE FUNCTION app_guard_permanent_school_code();

-- Deliberately AFTER INSERT, matching SQLite's timing: the row is inserted,
-- then signup_name is initialized in the same transaction. The existing
-- immutable-signup-name guard permits the empty-to-initial-value transition.
CREATE OR REPLACE FUNCTION app_initialize_signup_name()
RETURNS trigger
LANGUAGE plpgsql
AS $function$
BEGIN
  IF NEW.signup_name IS NULL OR NEW.signup_name = '' THEN
    UPDATE users SET signup_name = NEW.name WHERE id = NEW.id;
  END IF;
  RETURN NEW;
END;
$function$;

DROP TRIGGER IF EXISTS trg_users_signup_name_init_pg ON users;
CREATE TRIGGER trg_users_signup_name_init_pg
AFTER INSERT ON users
FOR EACH ROW EXECUTE FUNCTION app_initialize_signup_name();
'''

def main() -> None:
    ap=argparse.ArgumentParser()
    ap.add_argument('--inventory', default='postgres_trigger_porting_plan.json')
    ap.add_argument('--snapshot', default='postgres_effective_schema_snapshot.json')
    ap.add_argument('--output', default='postgres_business_rule_triggers.sql')
    a=ap.parse_args()
    Path(a.output).write_text(generate(json.loads(Path(a.inventory).read_text()), json.loads(Path(a.snapshot).read_text())))
    print('Generated 2 PostgreSQL business-rule triggers and 2 functions.')
if __name__ == '__main__': main()
