"""PostgreSQL-native migration 184: sync_tombstones.

Ports the effective SQLite table that records hard deletions so offline
devices can drop the matching records on their next pull. Every
`trg_<table>_tombstone` function in `postgres_tombstone_triggers.sql` inserts
into this table, and nothing had created it in PostgreSQL until now.

The effective source has exactly 5 columns (confirmed against the effective
schema snapshot): `id`, a nullable `school_id`, and NOT NULL `entity`,
`client_uuid` and `deleted_at` (UTC text, YYYY-MM-DDTHH:MM:SS). Unlike the
timetable tables it has no `tenant_id`, `updated_at`, `is_deleted` or
`client_uuid` uniqueness: several tombstones may legitimately exist for one
client_uuid (a record deleted, recreated and deleted again), so no unique
index is created. The source declares no foreign key on `school_id`; none is
added, because a tombstone must outlive its school row and a missing parent
already yields NULL in the trigger functions. There are no CHECK constraints
and no triggers on this table; verification asserts none exist.

The one index, `idx_sync_tombstones_school (school_id, deleted_at)`, is the
non-unique lookup the sync pull uses to filter by school and cursor.
`id` is a BIGINT identity, following the rest of this series for SQLite
INTEGER PRIMARY KEY AUTOINCREMENT columns. This migration does not alter
SQLite startup, SQLite migrations, or offline sync.
"""
from __future__ import annotations

from postgres_migrations import PostgresMigration

MIGRATION_VERSION = 184
MIGRATION_NAME = "create_sync_tombstones"

MIGRATION_STATEMENTS = (
    """CREATE TABLE IF NOT EXISTS sync_tombstones (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        school_id INTEGER,
        entity TEXT NOT NULL,
        client_uuid TEXT NOT NULL,
        deleted_at TEXT NOT NULL
    )""",
    "CREATE INDEX IF NOT EXISTS idx_sync_tombstones_school "
    "ON sync_tombstones (school_id, deleted_at)",
)
MIGRATION_SOURCE = ";\n\n".join(MIGRATION_STATEMENTS)

_EXPECTED_COLUMNS = {
    "id": ("bigint", True), "school_id": ("integer", False), "entity": ("text", True),
    "client_uuid": ("text", True), "deleted_at": ("text", True),
}


def apply_sync_tombstones(conn) -> None:
    for statement in MIGRATION_STATEMENTS:
        conn.execute(statement)

    rows = conn.execute(
        "SELECT column_name, data_type, is_nullable FROM information_schema.columns "
        "WHERE table_schema = current_schema() AND table_name = ? ORDER BY ordinal_position",
        ("sync_tombstones",),
    ).fetchall()
    actual = {str(r["column_name"]): (str(r["data_type"]).lower(), str(r["is_nullable"]).upper() == "NO") for r in rows}
    missing = sorted(set(_EXPECTED_COLUMNS) - set(actual))
    wrong = {n: {"actual": actual[n], "expected": e} for n, e in _EXPECTED_COLUMNS.items() if n in actual and actual[n] != e}
    if missing or wrong or set(actual) != set(_EXPECTED_COLUMNS):
        raise RuntimeError(f"sync_tombstones columns incompatible: missing={missing}, wrong={wrong}")

    fk_rows = conn.execute(
        "SELECT kcu.column_name FROM information_schema.table_constraints tc "
        "JOIN information_schema.key_column_usage kcu ON tc.constraint_name = kcu.constraint_name AND tc.constraint_schema = kcu.constraint_schema "
        "WHERE tc.constraint_type = 'FOREIGN KEY' AND tc.table_schema = current_schema() AND tc.table_name = ?",
        ("sync_tombstones",),
    ).fetchall()
    if fk_rows:
        raise RuntimeError("sync_tombstones foreign keys incompatible: source declares none")

    unique_rows = conn.execute(
        "SELECT tc.constraint_name FROM information_schema.table_constraints tc "
        "WHERE tc.constraint_type = 'UNIQUE' AND tc.table_schema = current_schema() AND tc.table_name = ?",
        ("sync_tombstones",),
    ).fetchall()
    if unique_rows:
        raise RuntimeError("sync_tombstones unique constraints incompatible: unexpected table-level UNIQUE constraint")

    check_rows = conn.execute(
        "SELECT conname FROM pg_constraint WHERE conrelid = 'sync_tombstones'::regclass AND contype = 'c'"
    ).fetchall()
    if check_rows:
        raise RuntimeError("sync_tombstones CHECK constraints incompatible: unexpected CHECK constraint")

    index_rows = conn.execute(
        "SELECT indexname, indexdef FROM pg_indexes WHERE schemaname = current_schema() AND tablename = ?",
        ("sync_tombstones",),
    ).fetchall()
    indexes = {str(r["indexname"]): str(r["indexdef"]).lower().replace('"', "") for r in index_rows}
    if set(indexes) != {"sync_tombstones_pkey", "idx_sync_tombstones_school"}:
        raise RuntimeError(f"sync_tombstones indexes incompatible: {sorted(indexes)}")
    school_idx = indexes["idx_sync_tombstones_school"]
    if "unique" in school_idx or "(school_id, deleted_at)" not in school_idx:
        raise RuntimeError("sync_tombstones school lookup index is incompatible")

    trigger_rows = conn.execute(
        "SELECT trigger_name FROM information_schema.triggers WHERE trigger_schema = current_schema() AND event_object_table = ?",
        ("sync_tombstones",),
    ).fetchall()
    if trigger_rows:
        raise RuntimeError(f"sync_tombstones triggers incompatible: {sorted(str(r['trigger_name']) for r in trigger_rows)}")


def migration() -> PostgresMigration:
    return PostgresMigration(version=MIGRATION_VERSION, name=MIGRATION_NAME,
                             apply=apply_sync_tombstones, source=MIGRATION_SOURCE)
