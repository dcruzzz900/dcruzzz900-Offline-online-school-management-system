import pytest
from postgres_migration_106_ai_audit_log import (
    MIGRATION_NAME, MIGRATION_SOURCE, MIGRATION_VERSION, apply_ai_audit_log, migration,
)
from postgres_migration_registry import POSTGRES_MIGRATIONS


class Result:
    def __init__(self, rows): self.rows = rows
    def fetchall(self): return self.rows
    def fetchone(self): return self.rows[0] if self.rows else None


class FakeConnection:
    def __init__(self, columns=None, fk=False, indexes=None, triggers=None):
        types = {
            "id": "bigint", "school_id": "bigint", "user_id": "bigint", "feature": "text",
            "student_id": "bigint", "consent_status": "text", "data_scope": "text", "action": "text",
            "request_summary": "text", "output_summary": "text", "created_at": "text", "tenant_id": "text",
        }
        required = {"id", "school_id", "feature", "action"}
        self.columns = columns if columns is not None else [
            {"column_name": n, "data_type": t, "is_nullable": "NO" if n in required else "YES"}
            for n, t in types.items()
        ]
        self.fk = fk
        self.indexes = indexes if indexes is not None else [
            {"indexname": "ai_audit_log_pkey"}, {"indexname": "idx_ai_audit_school_time"}
        ]
        self.triggers = triggers if triggers is not None else [{"trigger_name": "trg_ai_audit_log_tenant_stamp_pg"}]
        self.calls = []

    def execute(self, sql, params=()):
        self.calls.append((sql, params))
        if "information_schema.columns" in sql: return Result(self.columns)
        if "constraint_type = 'FOREIGN KEY'" in sql: return Result([{"x": 1}] if self.fk else [])
        if "FROM pg_indexes" in sql: return Result(self.indexes)
        if "information_schema.triggers" in sql: return Result(self.triggers)
        return Result([])


def test_metadata_registry_and_schema_port():
    m = migration()
    assert (m.version, m.name, m.source) == (106, MIGRATION_NAME, MIGRATION_SOURCE)
    assert MIGRATION_VERSION == 106 and MIGRATION_NAME == "create_ai_audit_log"
    assert [item.version for item in POSTGRES_MIGRATIONS] == list(range(100, 188))
    conn = FakeConnection(); apply_ai_audit_log(conn)
    sql = "\n".join(statement for statement, _ in conn.calls)
    assert "GENERATED BY DEFAULT AS IDENTITY" in sql
    assert "idx_ai_audit_school_time ON ai_audit_log (school_id, created_at)" in sql
    assert "NEW.tenant_id := v_tenant_id" in sql
    assert "BEFORE INSERT ON ai_audit_log" in sql


def test_rejects_missing_column_wrong_index_and_missing_trigger():
    cols = [dict(row) for row in FakeConnection().columns if row["column_name"] != "tenant_id"]
    with pytest.raises(RuntimeError, match="missing columns"):
        apply_ai_audit_log(FakeConnection(columns=cols))
    with pytest.raises(RuntimeError, match="indexes are incompatible"):
        apply_ai_audit_log(FakeConnection(indexes=[{"indexname": "ai_audit_log_pkey"}]))
    with pytest.raises(RuntimeError, match="tenant-stamping trigger is missing"):
        apply_ai_audit_log(FakeConnection(triggers=[]))


def test_rejects_unexpected_foreign_key_and_incompatible_column():
    with pytest.raises(RuntimeError, match="unexpected foreign-key"):
        apply_ai_audit_log(FakeConnection(fk=True))
    cols = [dict(row) for row in FakeConnection().columns]
    cols[1]["data_type"] = "integer"
    with pytest.raises(RuntimeError, match="incompatible columns"):
        apply_ai_audit_log(FakeConnection(columns=cols))
