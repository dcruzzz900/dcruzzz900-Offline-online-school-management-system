import pytest

from postgres_migration_167_schedule_templates import (
    MIGRATION_NAME, MIGRATION_SOURCE, MIGRATION_STATEMENTS, MIGRATION_VERSION,
    _EXPECTED_COLUMNS, apply_schedule_templates, migration,
)
from postgres_migration_registry import POSTGRES_MIGRATIONS


class Result:
    def __init__(self, rows): self.rows = rows
    def fetchall(self): return self.rows
    def fetchone(self): return self.rows[0] if self.rows else None


class FakeConnection:
    def __init__(self, columns=None, fks=None, uniques=None, indexes=None, triggers=None, parent_types=None):
        self.columns = columns if columns is not None else [
            {"column_name": n, "data_type": typ, "is_nullable": "NO" if req else "YES"}
            for n, (typ, req) in _EXPECTED_COLUMNS.items()
        ]
        self.fks = fks if fks is not None else [
            {"column_name": "school_id", "foreign_table_name": "schools", "foreign_column_name": "id"},
            {"column_name": "academic_session_id", "foreign_table_name": "sessions", "foreign_column_name": "id"},
            {"column_name": "term_id", "foreign_table_name": "terms", "foreign_column_name": "id"},
        ]
        self.uniques = uniques if uniques is not None else []
        self.indexes = indexes if indexes is not None else [
            {"indexname": "schedule_templates_pkey", "indexdef": "CREATE UNIQUE INDEX schedule_templates_pkey ON public.schedule_templates USING btree (id)"},
            {"indexname": "idx_schedule_templates_client_uuid", "indexdef": "CREATE UNIQUE INDEX idx_schedule_templates_client_uuid ON public.schedule_templates USING btree (client_uuid) WHERE (client_uuid IS NOT NULL)"},
        ]
        self.triggers = triggers if triggers is not None else [
            {"trigger_name": "trg_schedule_templates_sync_defaults"}, {"trigger_name": "trg_schedule_templates_sync_touch"}]
        self.parent_types = {"schools": "integer", "sessions": "integer", "terms": "integer"}
        self.parent_types.update(parent_types or {})
        self.calls = []

    def execute(self, sql, params=()):
        self.calls.append((sql, params))
        if "information_schema.columns" in sql and params and params[0] in self.parent_types:
            return Result([{"column_name": "id", "data_type": self.parent_types[params[0]]}])
        if "information_schema.columns" in sql: return Result(self.columns)
        if "constraint_type = 'FOREIGN KEY'" in sql: return Result(self.fks)
        if "constraint_type = 'UNIQUE'" in sql: return Result(self.uniques)
        if "FROM pg_indexes" in sql: return Result(self.indexes)
        if "information_schema.triggers" in sql: return Result(self.triggers)
        return Result([])


def test_registry_and_migration_identity():
    assert MIGRATION_VERSION == 167
    assert MIGRATION_NAME == "create_schedule_templates"
    assert POSTGRES_MIGRATIONS[-21].version == 167
    assert [m.version for m in POSTGRES_MIGRATIONS] == list(range(100, 188))
    assert migration().version == 167


def test_effective_sqlite_schema_is_preserved():
    assert list(_EXPECTED_COLUMNS) == [
        "id", "tenant_id", "school_id", "academic_session_id", "term_id", "name", "description",
        "is_default", "status", "created_at", "updated_at", "client_uuid", "is_deleted",
    ]
    sql = MIGRATION_SOURCE.lower()
    for fragment in (
        "id bigint generated by default as identity primary key", "tenant_id text not null",
        "school_id integer not null", "academic_session_id integer,", "term_id integer,",
        "name text not null", "is_default bigint not null default 0", "status text not null default 'active'",
        "created_at text default current_timestamp", "updated_at text default current_timestamp",
        "is_deleted bigint default 0", "references schools(id)", "references sessions(id)",
        "references terms(id)", "where client_uuid is not null", "before insert", "before update",
    ):
        assert fragment in sql
    assert sql.count("references ") == 3
    assert "unique (" not in sql.replace("create unique index", "")


def test_apply_executes_every_statement_and_validates():
    conn = FakeConnection()
    apply_schedule_templates(conn)
    executed = [sql for sql, _ in conn.calls]
    for statement in MIGRATION_STATEMENTS:
        assert statement in executed


@pytest.mark.parametrize("parent", ["schools", "sessions", "terms"])
def test_rejects_incompatible_parent_key_type(parent):
    with pytest.raises(RuntimeError, match=f"{parent}.id INTEGER"):
        apply_schedule_templates(FakeConnection(parent_types={parent: "bigint"}))


def test_rejects_wrong_columns():
    with pytest.raises(RuntimeError, match="columns incompatible"):
        apply_schedule_templates(FakeConnection(columns=[]))


def test_rejects_missing_or_wrong_foreign_keys():
    with pytest.raises(RuntimeError, match="foreign keys incompatible"):
        apply_schedule_templates(FakeConnection(fks=[]))
    partial = [{"column_name": "school_id", "foreign_table_name": "schools", "foreign_column_name": "id"}]
    with pytest.raises(RuntimeError, match="foreign keys incompatible"):
        apply_schedule_templates(FakeConnection(fks=partial))


def test_rejects_unexpected_unique_constraint():
    with pytest.raises(RuntimeError, match="unique constraints incompatible"):
        apply_schedule_templates(FakeConnection(uniques=[{"constraint_name": "x"}]))


def test_rejects_wrong_indexes():
    with pytest.raises(RuntimeError, match="indexes incompatible"):
        apply_schedule_templates(FakeConnection(indexes=[]))


def test_rejects_non_partial_client_uuid_index():
    bad = [
        {"indexname": "schedule_templates_pkey", "indexdef": "x"},
        {"indexname": "idx_schedule_templates_client_uuid", "indexdef": "CREATE INDEX i ON t USING btree (client_uuid)"},
    ]
    with pytest.raises(RuntimeError, match="partial index"):
        apply_schedule_templates(FakeConnection(indexes=bad))


def test_rejects_wrong_triggers():
    with pytest.raises(RuntimeError, match="triggers incompatible"):
        apply_schedule_templates(FakeConnection(triggers=[]))
