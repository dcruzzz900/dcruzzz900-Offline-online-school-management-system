import pytest

from postgres_migration_185_sync_log import (
    MIGRATION_NAME, MIGRATION_SOURCE, MIGRATION_STATEMENTS, MIGRATION_VERSION,
    _EXPECTED_COLUMNS, apply_sync_log, migration,
)
from postgres_migration_registry import POSTGRES_MIGRATIONS

_DEFAULTS = {"record_count": "0", "conflict_count": "0", "error_count": "0", "created_at": "CURRENT_TIMESTAMP"}


class Result:
    def __init__(self, rows): self.rows = rows
    def fetchall(self): return self.rows
    def fetchone(self): return self.rows[0] if self.rows else None


GOOD_INDEXES = [
    {"indexname": "sync_log_pkey", "indexdef": "CREATE UNIQUE INDEX sync_log_pkey ON public.sync_log USING btree (id)"},
    {"indexname": "idx_sync_log_school", "indexdef": "CREATE INDEX idx_sync_log_school ON public.sync_log USING btree (school_id, created_at)"},
]


def good_columns():
    return [
        {"column_name": n, "data_type": typ, "is_nullable": "NO" if req else "YES", "column_default": _DEFAULTS.get(n)}
        for n, (typ, req, _d) in _EXPECTED_COLUMNS.items()
    ]


class FakeConnection:
    def __init__(self, columns=None, fks=None, uniques=None, checks=None, indexes=None, triggers=None):
        self.columns = columns if columns is not None else good_columns()
        self.fks = fks or []
        self.uniques = uniques or []
        self.checks = checks or []
        self.indexes = indexes if indexes is not None else GOOD_INDEXES
        self.triggers = triggers or []
        self.calls = []

    def execute(self, sql, params=()):
        self.calls.append((sql, params))
        if "information_schema.columns" in sql: return Result(self.columns)
        if "constraint_type = 'FOREIGN KEY'" in sql: return Result(self.fks)
        if "constraint_type = 'UNIQUE'" in sql: return Result(self.uniques)
        if "FROM pg_constraint" in sql: return Result(self.checks)
        if "FROM pg_indexes" in sql: return Result(self.indexes)
        if "information_schema.triggers" in sql: return Result(self.triggers)
        return Result([])


def test_registry_and_migration_identity():
    assert MIGRATION_VERSION == 185
    assert MIGRATION_NAME == "create_sync_log"
    assert POSTGRES_MIGRATIONS[-3].version == 185
    assert [m.version for m in POSTGRES_MIGRATIONS] == list(range(100, 188))
    assert migration().version == 185


def test_effective_sqlite_schema_is_preserved():
    assert list(_EXPECTED_COLUMNS) == [
        "id", "school_id", "device_id", "user_id", "direction", "entity",
        "record_count", "conflict_count", "error_count", "created_at", "tenant_id",
    ]
    sql = MIGRATION_SOURCE.lower()
    for fragment in (
        "id bigint generated by default as identity primary key", "school_id integer not null",
        "device_id text not null", "user_id integer,", "direction text not null", "entity text,",
        "record_count bigint default 0", "conflict_count bigint default 0", "error_count bigint default 0",
        "created_at text default current_timestamp", "tenant_id text",
        "idx_sync_log_school", "(school_id, created_at)",
    ):
        assert fragment in sql
    assert "references" not in sql and "unique" not in sql and "check" not in sql and "trigger" not in sql


def test_apply_executes_every_statement_and_validates():
    conn = FakeConnection()
    apply_sync_log(conn)
    executed = [sql for sql, _ in conn.calls]
    for statement in MIGRATION_STATEMENTS:
        assert statement in executed


