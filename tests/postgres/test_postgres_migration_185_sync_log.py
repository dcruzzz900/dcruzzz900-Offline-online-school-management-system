def test_rejects_unique_or_wrong_school_index():
    for bad_def in ("CREATE UNIQUE INDEX i ON t USING btree (school_id, created_at)",
                    "CREATE INDEX i ON t USING btree (created_at, school_id)"):
        bad = [GOOD_INDEXES[0], {"indexname": "idx_sync_log_school", "indexdef": bad_def}]
        with pytest.raises(RuntimeError, match="school lookup index"):
            apply_sync_log(FakeConnection(indexes=bad))


