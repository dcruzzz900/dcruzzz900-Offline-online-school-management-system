import pytest

from postgres_migration_139_parent_teacher_messages import (
    MIGRATION_NAME, MIGRATION_SOURCE, MIGRATION_VERSION,
    apply_parent_teacher_messages, migration,
)
from postgres_migration_registry import POSTGRES_MIGRATIONS


class Result:
    def __init__(self, rows): self.rows = rows
    def fetchall(self): return self.rows
    def fetchone(self): return self.rows[0] if self.rows else None


class FakeConnection:
    def __init__(self, dependency_types=None, columns=None, fks=None, indexes=None, checks=None, triggers=None):
        self.dependency_types = dependency_types or {
            "schools": "integer", "parent_accounts": "bigint", "users": "integer", "students": "integer"
        }
        expected = {
            "id": ("bigint", True), "school_id": ("integer", True),
            "parent_id": ("bigint", True), "teacher_id": ("integer", True),
            "student_id": ("integer", True), "body": ("text", True),
            "sender_type": ("text", True), "is_read": ("integer", True),
            "created_at": ("text", False), "tenant_id": ("text", False),
        }
        self.columns = columns if columns is not None else [
            {"column_name": name, "data_type": typ, "is_nullable": "NO" if required else "YES"}
            for name, (typ, required) in expected.items()
        ]
        self.fks = fks if fks is not None else [
            {"column_name": "school_id", "foreign_table_name": "schools", "foreign_column_name": "id"},
            {"column_name": "parent_id", "foreign_table_name": "parent_accounts", "foreign_column_name": "id"},
            {"column_name": "teacher_id", "foreign_table_name": "users", "foreign_column_name": "id"},
            {"column_name": "student_id", "foreign_table_name": "students", "foreign_column_name": "id"},
        ]
        self.indexes = indexes if indexes is not None else [
            {"indexname": "parent_teacher_messages_pkey", "indexdef": "CREATE UNIQUE INDEX parent_teacher_messages_pkey ON public.parent_teacher_messages USING btree (id)"},
            {"indexname": "idx_parent_messages_teacher", "indexdef": "CREATE INDEX idx_parent_messages_teacher ON public.parent_teacher_messages USING btree (school_id, teacher_id, is_read)"},
            {"indexname": "idx_parent_messages_thread", "indexdef": "CREATE INDEX idx_parent_messages_thread ON public.parent_teacher_messages USING btree (school_id, parent_id, teacher_id, student_id, created_at)"},
        ]
        self.checks = checks if checks is not None else [
            {"conname": "parent_teacher_messages_sender_type_check", "definition": "CHECK ((sender_type = ANY (ARRAY['parent'::text, 'teacher'::text])))"}
        ]
        self.triggers = triggers if triggers is not None else [
            {"trigger_name": "trg_parent_teacher_messages_tenant_stamp_pg"}
        ]
        self.calls = []

    def execute(self, sql, params=()):
        self.calls.append((sql, params))
        if "information_schema.columns" in sql and len(params) == 2 and params[0] in self.dependency_types:
            return Result([{"column_name": "id", "data_type": self.dependency_types[params[0]]}])
        if "information_schema.columns" in sql:
            return Result(self.columns)
        if "information_schema.table_constraints" in sql and "JOIN" in sql:
            return Result(self.fks)
        if "FROM pg_indexes" in sql:
            return Result(self.indexes)
        if "FROM pg_constraint" in sql:
            return Result(self.checks)
        if "information_schema.triggers" in sql:
            return Result(self.triggers)
        return Result([])


def test_registry_and_migration_identity():
    assert MIGRATION_VERSION == 139
    assert MIGRATION_NAME == "create_parent_teacher_messages"
    assert [item.version for item in POSTGRES_MIGRATIONS] == list(range(100, 188))
    assert next(item for item in POSTGRES_MIGRATIONS if item.version == 139).name == MIGRATION_NAME
    assert migration().version == 139


def test_ddl_preserves_source_relationships_constraints_indexes_and_trigger():
    sql = MIGRATION_SOURCE.lower()
    for fragment in (
        "id bigint generated by default as identity primary key",
        "school_id integer not null", "parent_id bigint not null",
        "teacher_id integer not null", "student_id integer not null",
        "sender_type text not null check (sender_type in ('parent', 'teacher'))",
        "is_read integer not null default 0", "created_at text default current_timestamp",
        "references parent_accounts(id) on delete cascade",
        "references schools(id)", "references users(id)", "references students(id)",
        "idx_parent_messages_teacher on parent_teacher_messages(school_id, teacher_id, is_read)",
        "idx_parent_messages_thread on parent_teacher_messages(school_id, parent_id, teacher_id, student_id, created_at)",
        "after insert on parent_teacher_messages", "new.tenant_id is null or new.tenant_id = ''",
    ):
        assert fragment in sql


def test_apply_executes_and_validates_migration():
    conn = FakeConnection()
    apply_parent_teacher_messages(conn)
    assert len([call for call in conn.calls if call[0] in MIGRATION_SOURCE.split(";\n\n")]) == len(MIGRATION_SOURCE.split(";\n\n"))


@pytest.mark.parametrize("dependency,wrong_type", [
    ("schools", "bigint"), ("parent_accounts", "integer"),
    ("users", "bigint"), ("students", "bigint"),
])
def test_apply_rejects_incompatible_dependency_key_types(dependency, wrong_type):
    types = {"schools": "integer", "parent_accounts": "bigint", "users": "integer", "students": "integer"}
    types[dependency] = wrong_type
    with pytest.raises(RuntimeError, match="requires"):
        apply_parent_teacher_messages(FakeConnection(dependency_types=types))


def test_apply_rejects_missing_foreign_key():
    with pytest.raises(RuntimeError, match="foreign keys"):
        apply_parent_teacher_messages(FakeConnection(fks=[]))


def test_apply_rejects_wrong_index_set():
    with pytest.raises(RuntimeError, match="indexes"):
        apply_parent_teacher_messages(FakeConnection(indexes=[]))


def test_apply_rejects_missing_sender_type_check():
    with pytest.raises(RuntimeError, match="CHECK constraint"):
        apply_parent_teacher_messages(FakeConnection(checks=[]))


def test_apply_rejects_missing_tenant_trigger():
    with pytest.raises(RuntimeError, match="triggers"):
        apply_parent_teacher_messages(FakeConnection(triggers=[]))
