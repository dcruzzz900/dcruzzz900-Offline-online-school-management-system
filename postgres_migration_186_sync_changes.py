"""PostgreSQL-native migration 186: sync_changes.

Ports the effective SQLite table holding one row per change a device replayed
from its offline queue (`offline_sync.py`). `change_id` (a UUID made on the
device) plus `school_id` makes a retried push idempotent: a retry is answered
from the stored row and `attempts` is incremented rather than the change being
applied twice.

The source has 17 columns (confirmed against the effective schema snapshot;
`tenant_id` is declared directly in its `CREATE TABLE`, so no later migration
adds it and no tenant-stamp trigger exists or is needed -- the application
supplies it). Unlike the other sync tables ported so far, this one carries a
real table-level constraint: `UNIQUE(school_id, change_id)`. The application
depends on it for its `INSERT ... ON CONFLICT(school_id, change_id) DO UPDATE`
upserts, which PostgreSQL accepts against a UNIQUE constraint, so it is
recreated as a named UNIQUE constraint (not a bare index) and verification
checks its columns and their order. The non-unique lookup index
`idx_sync_changes_school (school_id, received_at)` is also recreated.

Type choices follow this series: `id` is a BIGINT identity; `status_code` and
`attempts` are BIGINT; `school_id` and `user_id` stay INTEGER to match
`schools.id` / `users.id`. Defaults are preserved: `received_at TEXT DEFAULT
CURRENT_TIMESTAMP`, `state TEXT NOT NULL DEFAULT 'applied'`, `attempts BIGINT
DEFAULT 1`. The source declares no foreign key and no CHECK (the `applied |
conflict | failed` list on `state` is only a comment), so none is added;
verification asserts none exist, nor any trigger. This migration does not alter
SQLite startup, SQLite migrations, or offline sync.
"""
from __future__ import annotations

from postgres_migrations import PostgresMigration

MIGRATION_VERSION = 186
MIGRATION_NAME = "create_sync_changes"
_UNIQUE_NAME = "sync_changes_school_id_change_id_key"

MIGRATION_STATEMENTS = (
    f"""CREATE TABLE IF NOT EXISTS sync_changes (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        change_id TEXT NOT NULL,
        school_id INTEGER NOT NULL,
        tenant_id TEXT,
        user_id INTEGER,
        device_id TEXT,
        method TEXT,
        path TEXT,
        entity TEXT,
        entity_key TEXT,
        base_version TEXT,
        captured_at TEXT,
        received_at TEXT DEFAULT CURRENT_TIMESTAMP,
        state TEXT NOT NULL DEFAULT 'applied',
        status_code BIGINT,
        response_body TEXT,
        attempts BIGINT DEFAULT 1,
        CONSTRAINT {_UNIQUE_NAME} UNIQUE (school_id, change_id)
    )""",
    "CREATE INDEX IF NOT EXISTS idx_sync_changes_school ON sync_changes (school_id, received_at)",
)
MIGRATION_SOURCE = ";\n\n".join(MIGRATION_STATEMENTS)

# name -> (data_type, not_null, default fragment or None)
_EXPECTED_COLUMNS = {
    "id": ("bigint", True, None), "change_id": ("text", True, None),
    "school_id": ("integer", True, None), "tenant_id": ("text", False, None),
    "user_id": ("integer", False, None), "device_id": ("text", False, None),
    "method": ("text", False, None), "path": ("text", False, None),
    "entity": ("text", False, None), "entity_key": ("text", False, None),
    "base_version": ("text", False, None), "captured_at": ("text", False, None),
    "received_at": ("text", False, "current_timestamp"), "state": ("text", True, "'applied'"),
    "status_code": ("bigint", False, None), "response_body": ("text", False, None),
    "attempts": ("bigint", False, "1"),
}


def apply_sync_changes(conn) -> None:
    for statement in MIGRATION_STATEMENTS:
        conn.execute(statement)

    rows = conn.execute(
        "SELECT column_name, data_type, is_nullable, column_default FROM information_schema.columns "
        "WHERE table_schema = current_schema() AND table_name = ? ORDER BY ordinal_position",
        ("sync_changes",),
    ).fetchall()
    actual = {}
    for r in rows:
        default = r["column_default"]
        actual[str(r["column_name"])] = (str(r["data_type"]).lower(), str(r["is_nullable"]).upper() == "NO",
                                         None if default is None else str(default).lower())
    missing = sorted(set(_EXPECTED_COLUMNS) - set(actual))
    wrong = {}
    for name, (typ, req, default_fragment) in _EXPECTED_COLUMNS.items():
        if name not in actual:
            continue
        a_typ, a_req, a_default = actual[name]
        if name == "id":
            default_ok = True  # identity columns report no default or a generated one
        elif default_fragment is None:
            default_ok = a_default is None
        else:
            default_ok = a_default is not None and default_fragment in a_default
        if (a_typ, a_req) != (typ, req) or not default_ok:
            wrong[name] = {"actual": actual[name], "expected": (typ, req, default_fragment)}
    if missing or wrong or set(actual) != set(_EXPECTED_COLUMNS):
        raise RuntimeError(f"sync_changes columns incompatible: missing={missing}, wrong={wrong}")

    fk_rows = conn.execute(
        "SELECT kcu.column_name FROM information_schema.table_constraints tc "
        "JOIN information_schema.key_column_usage kcu ON tc.constraint_name = kcu.constraint_name AND tc.constraint_schema = kcu.constraint_schema "
        "WHERE tc.constraint_type = 'FOREIGN KEY' AND tc.table_schema = current_schema() AND tc.table_name = ?",
        ("sync_changes",),
    ).fetchall()
    if fk_rows:
        raise RuntimeError("sync_changes foreign keys incompatible: source declares none")

    unique_rows = conn.execute(
        "SELECT tc.constraint_name, kcu.column_name, kcu.ordinal_position "
        "FROM information_schema.table_constraints tc "
        "JOIN information_schema.key_column_usage kcu ON tc.constraint_name = kcu.constraint_name AND tc.constraint_schema = kcu.constraint_schema "
        "WHERE tc.constraint_type = 'UNIQUE' AND tc.table_schema = current_schema() AND tc.table_name = ? "
        "ORDER BY tc.constraint_name, kcu.ordinal_position",
        ("sync_changes",),
    ).fetchall()
    uniques: dict[str, list[str]] = {}
    for r in unique_rows:
        uniques.setdefault(str(r["constraint_name"]), []).append(str(r["column_name"]))
    if list(uniques.values()) != [["school_id", "change_id"]]:
        raise RuntimeError(f"sync_changes unique constraints incompatible: {uniques}")

    check_rows = conn.execute(
        "SELECT conname FROM pg_constraint WHERE conrelid = 'sync_changes'::regclass AND contype = 'c'"
    ).fetchall()
    if check_rows:
        raise RuntimeError("sync_changes CHECK constraints incompatible: unexpected CHECK constraint")

    unique_constraint_name = next(iter(uniques))
    index_rows = conn.execute(
        "SELECT indexname, indexdef FROM pg_indexes WHERE schemaname = current_schema() AND tablename = ?",
        ("sync_changes",),
    ).fetchall()
    indexes = {str(r["indexname"]): str(r["indexdef"]).lower().replace('"', "") for r in index_rows}
    if set(indexes) != {"sync_changes_pkey", unique_constraint_name, "idx_sync_changes_school"}:
        raise RuntimeError(f"sync_changes indexes incompatible: {sorted(indexes)}")
    school_idx = indexes["idx_sync_changes_school"]
    if "unique" in school_idx or "(school_id, received_at)" not in school_idx:
        raise RuntimeError("sync_changes school lookup index is incompatible")

    trigger_rows = conn.execute(
        "SELECT trigger_name FROM information_schema.triggers WHERE trigger_schema = current_schema() AND event_object_table = ?",
        ("sync_changes",),
    ).fetchall()
    if trigger_rows:
        raise RuntimeError(f"sync_changes triggers incompatible: {sorted(str(r['trigger_name']) for r in trigger_rows)}")


def migration() -> PostgresMigration:
    return PostgresMigration(version=MIGRATION_VERSION, name=MIGRATION_NAME,
                             apply=apply_sync_changes, source=MIGRATION_SOURCE)
