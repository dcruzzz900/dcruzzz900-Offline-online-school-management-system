"""PostgreSQL-native migration 100: create the standalone security_events table.

The source definition, index and append-only triggers were reviewed against
postgres_effective_schema_snapshot.json. The table has no foreign-key
dependencies, making it a suitable first table-creation migration. It is not
wired into the active Flask/SQLite startup path.
"""
from __future__ import annotations

from postgres_migrations import PostgresMigration


MIGRATION_VERSION = 100
MIGRATION_NAME = "create_security_events"

# Keep the timestamp as TEXT to match the current application schema and retain
# its UTC ISO-8601-Z representation. Do not change this to TIMESTAMPTZ until all
# application readers/writers have been audited for the resulting type change.
MIGRATION_STATEMENTS = (
    r'''CREATE TABLE IF NOT EXISTS security_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_name TEXT NOT NULL,
    actor_user_id BIGINT,
    actor_role TEXT,
    actor_name TEXT,
    school_id BIGINT,
    tenant_id TEXT,
    resource_type TEXT,
    resource_id BIGINT,
    decision TEXT,
    details TEXT,
    request_id TEXT,
    created_at TEXT DEFAULT to_char(
        clock_timestamp() AT TIME ZONE 'UTC',
        'YYYY-MM-DD"T"HH24:MI:SS"Z"'
    )''',
    "CREATE INDEX IF NOT EXISTS idx_security_events_school_time ON security_events (school_id, created_at)",
    r'''CREATE OR REPLACE FUNCTION app_reject_immutable_row()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION '%', TG_ARGV[0] USING ERRCODE = '55000';
END;
$$''',
    "DROP TRIGGER IF EXISTS trg_security_events_no_delete ON security_events",
    "CREATE TRIGGER trg_security_events_no_delete BEFORE DELETE ON security_events FOR EACH ROW EXECUTE FUNCTION app_reject_immutable_row('Audit history is append-only')",
    "DROP TRIGGER IF EXISTS trg_security_events_no_update ON security_events",
    "CREATE TRIGGER trg_security_events_no_update BEFORE UPDATE ON security_events FOR EACH ROW EXECUTE FUNCTION app_reject_immutable_row('Audit history is append-only')",
)
MIGRATION_SOURCE = ";\n\n".join(MIGRATION_STATEMENTS)

_EXPECTED_COLUMNS = {
    "id": "bigint",
    "event_name": "text",
    "actor_user_id": "bigint",
    "actor_role": "text",
    "actor_name": "text",
    "school_id": "bigint",
    "tenant_id": "text",
    "resource_type": "text",
    "resource_id": "bigint",
    "decision": "text",
    "details": "text",
    "request_id": "text",
    "created_at": "text",
}


def apply_security_events(conn) -> None:
    """Create security_events if absent, then fail if its shape is incompatible."""
    for statement in MIGRATION_STATEMENTS:
        conn.execute(statement)
    rows = conn.execute(
        "SELECT column_name, data_type FROM information_schema.columns "
        "WHERE table_schema = current_schema() AND table_name = ? "
        "ORDER BY ordinal_position",
        ("security_events",),
    ).fetchall()
    actual = {str(row["column_name"]): str(row["data_type"]).lower() for row in rows}
    missing = sorted(set(_EXPECTED_COLUMNS) - set(actual))
    wrong = {
        name: {"actual": actual[name], "expected": expected}
        for name, expected in _EXPECTED_COLUMNS.items()
        if name in actual and actual[name] != expected
    }
    if missing or wrong:
        raise RuntimeError(
            "security_events schema is incompatible; "
            f"missing columns={missing}, incompatible types={wrong}"
        )

    index_row = conn.execute(
        "SELECT indexdef FROM pg_indexes "
        "WHERE schemaname = current_schema() AND indexname = ?",
        ("idx_security_events_school_time",),
    ).fetchone()
    if index_row is None:
        raise RuntimeError("security_events school/time index was not created")
    index_definition = str(index_row["indexdef"]).lower().replace('"', "")
    if "unique index" in index_definition or "(school_id, created_at)" not in index_definition:
        raise RuntimeError("security_events school/time index has an incompatible definition")


def migration() -> PostgresMigration:
    return PostgresMigration(
        version=MIGRATION_VERSION,
        name=MIGRATION_NAME,
        apply=apply_security_events,
        source=MIGRATION_SOURCE,
    )
