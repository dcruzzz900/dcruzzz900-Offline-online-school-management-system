import pytest

from postgres_migration_137_parent_consent_events import (
    MIGRATION_NAME, MIGRATION_SOURCE, MIGRATION_VERSION,
    apply_parent_consent_events, migration,
)
from postgres_migration_registry import POSTGRES_MIGRATIONS


class Result:
    def __init__(self, rows): self.rows = rows
    def fetchall(self): return self.rows
    def fetchone(self): return self.rows[0] if self.rows else None


class FakeConnection:
    def __init__(self, dependency_types=None, columns=None, fks=None, constraints=None, indexes=None, triggers=None):
        self.dependency_types = dependency_types or {"schools": "integer", "students": "integer", "parent_accounts": "bigint"}
        expected = {
            "id": ("bigint", True), "school_id": ("integer", True), "parent_id": ("bigint", True),
            "student_id": ("integer", True), "action": ("text", True), "policy_version": ("text", False),
            "created_at": ("text", False), "tenant_id": ("text", False),
        }
        self.columns = columns if columns is not None else [
            {"column_name": n, "data_type": t, "is_nullable": "NO" if required else "YES"}
            for n, (t, required) in expected.items()
        ]
        self.fks = fks if fks is not None else [
            {"column_name": "school_id", "foreign_table_name": "schools", "foreign_column_name": "id"},
            {"column_name": "parent_id", "foreign_table_name": "parent_accounts", "foreign_column_name": "id"},
            {"column_name": "student_id", "foreign_table_name": "students", "foreign_column_name": "id"},
        ]
        self.constraints = constraints if constraints is not None else [{"constraint_name": "parent_consent_events_action_check", "constraint_type": "CHECK"}]
        self.indexes = indexes if indexes is not None else [
            {"indexname": "parent_consent_events_pkey", "indexdef": "CREATE UNIQUE INDEX parent_consent_events_pkey ON public.parent_consent_events USING btree (id)"}
        ]
        self.triggers = triggers if triggers is not None else [{"trigger_name": "trg_parent_consent_events_tenant_stamp_pg"}]
        self.calls = []

    def execute(self, sql, params=()):
        self.calls.append((sql, params))
        if "information_schema.columns" in sql and params and params[0] in self.dependency_types:
            return Result([{"column_name": "id", "data_type": self.dependency_types[params[0]]}])
        if "information_schema.columns" in sql:
            return Result(self.columns)
        if "information_schema.table_constraints" in sql and "JOIN" in sql:
            return Result(self.fks)
        if "information_schema.table_constraints" in sql:
            return Result(self.constraints)
        if "FROM pg_indexes" in sql:
            return Result(self.indexes)
        if "information_schema.triggers" in sql:
            return Result(self.triggers)
        return Result([])


def test_registry_and_migration_identity():
    assert MIGRATION_VERSION == 137
    assert MIGRATION_NAME == "create_parent_consent_events"
    assert [item.version for item in POSTGRES_MIGRATIONS] == list(range(100, 188))
    assert next(item for item in POSTGRES_MIGRATIONS if item.version == 137).name == MIGRATION_NAME
    assert migration().version == 137


def test_ddl_preserves_relationships_action_check_and_tenant_trigger():
    sql = MIGRATION_SOURCE.lower()
    for fragment in (
        "id bigint generated by default as identity primary key", "school_id integer not null",
        "parent_id bigint not null", "student_id integer not null",
        "check (action in ('granted', 'withdrawn'))", "created_at text default current_timestamp",
        "references schools(id)", "references parent_accounts(id)", "references students(id)",
        "after insert on parent_consent_events", "new.tenant_id is null or new.tenant_id = ''",
    ):
        assert fragment in sql
    assert "create index" not in sql


def test_apply_executes_and_validates_migration():
    conn = FakeConnection()
    apply_parent_consent_events(conn)
    assert len([call for call in conn.calls if call[0] in MIGRATION_SOURCE.split(";\n\n")]) == len(MIGRATION_SOURCE.split(";\n\n"))


@pytest.mark.parametrize("dependency,wrong_type", [("schools", "bigint"), ("students", "bigint"), ("parent_accounts", "integer")])
def test_apply_rejects_incompatible_dependency_key_types(dependency, wrong_type):
    types = {"schools": "integer", "students": "integer", "parent_accounts": "bigint"}
    types[dependency] = wrong_type
    with pytest.raises(RuntimeError, match="requires"):
        apply_parent_consent_events(FakeConnection(dependency_types=types))


def test_apply_rejects_missing_foreign_key():
    with pytest.raises(RuntimeError, match="foreign keys"):
        apply_parent_consent_events(FakeConnection(fks=[]))


def test_apply_rejects_missing_action_check():
    with pytest.raises(RuntimeError, match="CHECK constraint"):
        apply_parent_consent_events(FakeConnection(constraints=[]))


def test_apply_rejects_missing_tenant_trigger():
    with pytest.raises(RuntimeError, match="triggers"):
        apply_parent_consent_events(FakeConnection(triggers=[]))
