"""PostgreSQL-native migration 136: parent_accounts.

Ports parent accounts, the school relationship, school-scoped username
uniqueness, and the source tenant-stamping trigger. This migration remains
separate from SQLite startup.
"""
from __future__ import annotations

from postgres_migrations import PostgresMigration

MIGRATION_VERSION = 136
MIGRATION_NAME = "create_parent_accounts"

MIGRATION_STATEMENTS = (
    """CREATE TABLE IF NOT EXISTS parent_accounts (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        school_id INTEGER NOT NULL,
        tenant_id TEXT NOT NULL,
        name TEXT NOT NULL,
        username TEXT NOT NULL,
        email TEXT,
        phone TEXT,
        password_hash TEXT NOT NULL,
        is_active BIGINT NOT NULL DEFAULT 1,
        last_notification_seen_id BIGINT DEFAULT 0,
        created_at TEXT DEFAULT CURRENT_TIMESTAMP,
        account_status TEXT DEFAULT 'active',
        signup_status TEXT DEFAULT 'approved',
        photo_filename TEXT,
        date_of_birth TEXT,
        gender TEXT,
        CONSTRAINT uq_parent_accounts_school_username UNIQUE (school_id, username),
        CONSTRAINT fk_parent_accounts_school FOREIGN KEY (school_id) REFERENCES schools(id)
    )""",
    """CREATE OR REPLACE FUNCTION stamp_parent_accounts_tenant()
    RETURNS trigger LANGUAGE plpgsql AS $$
    BEGIN
        -- The source declares tenant_id NOT NULL but stamps an empty string.
        IF NEW.tenant_id = '' THEN
            UPDATE parent_accounts
            SET tenant_id = (SELECT tenant_id FROM schools WHERE id = NEW.school_id)
            WHERE id = NEW.id;
        END IF;
        RETURN NEW;
    END;
    $$""",
    "DROP TRIGGER IF EXISTS trg_parent_accounts_tenant_stamp_pg ON parent_accounts",
    "CREATE TRIGGER trg_parent_accounts_tenant_stamp_pg AFTER INSERT ON parent_accounts FOR EACH ROW EXECUTE FUNCTION stamp_parent_accounts_tenant()",
)
MIGRATION_SOURCE = ";\n\n".join(MIGRATION_STATEMENTS)

_EXPECTED_COLUMNS = {
    "id": ("bigint", True),
    "school_id": ("integer", True),
    "tenant_id": ("text", True),
    "name": ("text", True),
    "username": ("text", True),
    "email": ("text", False),
    "phone": ("text", False),
    "password_hash": ("text", True),
    "is_active": ("bigint", True),
    "last_notification_seen_id": ("bigint", False),
    "created_at": ("text", False),
    "account_status": ("text", False),
    "signup_status": ("text", False),
    "photo_filename": ("text", False),
    "date_of_birth": ("text", False),
    "gender": ("text", False),
}
_EXPECTED_TRIGGERS = {"trg_parent_accounts_tenant_stamp_pg"}


def apply_parent_accounts(conn) -> None:
    school_row = conn.execute(
        "SELECT column_name, data_type FROM information_schema.columns "
        "WHERE table_schema = current_schema() AND table_name = ? AND column_name = ?",
        ("schools", "id"),
    ).fetchone()
    if school_row is None or str(school_row["data_type"]).lower() != "integer":
        raise RuntimeError("parent_accounts requires schools.id INTEGER")

    for statement in MIGRATION_STATEMENTS:
        conn.execute(statement)

    rows = conn.execute(
        "SELECT column_name, data_type, is_nullable FROM information_schema.columns "
        "WHERE table_schema = current_schema() AND table_name = ? ORDER BY ordinal_position",
        ("parent_accounts",),
    ).fetchall()
    actual = {
        str(row["column_name"]): (
            str(row["data_type"]).lower(),
            str(row["is_nullable"]).upper() == "NO",
        )
        for row in rows
    }
    missing = sorted(set(_EXPECTED_COLUMNS) - set(actual))
    wrong = {
        name: {"actual": actual[name], "expected": expected}
        for name, expected in _EXPECTED_COLUMNS.items()
        if name in actual and actual[name] != expected
    }
    if missing or wrong or set(actual) != set(_EXPECTED_COLUMNS):
        raise RuntimeError(f"parent_accounts columns incompatible: missing={missing}, wrong={wrong}")

    fk_rows = conn.execute(
        "SELECT kcu.column_name, ccu.table_name AS foreign_table_name, "
        "ccu.column_name AS foreign_column_name "
        "FROM information_schema.table_constraints tc "
        "JOIN information_schema.key_column_usage kcu "
        "ON tc.constraint_name = kcu.constraint_name AND tc.constraint_schema = kcu.constraint_schema "
        "JOIN information_schema.constraint_column_usage ccu "
        "ON ccu.constraint_name = tc.constraint_name AND ccu.constraint_schema = tc.constraint_schema "
        "WHERE tc.constraint_type = 'FOREIGN KEY' AND tc.table_schema = current_schema() "
        "AND tc.table_name = ?",
        ("parent_accounts",),
    ).fetchall()
    actual_fks = {
        (str(row["column_name"]), str(row["foreign_table_name"]), str(row["foreign_column_name"]))
        for row in fk_rows
    }
    if actual_fks != {("school_id", "schools", "id")}:
        raise RuntimeError(f"parent_accounts foreign keys incompatible: {sorted(actual_fks)}")

    index_rows = conn.execute(
        "SELECT indexname, indexdef FROM pg_indexes "
        "WHERE schemaname = current_schema() AND tablename = ?",
        ("parent_accounts",),
    ).fetchall()
    indexes = {
        str(row["indexname"]): str(row["indexdef"]).lower().replace('"', "")
        for row in index_rows
    }
    expected_indexes = {"parent_accounts_pkey", "parent_accounts_school_id_username_key"}
    if set(indexes) != expected_indexes:
        raise RuntimeError(f"parent_accounts indexes incompatible: {sorted(indexes)}")
    unique_index = indexes["parent_accounts_school_id_username_key"]
    if "unique index" not in unique_index or "(school_id, username)" not in unique_index:
        raise RuntimeError("parent_accounts school/username unique index is incompatible")

    trigger_rows = conn.execute(
        "SELECT trigger_name FROM information_schema.triggers "
        "WHERE trigger_schema = current_schema() AND event_object_table = ?",
        ("parent_accounts",),
    ).fetchall()
    actual_triggers = {str(row["trigger_name"]) for row in trigger_rows}
    if actual_triggers != _EXPECTED_TRIGGERS:
        raise RuntimeError(f"parent_accounts triggers incompatible: {sorted(actual_triggers)}")


def migration() -> PostgresMigration:
    return PostgresMigration(
        version=MIGRATION_VERSION,
        name=MIGRATION_NAME,
        apply=apply_parent_accounts,
        source=MIGRATION_SOURCE,
    )
