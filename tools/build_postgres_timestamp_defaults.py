#!/usr/bin/env python3
"""Generate PostgreSQL UTC text timestamp defaults from the audited SQLite schema.

Only exact, reviewed SQLite strftime(..., 'now') defaults are converted.
The generator is offline and fails closed when the effective schema changes.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SNAPSHOT = ROOT / "postgres_effective_schema_snapshot.json"
OUTPUT = ROOT / "postgres_timestamp_defaults.sql"
EXPECTED = {
    ("attendance_audit", "server_timestamp"),
    ("result_publication_audit", "server_timestamp"),
    ("student_ai_consent_events", "server_timestamp"),
    ("student_status_history", "server_timestamp"),
}
SOURCE_DEFAULT = "strftime('%Y-%m-%dT%H:%M:%SZ','now')"
PG_DEFAULT = "(to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD\"T\"HH24:MI:SS\"Z\"'))"


def generate(snapshot: dict) -> str:
    found = set()
    for table in snapshot.get("tables", []):
        for column in table.get("columns", []):
            if column.get("default") == SOURCE_DEFAULT:
                if column.get("type", "").upper() != "TEXT":
                    raise ValueError(f"{table['name']}.{column['name']} must remain TEXT")
                found.add((table["name"], column["name"]))
    if found != EXPECTED:
        missing, extra = sorted(EXPECTED - found), sorted(found - EXPECTED)
        raise ValueError(f"Timestamp default inventory changed; missing={missing}, extra={extra}")
    lines = [
        "-- Generated by tools/build_postgres_timestamp_defaults.py",
        "-- Converts four audited SQLite UTC ISO-text defaults to PostgreSQL.",
        "-- Apply only after these tables exist and their timestamp columns are TEXT.",
        "-- clock_timestamp() is used so the default is evaluated per inserted row.",
        "",
    ]
    for table, column in sorted(found):
        lines += [
            f"ALTER TABLE {table}",
            f"    ALTER COLUMN {column} SET DEFAULT {PG_DEFAULT};",
            "",
        ]
    return "\n".join(lines)


def main() -> None:
    snapshot = json.loads(SNAPSHOT.read_text())
    sql = generate(snapshot)
    OUTPUT.write_text(sql)
    print(f"Generated UTC text timestamp defaults for {len(EXPECTED)} columns")


if __name__ == "__main__":
    main()
