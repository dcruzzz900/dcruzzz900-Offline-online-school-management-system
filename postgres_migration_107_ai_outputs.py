    "DROP TRIGGER IF EXISTS trg_ai_outputs_tenant_stamp_pg ON ai_outputs",
    "CREATE TRIGGER trg_ai_outputs_tenant_stamp_pg BEFORE INSERT ON ai_outputs FOR EACH ROW EXECUTE FUNCTION app_stamp_tenant_ai_outputs()",
