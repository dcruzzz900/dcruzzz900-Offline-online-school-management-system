import pytest

from postgres_migration_166_school_days_v2 import (
    MIGRATION_NAME, MIGRATION_SOURCE, MIGRATION_STATEMENTS, MIGRATION_VERSION,
    _EXPECTED_COLUMNS, apply_school_days_v2, migration,
)
from postgres_migration_registry import POSTGRES_MIGRATIONS


class Result:
    def __init__(self, rows): self.rows = rows
    def fetchall(self): return self.rows
    def fetchone(self): return self.rows[0] if self.rows else None


class FakeConnection:
    def __init__(self, columns=None, fks=None, uniques=None, indexes=None, triggers=None, school_id_type="integer"):
        self.columns = columns if columns is not None else [
            {"column_name": n, "data_type": typ, "is_nullable": "NO" if req else "YES"}
            for n, (typ, req) in _EXPECTED_COLUMNS.items()
        ]
        self.fks = fks if fks is not None else [
            {"column_name": "school_id", "foreign_table_name": "schools", "foreign_column_name": "id"}]
        self.uniques = uniques if uniques is not None else [
            {"constraint_name": "uq_school_days_v2_tenant_school_day_code", "column_name": c, "ordinal_position": i}
            for i, c in enumerate(("tenant_id", "school_id", "day_code"), 1)
        ]
        self.indexes = indexes if indexes is not None else [
            {"indexname": "school_days_v2_pkey", "indexdef": "CREATE UNIQUE INDEX school_days_v2_pkey ON public.school_days_v2 USING btree (id)"},
            {"indexname": "uq_school_days_v2_tenant_school_day_code", "indexdef": "CREATE UNIQUE INDEX uq_school_days_v2_tenant_school_day_code ON public.school_days_v2 USING btree (tenant_id, school_id, day_code)"},
            {"indexname": "idx_school_days_v2_client_uuid", "indexdef": "CREATE UNIQUE INDEX idx_school_days_v2_client_uuid ON public.school_days_v2 USING btree (client_uuid) WHERE (client_uuid IS NOT NULL)"},
        ]
        self.triggers = triggers if triggers is not None else [
            {"trigger_name": "trg_school_days_v2_sync_defaults"}, {"trigger_name": "trg_school_days_v2_sync_touch"}]
        self.school_id_type = school_id_type
        self.calls = []

    def execute(self, sql, params=()):
        self.calls.append((sql, params))
        if "information_schema.columns" in sql and "schools" in params:
            return Result([{"column_name": "id", "data_type": self.school_id_type}])
        if "information_schema.columns" in sql: return Result(self.columns)
        if "constraint_type = 'FOREIGN KEY'" in sql: return Result(self.fks)
        if "constraint_type = 'UNIQUE'" in sql: return Result(self.uniques)
        if "FROM pg_indexes" in sql: return Result(self.indexes)
        if "information_schema.triggers" in sql: return Result(self.triggers)
        return Result([])


def test_registry_and_migration_identity():
    assert MIGRATION_VERSION == 166
    assert MIGRATION_NAME == "create_school_days_v2"
    assert POSTGRES_MIGRATIONS[-22].version == 166
    assert [m.version for m in POSTGRES_MIGRATIONS] == list(range(100, 188))
    assert migration().version == 166


def test_effective_sqlite_schema_is_preserved():
    assert list(_EXPECTED_COLUMNS) == [
        "id", "tenant_id", "school_id", "day_name", "day_code", "day_order",
        "is_active", "client_uuid", "updated_at", "is_deleted",
    ]
    sql = MIGRATION_SOURCE.lower()
    for fragment in (
        "id bigint generated by default as identity primary key", "tenant_id text not null",
        "school_id integer not null", "day_name text not null", "day_code text not null",
        "day_order bigint not null", "is_active bigint not null default 1", "is_deleted bigint default 0",
        "unique (tenant_id, school_id, day_code)", "references schools(id)",
        "where client_uuid is not null", "before insert", "before update",
    ):
        assert fragment in sql
    assert sql.count("references ") == 1


def test_apply_executes_every_statement_and_validates():
    conn = FakeConnection()
    apply_school_days_v2(conn)
    executed = [sql for sql, _ in conn.calls]
    for statement in MIGRATION_STATEMENTS:
        assert statement in executed


def test_rejects_incompatible_school_primary_key_type():
    with pytest.raises(RuntimeError, match="schools.id INTEGER"):
        apply_school_days_v2(FakeConnection(school_id_type="bigint"))


def test_rejects_wrong_columns():
    with pytest.raises(RuntimeError, match="columns incompatible"):
        apply_school_days_v2(FakeConnection(columns=[]))


def test_rejects_wrong_foreign_key():
    with pytest.raises(RuntimeError, match="foreign keys incompatible"):
        apply_school_days_v2(FakeConnection(fks=[]))


def test_rejects_wrong_unique_constraint():
    with pytest.raises(RuntimeError, match="unique constraints incompatible"):
        apply_school_days_v2(FakeConnection(uniques=[]))
    reordered = [{"constraint_name": "uq_x", "column_name": c, "ordinal_position": i}
                 for i, c in enumerate(("school_id", "tenant_id", "day_code"), 1)]
    with pytest.raises(RuntimeError, match="unique constraints incompatible"):
        apply_school_days_v2(FakeConnection(uniques=reordered))


def test_rejects_wrong_indexes():
    with pytest.raises(RuntimeError, match="indexes incompatible"):
        apply_school_days_v2(FakeConnection(indexes=[]))


def test_rejects_non_partial_client_uuid_index():
    bad = [
        {"indexname": "school_days_v2_pkey", "indexdef": "x"},
        {"indexname": "uq_school_days_v2_tenant_school_day_code", "indexdef": "x"},
        {"indexname": "idx_school_days_v2_client_uuid", "indexdef": "CREATE INDEX i ON t USING btree (client_uuid)"},
    ]
    with pytest.raises(RuntimeError, match="partial index"):
        apply_school_days_v2(FakeConnection(indexes=bad))


def test_rejects_wrong_triggers():
    with pytest.raises(RuntimeError, match="triggers incompatible"):
        apply_school_days_v2(FakeConnection(triggers=[]))
