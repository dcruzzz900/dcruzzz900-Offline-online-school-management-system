"""PostgreSQL-native migration 106: ai_audit_log.

Faithful port of the effective SQLite table, its school/time lookup index,
and tenant-stamping trigger. The source table declares no foreign keys.
Timestamp values remain TEXT for compatibility with existing application data.
The tenant trigger reads schools.tenant_id when the incoming value is NULL/empty.
"""
from __future__ import annotations

from postgres_migrations import PostgresMigration

MIGRATION_VERSION = 106
MIGRATION_NAME = "create_ai_audit_log"

MIGRATION_STATEMENTS = (
    r'''CREATE TABLE IF NOT EXISTS ai_audit_log (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        school_id BIGINT NOT NULL,
        user_id BIGINT,
        feature TEXT NOT NULL,
        student_id BIGINT,
        consent_status TEXT,
        data_scope TEXT,
        action TEXT NOT NULL,
        request_summary TEXT,
        output_summary TEXT,
        created_at TEXT DEFAULT CURRENT_TIMESTAMP,
        tenant_id TEXT
    )''',
    "CREATE INDEX IF NOT EXISTS idx_ai_audit_school_time ON ai_audit_log (school_id, created_at)",
    r'''CREATE OR REPLACE FUNCTION app_stamp_tenant_ai_audit_log()
        RETURNS trigger LANGUAGE plpgsql AS $$
        DECLARE v_tenant_id TEXT;
        BEGIN
            IF NEW.tenant_id IS NULL OR NEW.tenant_id = '' THEN
                SELECT tenant_id INTO v_tenant_id FROM schools WHERE id = NEW.school_id;
                NEW.tenant_id := v_tenant_id;
            END IF;
            RETURN NEW;
        END;
        $$''',
    "DROP TRIGGER IF EXISTS trg_ai_audit_log_tenant_stamp_pg ON ai_audit_log",
    "CREATE TRIGGER trg_ai_audit_log_tenant_stamp_pg BEFORE INSERT ON ai_audit_log FOR EACH ROW EXECUTE FUNCTION app_stamp_tenant_ai_audit_log()",
)
MIGRATION_SOURCE = ";\n\n".join(MIGRATION_STATEMENTS)

_EXPECTED_COLUMNS = {
    "id": ("bigint", True), "school_id": ("bigint", True), "user_id": ("bigint", False),
    "feature": ("text", True), "student_id": ("bigint", False), "consent_status": ("text", False),
    "data_scope": ("text", False), "action": ("text", True), "request_summary": ("text", False),
    "output_summary": ("text", False), "created_at": ("text", False), "tenant_id": ("text", False),
}


def apply_ai_audit_log(conn) -> None:
    for statement in MIGRATION_STATEMENTS:
        conn.execute(statement)

    rows = conn.execute(
        "SELECT column_name, data_type, is_nullable FROM information_schema.columns "
        "WHERE table_schema = current_schema() AND table_name = ? ORDER BY ordinal_position",
        ("ai_audit_log",),
    ).fetchall()
    actual = {
        str(row["column_name"]): (str(row["data_type"]).lower(), str(row["is_nullable"]).upper() == "NO")
        for row in rows
    }
    missing = sorted(set(_EXPECTED_COLUMNS) - set(actual))
    wrong = {name: {"actual": actual[name], "expected": expected}
             for name, expected in _EXPECTED_COLUMNS.items() if name in actual and actual[name] != expected}
    if missing or wrong:
        raise RuntimeError(f"ai_audit_log schema is incompatible; missing columns={missing}, incompatible columns={wrong}")

    fk = conn.execute(
        "SELECT 1 FROM information_schema.table_constraints WHERE table_schema = current_schema() "
        "AND table_name = ? AND constraint_type = 'FOREIGN KEY' LIMIT 1", ("ai_audit_log",),
    ).fetchone()
    if fk is not None:
        raise RuntimeError("ai_audit_log has unexpected foreign-key constraints")

    indexes = conn.execute(
        "SELECT indexname FROM pg_indexes WHERE schemaname = current_schema() AND tablename = ?", ("ai_audit_log",),
    ).fetchall()
    names = {str(row["indexname"]) for row in indexes}
    if names != {"ai_audit_log_pkey", "idx_ai_audit_school_time"}:
        raise RuntimeError(f"ai_audit_log indexes are incompatible: {sorted(names)}")

    triggers = conn.execute(
        "SELECT trigger_name FROM information_schema.triggers WHERE trigger_schema = current_schema() AND event_object_table = ?",
        ("ai_audit_log",),
    ).fetchall()
    trigger_names = {str(row["trigger_name"]) for row in triggers}
    if "trg_ai_audit_log_tenant_stamp_pg" not in trigger_names:
        raise RuntimeError("ai_audit_log tenant-stamping trigger is missing")


def migration() -> PostgresMigration:
    return PostgresMigration(version=MIGRATION_VERSION, name=MIGRATION_NAME,
                             apply=apply_ai_audit_log, source=MIGRATION_SOURCE)
