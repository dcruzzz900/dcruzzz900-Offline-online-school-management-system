#!/usr/bin/env python3
"""Generate reviewed PostgreSQL billing-payment history capture triggers."""
from __future__ import annotations
import argparse, json, re
from pathlib import Path

EXPECTED = {
    'trg_billing_payment_insert_history',
    'trg_billing_payment_update_history',
}
IDENT = re.compile(r'^[a-z][a-z0-9_]*$')
def qi(value: str) -> str:
    if not IDENT.fullmatch(value):
        raise ValueError(f'Unsafe SQL identifier: {value!r}')
    return '"' + value + '"'

def validate(plan: dict, snapshot: dict) -> None:
    items = [x for x in plan['triggers'] if x.get('category') == 'audit_or_history_capture']
    if len(items) != 2 or {x.get('name') for x in items} != EXPECTED:
        raise ValueError('Expected exactly the two reviewed billing payment history triggers')
    tables = {t['name']: {c['name'] for c in t['columns']} for t in snapshot['tables']}
    required = {
        'billing_payments': {'id','school_id','invoice_id','status','amount_ngn','payment_reference','confirmed_by'},
        'billing_payment_history': {'payment_id','school_id','invoice_id','action','old_status','new_status','old_amount_ngn','new_amount_ngn','old_reference','new_reference','actor'},
    }
    for table, cols in required.items():
        if table not in tables or not cols <= tables[table]:
            raise ValueError(f'{table} missing required columns: {sorted(cols - tables.get(table, set()))}')
    by_name = {x['name']: x for x in items}
    ins = re.sub(r'\s+', ' ', by_name['trg_billing_payment_insert_history']['source_sql']).lower()
    upd = re.sub(r'\s+', ' ', by_name['trg_billing_payment_update_history']['source_sql']).lower()
    for token in ('after insert on billing_payments','new.id','new.school_id','new.invoice_id',"'created'",'new.status','new.amount_ngn','new.payment_reference','new.confirmed_by'):
        if token not in ins: raise ValueError(f'Unexpected insert-history source SQL; missing {token!r}')
    for token in ('after update of status,amount_ngn,payment_reference,provider,invoice_id on billing_payments',
                  'old.status is not new.status','old.amount_ngn is not new.amount_ngn',
                  'old.payment_reference is not new.payment_reference','old.invoice_id is not new.invoice_id',
                  "new.status='confirmed'", "'reversed','refunded','cancelled'", 'old.amount_ngn','new.amount_ngn'):
        if token not in upd: raise ValueError(f'Unexpected update-history source SQL; missing {token!r}')

def generate(plan: dict, snapshot: dict) -> str:
    validate(plan, snapshot)
    return '''-- Generated by tools/build_postgres_audit_history.py
-- Reviewed port of the two SQLite billing payment history capture triggers.
-- History inserts run in the same transaction as the payment write.
-- Apply only after reviewing POSTGRES_AUDIT_HISTORY.md.

CREATE OR REPLACE FUNCTION app_capture_billing_payment_history()
RETURNS trigger
LANGUAGE plpgsql
AS $function$
BEGIN
  IF TG_OP = 'INSERT' THEN
    INSERT INTO billing_payment_history
      (payment_id, school_id, invoice_id, action, old_status, new_status,
       new_amount_ngn, new_reference, actor)
    VALUES
      (NEW.id, NEW.school_id, NEW.invoice_id, 'created', NULL, NEW.status,
       NEW.amount_ngn, NEW.payment_reference, COALESCE(NEW.confirmed_by, 'system'));
    RETURN NEW;
  END IF;

  -- Mirrors SQLite's UPDATE OF list and WHEN predicate. provider-only changes
  -- intentionally do not create a history row; provider is in UPDATE OF but
  -- is absent from the original WHEN comparison.
  IF OLD.status IS DISTINCT FROM NEW.status
     OR OLD.amount_ngn IS DISTINCT FROM NEW.amount_ngn
     OR OLD.payment_reference IS DISTINCT FROM NEW.payment_reference
     OR OLD.invoice_id IS DISTINCT FROM NEW.invoice_id THEN
    INSERT INTO billing_payment_history
      (payment_id, school_id, invoice_id, action, old_status, new_status,
       old_amount_ngn, new_amount_ngn, old_reference, new_reference, actor)
    VALUES
      (NEW.id, NEW.school_id, NEW.invoice_id,
       CASE
         WHEN OLD.status IS DISTINCT FROM NEW.status AND NEW.status = 'confirmed' THEN 'confirmed'
         WHEN OLD.status IS DISTINCT FROM NEW.status AND NEW.status IN ('reversed', 'refunded', 'cancelled') THEN 'status_changed'
         ELSE 'changed'
       END,
       OLD.status, NEW.status, OLD.amount_ngn, NEW.amount_ngn,
       OLD.payment_reference, NEW.payment_reference,
       COALESCE(NEW.confirmed_by, 'system'));
  END IF;
  RETURN NEW;
END;
$function$;

DROP TRIGGER IF EXISTS trg_billing_payment_insert_history_pg ON billing_payments;
CREATE TRIGGER trg_billing_payment_insert_history_pg
AFTER INSERT ON billing_payments
FOR EACH ROW EXECUTE FUNCTION app_capture_billing_payment_history();

DROP TRIGGER IF EXISTS trg_billing_payment_update_history_pg ON billing_payments;
CREATE TRIGGER trg_billing_payment_update_history_pg
AFTER UPDATE OF status, amount_ngn, payment_reference, provider, invoice_id ON billing_payments
FOR EACH ROW EXECUTE FUNCTION app_capture_billing_payment_history();
'''

def main() -> None:
    ap=argparse.ArgumentParser()
    ap.add_argument('--inventory', default='postgres_trigger_porting_plan.json')
    ap.add_argument('--snapshot', default='postgres_effective_schema_snapshot.json')
    ap.add_argument('--output', default='postgres_audit_history.sql')
    args=ap.parse_args()
    sql=generate(json.loads(Path(args.inventory).read_text()), json.loads(Path(args.snapshot).read_text()))
    Path(args.output).write_text(sql)
    print('Generated 1 PostgreSQL function and 2 billing-payment history triggers.')
if __name__ == '__main__': main()
