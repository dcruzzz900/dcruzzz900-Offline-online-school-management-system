"""PostgreSQL-native migration 187: sync_conflicts.

Ports the effective SQLite table of offline-sync conflicts (the client's
payload versus the server's, plus how and by whom it was resolved). This is
the last real table in the table-level gap report; only `schema_steps`
(SQLite's own migration bookkeeping) remains, and it is deliberately not
ported.

The source has 20 effective columns, not the 11 its original `CREATE TABLE`
shows: later migrations add `tenant_id`, `change_id`, `kind`, `sensitive`,
`reason`, `entity_key`, `resolved_by`, `method` and `path` (confirmed against the
effective schema snapshot). `postgres_tenant_triggers.sql` already defines
`app_stamp_tenant_sync_conflicts()` / `trg_sync_conflicts_tenant_stamp_pg`
(same condition and source column as SQLite), so this migration relies on it
rather than re-implementing tenant stamping, as migrations 182, 183 and 185
did. Because that file may be applied before or after this migration,
verification accepts that single trigger being present or absent and rejects
any other.

The one foreign key is `school_id` -> `schools.id`; `schools.id` is INTEGER in
`postgres_schema_base.sql`, so `school_id` stays INTEGER (checked before
creating the table, as in migration 183). Other types follow this series: `id`
is a BIGINT identity; `resolved` and `sensitive` are BIGINT DEFAULT 0;
`detected_at` is `TEXT DEFAULT CURRENT_TIMESTAMP`. Two non-unique indexes are
recreated: `idx_sync_conflicts_school (school_id, resolved)` and
`idx_sync_conflicts_change (school_id, change_id)`. The source has no UNIQUE or
CHECK constraints; verification asserts none exist. This migration does not
alter SQLite startup, SQLite migrations, or offline sync.
"""
from __future__ import annotations

from postgres_migrations import PostgresMigration

MIGRATION_VERSION = 187
MIGRATION_NAME = "create_sync_conflicts"

MIGRATION_STATEMENTS = (
    """CREATE TABLE IF NOT EXISTS sync_conflicts (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        school_id INTEGER NOT NULL,
        entity TEXT NOT NULL,
        client_uuid TEXT NOT NULL,
        device_id TEXT,
        client_payload TEXT NOT NULL,
        server_payload TEXT NOT NULL,
        detected_at TEXT DEFAULT CURRENT_TIMESTAMP,
        resolved BIGINT DEFAULT 0,
        resolved_at TEXT,
        resolution TEXT,
        tenant_id TEXT,
        change_id TEXT,
        kind TEXT,
        sensitive BIGINT DEFAULT 0,
        reason TEXT,
        entity_key TEXT,
        resolved_by TEXT,
        method TEXT,
        path TEXT,
        CONSTRAINT fk_sync_conflicts_school FOREIGN KEY (school_id) REFERENCES schools(id)
    )""",
    "CREATE INDEX IF NOT EXISTS idx_sync_conflicts_school ON sync_conflicts (school_id, resolved)",
    "CREATE INDEX IF NOT EXISTS idx_sync_conflicts_change ON sync_conflicts (school_id, change_id)",
)
MIGRATION_SOURCE = ";\n\n".join(MIGRATION_STATEMENTS)

# name -> (data_type, not_null, default fragment or None)
_EXPECTED_COLUMNS = {
    "id": ("bigint", True, None), "school_id": ("integer", True, None),
    "entity": ("text", True, None), "client_uuid": ("text", True, None),
    "device_id": ("text", False, None), "client_payload": ("text", True, None),
    "server_payload": ("text", True, None), "detected_at": ("text", False, "current_timestamp"),
    "resolved": ("bigint", False, "0"), "resolved_at": ("text", False, None),
    "resolution": ("text", False, None), "tenant_id": ("text", False, None),
    "change_id": ("text", False, None), "kind": ("text", False, None),
    "sensitive": ("bigint", False, "0"), "reason": ("text", False, None),
    "entity_key": ("text", False, None), "resolved_by": ("text", False, None),
    "method": ("text", False, None), "path": ("text", False, None),
}
_EXPECTED_FKS = {("school_id", "schools", "id")}
_ALLOWED_TRIGGERS = {"trg_sync_conflicts_tenant_stamp_pg"}


def apply_sync_conflicts(conn) -> None:
    row = conn.execute(
        "SELECT column_name, data_type FROM information_schema.columns "
        "WHERE table_schema = current_schema() AND table_name = ? AND column_name = ?",
        ("schools", "id"),
    ).fetchone()
    if row is None or str(row["data_type"]).lower() != "integer":
        raise RuntimeError("sync_conflicts requires schools.id INTEGER")

    for statement in MIGRATION_STATEMENTS:
        conn.execute(statement)

    rows = conn.execute(
        "SELECT column_name, data_type, is_nullable, column_default FROM information_schema.columns "
        "WHERE table_schema = current_schema() AND table_name = ? ORDER BY ordinal_position",
        ("sync_conflicts",),
    ).fetchall()
    actual = {}
    for r in rows:
        default = r["column_default"]
        actual[str(r["column_name"])] = (str(r["data_type"]).lower(), str(r["is_nullable"]).upper() == "NO",
                                         None if default is None else str(default).lower())
    missing = sorted(set(_EXPECTED_COLUMNS) - set(actual))
    wrong = {}
    for name, (typ, req, default_fragment) in _EXPECTED_COLUMNS.items():
        if name not in actual:
            continue
        a_typ, a_req, a_default = actual[name]
        if name == "id":
            default_ok = True  # identity columns report no default or a generated one
        elif default_fragment is None:
            default_ok = a_default is None
        else:
            default_ok = a_default is not None and default_fragment in a_default
        if (a_typ, a_req) != (typ, req) or not default_ok:
            wrong[name] = {"actual": actual[name], "expected": (typ, req, default_fragment)}
    if missing or wrong or set(actual) != set(_EXPECTED_COLUMNS):
        raise RuntimeError(f"sync_conflicts columns incompatible: missing={missing}, wrong={wrong}")

    fk_rows = conn.execute(
        "SELECT kcu.column_name, ccu.table_name AS foreign_table_name, ccu.column_name AS foreign_column_name "
        "FROM information_schema.table_constraints tc "
        "JOIN information_schema.key_column_usage kcu ON tc.constraint_name = kcu.constraint_name AND tc.constraint_schema = kcu.constraint_schema "
        "JOIN information_schema.constraint_column_usage ccu ON ccu.constraint_name = tc.constraint_name AND ccu.constraint_schema = tc.constraint_schema "
        "WHERE tc.constraint_type = 'FOREIGN KEY' AND tc.table_schema = current_schema() AND tc.table_name = ?",
        ("sync_conflicts",),
    ).fetchall()
    actual_fks = {(str(r["column_name"]), str(r["foreign_table_name"]), str(r["foreign_column_name"])) for r in fk_rows}
    if actual_fks != _EXPECTED_FKS:
        raise RuntimeError(f"sync_conflicts foreign keys incompatible: {sorted(actual_fks)}")

    unique_rows = conn.execute(
        "SELECT tc.constraint_name FROM information_schema.table_constraints tc "
        "WHERE tc.constraint_type = 'UNIQUE' AND tc.table_schema = current_schema() AND tc.table_name = ?",
        ("sync_conflicts",),
    ).fetchall()
    if unique_rows:
        raise RuntimeError("sync_conflicts unique constraints incompatible: unexpected table-level UNIQUE constraint")

    check_rows = conn.execute(
        "SELECT conname FROM pg_constraint WHERE conrelid = 'sync_conflicts'::regclass AND contype = 'c'"
    ).fetchall()
    if check_rows:
        raise RuntimeError("sync_conflicts CHECK constraints incompatible: unexpected CHECK constraint")

    index_rows = conn.execute(
        "SELECT indexname, indexdef FROM pg_indexes WHERE schemaname = current_schema() AND tablename = ?",
        ("sync_conflicts",),
    ).fetchall()
    indexes = {str(r["indexname"]): str(r["indexdef"]).lower().replace('"', "") for r in index_rows}
    if set(indexes) != {"sync_conflicts_pkey", "idx_sync_conflicts_school", "idx_sync_conflicts_change"}:
        raise RuntimeError(f"sync_conflicts indexes incompatible: {sorted(indexes)}")
    for name, cols in (("idx_sync_conflicts_school", "(school_id, resolved)"),
                       ("idx_sync_conflicts_change", "(school_id, change_id)")):
        if "unique" in indexes[name] or cols not in indexes[name]:
            raise RuntimeError(f"sync_conflicts {name} index is incompatible")

    trigger_rows = conn.execute(
        "SELECT trigger_name FROM information_schema.triggers WHERE trigger_schema = current_schema() AND event_object_table = ?",
        ("sync_conflicts",),
    ).fetchall()
    unexpected = {str(r["trigger_name"]) for r in trigger_rows} - _ALLOWED_TRIGGERS
    if unexpected:
        raise RuntimeError(f"sync_conflicts triggers incompatible: {sorted(unexpected)}")


def migration() -> PostgresMigration:
    return PostgresMigration(version=MIGRATION_VERSION, name=MIGRATION_NAME,
                             apply=apply_sync_conflicts, source=MIGRATION_SOURCE)
