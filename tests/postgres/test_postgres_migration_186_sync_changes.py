import pytest

from postgres_migration_186_sync_changes import (
    MIGRATION_NAME, MIGRATION_SOURCE, MIGRATION_STATEMENTS, MIGRATION_VERSION,
    _EXPECTED_COLUMNS, apply_sync_changes, migration,
)
from postgres_migration_registry import POSTGRES_MIGRATIONS

_DEFAULTS = {"received_at": "CURRENT_TIMESTAMP", "state": "'applied'::text", "attempts": "1"}
_UQ = "sync_changes_school_id_change_id_key"
GOOD_UNIQUES = [
    {"constraint_name": _UQ, "column_name": "school_id", "ordinal_position": 1},
    {"constraint_name": _UQ, "column_name": "change_id", "ordinal_position": 2},
]
GOOD_INDEXES = [
    {"indexname": "sync_changes_pkey", "indexdef": "CREATE UNIQUE INDEX sync_changes_pkey ON public.sync_changes USING btree (id)"},
    {"indexname": _UQ, "indexdef": f"CREATE UNIQUE INDEX {_UQ} ON public.sync_changes USING btree (school_id, change_id)"},
    {"indexname": "idx_sync_changes_school", "indexdef": "CREATE INDEX idx_sync_changes_school ON public.sync_changes USING btree (school_id, received_at)"},
]


class Result:
    def __init__(self, rows): self.rows = rows
    def fetchall(self): return self.rows
    def fetchone(self): return self.rows[0] if self.rows else None


def good_columns():
    return [
        {"column_name": n, "data_type": typ, "is_nullable": "NO" if req else "YES", "column_default": _DEFAULTS.get(n)}
        for n, (typ, req, _d) in _EXPECTED_COLUMNS.items()
    ]


class FakeConnection:
    def __init__(self, columns=None, fks=None, uniques=None, checks=None, indexes=None, triggers=None):
        self.columns = columns if columns is not None else good_columns()
        self.fks = fks or []
        self.uniques = uniques if uniques is not None else GOOD_UNIQUES
        self.checks = checks or []
        self.indexes = indexes if indexes is not None else GOOD_INDEXES
        self.triggers = triggers or []
        self.calls = []

    def execute(self, sql, params=()):
        self.calls.append((sql, params))
        if "information_schema.columns" in sql: return Result(self.columns)
        if "constraint_type = 'FOREIGN KEY'" in sql: return Result(self.fks)
        if "constraint_type = 'UNIQUE'" in sql: return Result(self.uniques)
        if "FROM pg_constraint" in sql: return Result(self.checks)
        if "FROM pg_indexes" in sql: return Result(self.indexes)
        if "information_schema.triggers" in sql: return Result(self.triggers)
        return Result([])


def test_registry_and_migration_identity():
    assert MIGRATION_VERSION == 186
    assert MIGRATION_NAME == "create_sync_changes"
    assert POSTGRES_MIGRATIONS[-2].version == 186
    assert [m.version for m in POSTGRES_MIGRATIONS] == list(range(100, 188))
    assert migration().version == 186


def test_effective_sqlite_schema_is_preserved():
    assert list(_EXPECTED_COLUMNS) == [
        "id", "change_id", "school_id", "tenant_id", "user_id", "device_id", "method", "path",
        "entity", "entity_key", "base_version", "captured_at", "received_at", "state",
        "status_code", "response_body", "attempts",
    ]
    sql = MIGRATION_SOURCE.lower()
    for fragment in (
        "id bigint generated by default as identity primary key", "change_id text not null",
        "school_id integer not null", "tenant_id text,", "user_id integer,",
        "received_at text default current_timestamp", "state text not null default 'applied'",
        "status_code bigint,", "attempts bigint default 1",
        "unique (school_id, change_id)", "idx_sync_changes_school", "(school_id, received_at)",
    ):
        assert fragment in sql
    assert "references" not in sql and "check" not in sql and "trigger" not in sql


def test_unique_is_a_table_constraint_for_on_conflict_upserts():
    assert "constraint sync_changes_school_id_change_id_key unique (school_id, change_id)" in MIGRATION_SOURCE.lower().replace("\n", " ")
    assert "create unique index" not in MIGRATION_SOURCE.lower()


def test_apply_executes_every_statement_and_validates():
    conn = FakeConnection()
    apply_sync_changes(conn)
    executed = [sql for sql, _ in conn.calls]
    for statement in MIGRATION_STATEMENTS:
        assert statement in executed


def test_rejects_wrong_columns():
    with pytest.raises(RuntimeError, match="columns incompatible"):
        apply_sync_changes(FakeConnection(columns=[]))


def test_rejects_wrong_defaults():
    for col, bad in (("state", None), ("attempts", None), ("received_at", None), ("tenant_id", "'x'::text")):
        cols = good_columns()
        for c in cols:
            if c["column_name"] == col:
                c["column_default"] = bad
        with pytest.raises(RuntimeError, match="columns incompatible"):
            apply_sync_changes(FakeConnection(columns=cols))


def test_rejects_wrong_nullability():
    cols = good_columns()
    for c in cols:
        if c["column_name"] == "change_id":
            c["is_nullable"] = "YES"
    with pytest.raises(RuntimeError, match="columns incompatible"):
        apply_sync_changes(FakeConnection(columns=cols))


def test_rejects_unexpected_foreign_key():
    with pytest.raises(RuntimeError, match="foreign keys incompatible"):
        apply_sync_changes(FakeConnection(fks=[{"column_name": "school_id"}]))


def test_rejects_missing_unique_constraint():
    with pytest.raises(RuntimeError, match="unique constraints incompatible"):
        apply_sync_changes(FakeConnection(uniques=[]))


def test_rejects_wrong_unique_columns_or_order():
    reordered = [
        {"constraint_name": _UQ, "column_name": "change_id", "ordinal_position": 1},
        {"constraint_name": _UQ, "column_name": "school_id", "ordinal_position": 2},
    ]
    with pytest.raises(RuntimeError, match="unique constraints incompatible"):
        apply_sync_changes(FakeConnection(uniques=reordered))
    with pytest.raises(RuntimeError, match="unique constraints incompatible"):
        apply_sync_changes(FakeConnection(uniques=GOOD_UNIQUES[:1]))


def test_rejects_extra_unique_constraint():
    extra = GOOD_UNIQUES + [{"constraint_name": "x", "column_name": "path", "ordinal_position": 1}]
    with pytest.raises(RuntimeError, match="unique constraints incompatible"):
        apply_sync_changes(FakeConnection(uniques=extra))


def test_rejects_unexpected_check_constraint():
    with pytest.raises(RuntimeError, match="CHECK constraints incompatible"):
        apply_sync_changes(FakeConnection(checks=[{"conname": "x"}]))


def test_rejects_wrong_indexes():
    with pytest.raises(RuntimeError, match="indexes incompatible"):
        apply_sync_changes(FakeConnection(indexes=[]))


def test_rejects_unique_or_wrong_school_index():
    for bad_def in ("CREATE UNIQUE INDEX i ON t USING btree (school_id, received_at)",
                    "CREATE INDEX i ON t USING btree (received_at, school_id)"):
        bad = [GOOD_INDEXES[0], GOOD_INDEXES[1], {"indexname": "idx_sync_changes_school", "indexdef": bad_def}]
        with pytest.raises(RuntimeError, match="school lookup index"):
            apply_sync_changes(FakeConnection(indexes=bad))


def test_rejects_unexpected_triggers():
    with pytest.raises(RuntimeError, match="triggers incompatible"):
        apply_sync_changes(FakeConnection(triggers=[{"trigger_name": "x"}]))
