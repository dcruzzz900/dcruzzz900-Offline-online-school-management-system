MIGRATION_SOURCE = ";\n\n".join(MIGRATION_STATEMENTS)

_EXPECTED_COLUMNS = {
    "id": ("bigint", True), "code": ("text", True),
    "code_type": ("text", True), "school_id": ("bigint", True),
    "tenant_id": ("text", True), "class_id": ("bigint", False),
    "student_id": ("bigint", False), "created_by": ("bigint", False),
    "created_at": ("text", False), "expires_at": ("text", False),
    "max_usage": ("bigint", False), "usage_count": ("bigint", False),
    "status": ("text", True), "last_used_at": ("text", False),
    "revoked_at": ("text", False), "revoked_by": ("bigint", False),
    "session_id": ("bigint", False), "class_arm": ("text", False),
}


def apply_signup_codes(conn) -> None:
    for statement in MIGRATION_STATEMENTS:
        conn.execute(statement)

    rows = conn.execute(
        "SELECT column_name, data_type, is_nullable FROM information_schema.columns "
        "WHERE table_schema=current_schema() AND table_name=? ORDER BY ordinal_position",
        ("signup_codes",),
    ).fetchall()
    actual = {
        str(row["column_name"]): (str(row["data_type"]).lower(), str(row["is_nullable"]).upper() == "NO")
        for row in rows
    }
    missing = sorted(set(_EXPECTED_COLUMNS) - set(actual))
    wrong = {name: {"actual": actual[name], "expected": expected}
             for name, expected in _EXPECTED_COLUMNS.items() if name in actual and actual[name] != expected}
    if missing or wrong or set(actual) != set(_EXPECTED_COLUMNS):
        raise RuntimeError(f"signup_codes columns incompatible: missing={missing}, wrong={wrong}")

    constraint_rows = conn.execute(
        "SELECT constraint_name, constraint_type FROM information_schema.table_constraints "
        "WHERE table_schema=current_schema() AND table_name=?",
        ("signup_codes",),
    ).fetchall()
    constraints = {str(row["constraint_name"]): str(row["constraint_type"]).upper() for row in constraint_rows}
    expected_constraints = {
        "signup_codes_pkey": "PRIMARY KEY",
        "uq_signup_codes_code": "UNIQUE",
        "ck_signup_codes_type": "CHECK",
        "ck_signup_codes_status": "CHECK",
        "fk_signup_codes_school": "FOREIGN KEY",
    }
    if constraints != expected_constraints:
        raise RuntimeError(f"signup_codes constraints incompatible: {constraints}")

    index_rows = conn.execute(
        "SELECT indexname, indexdef FROM pg_indexes WHERE schemaname=current_schema() AND tablename=?",
        ("signup_codes",),
    ).fetchall()
    indexes = {str(row["indexname"]): str(row["indexdef"]).lower() for row in index_rows}
    expected_indexes = {"signup_codes_pkey", "uq_signup_codes_code", "idx_signup_codes_school_type"}
    if set(indexes) != expected_indexes:
        raise RuntimeError(f"signup_codes indexes incompatible: {sorted(indexes)}")
    if not all(part in indexes["idx_signup_codes_school_type"] for part in ("school_id", "code_type", "status")):
        raise RuntimeError("signup_codes school/type/status index is incompatible")

    triggers = conn.execute(
        "SELECT trigger_name FROM information_schema.triggers "
        "WHERE trigger_schema=current_schema() AND event_object_table=?",
        ("signup_codes",),
    ).fetchall()
    if triggers:
        raise RuntimeError("signup_codes has unexpected triggers")


def migration() -> PostgresMigration:
    return PostgresMigration(version=MIGRATION_VERSION, name=MIGRATION_NAME,
                             apply=apply_signup_codes, source=MIGRATION_SOURCE)
