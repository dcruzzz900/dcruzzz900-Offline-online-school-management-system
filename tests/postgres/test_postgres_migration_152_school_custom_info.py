from postgres_migration_152_school_custom_info import (
    MIGRATION_NAME, MIGRATION_STATEMENTS, MIGRATION_VERSION,
    _EXPECTED_COLUMNS, migration,
)
from postgres_migration_registry import POSTGRES_MIGRATIONS


def test_migration_identity_and_registry():
    item = migration()
    assert item.version == 152
    assert item.name == "create_school_custom_info"
    assert MIGRATION_VERSION == 152
    assert POSTGRES_MIGRATIONS[-36].version == 152
    assert [m.version for m in POSTGRES_MIGRATIONS] == list(range(100, 188))


def test_source_schema_matches_effective_sqlite_definition():
    assert len(_EXPECTED_COLUMNS) == 10
    sql = MIGRATION_STATEMENTS[0]
    for column in ("school_id", "tenant_id", "label", "value", "sort_order", "created_by", "created_at", "updated_at", "show_on_result"):
        assert column in sql
    assert "show_on_result BIGINT NOT NULL DEFAULT 0" in sql
    assert "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in sql
    assert "ux_school_custom_info_label" in MIGRATION_STATEMENTS[1]
    assert "LOWER(label)" in MIGRATION_STATEMENTS[1]
