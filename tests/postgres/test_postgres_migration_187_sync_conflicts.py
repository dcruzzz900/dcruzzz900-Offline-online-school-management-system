import pytest

from postgres_migration_187_sync_conflicts import (
    MIGRATION_NAME, MIGRATION_SOURCE, MIGRATION_STATEMENTS, MIGRATION_VERSION,
    _EXPECTED_COLUMNS, _EXPECTED_FKS, apply_sync_conflicts, migration,
)
from postgres_migration_registry import POSTGRES_MIGRATIONS

_DEFAULTS = {"detected_at": "CURRENT_TIMESTAMP", "resolved": "0", "sensitive": "0"}
GOOD_INDEXES = [
    {"indexname": "sync_conflicts_pkey", "indexdef": "CREATE UNIQUE INDEX sync_conflicts_pkey ON public.sync_conflicts USING btree (id)"},
    {"indexname": "idx_sync_conflicts_school", "indexdef": "CREATE INDEX idx_sync_conflicts_school ON public.sync_conflicts USING btree (school_id, resolved)"},
    {"indexname": "idx_sync_conflicts_change", "indexdef": "CREATE INDEX idx_sync_conflicts_change ON public.sync_conflicts USING btree (school_id, change_id)"},
]


class Result:
    def __init__(self, rows): self.rows = rows
    def fetchall(self): return self.rows
    def fetchone(self): return self.rows[0] if self.rows else None


def good_columns():
    return [
        {"column_name": n, "data_type": typ, "is_nullable": "NO" if req else "YES", "column_default": _DEFAULTS.get(n)}
        for n, (typ, req, _d) in _EXPECTED_COLUMNS.items()
    ]


class FakeConnection:
    def __init__(self, columns=None, fks=None, uniques=None, checks=None, indexes=None, triggers=None, parent_id_type="integer"):
        self.columns = columns if columns is not None else good_columns()
        self.fks = fks if fks is not None else [
            {"column_name": c, "foreign_table_name": t, "foreign_column_name": col} for c, t, col in _EXPECTED_FKS]
        self.uniques = uniques or []
        self.checks = checks or []
        self.indexes = indexes if indexes is not None else GOOD_INDEXES
        self.triggers = triggers or []
        self.parent_id_type = parent_id_type
        self.calls = []

    def execute(self, sql, params=()):
        self.calls.append((sql, params))
        if "information_schema.columns" in sql and params and params[0] == "schools":
            return Result([{"column_name": "id", "data_type": self.parent_id_type}])
        if "information_schema.columns" in sql: return Result(self.columns)
        if "constraint_type = 'FOREIGN KEY'" in sql: return Result(self.fks)
        if "constraint_type = 'UNIQUE'" in sql: return Result(self.uniques)
        if "FROM pg_constraint" in sql: return Result(self.checks)
        if "FROM pg_indexes" in sql: return Result(self.indexes)
        if "information_schema.triggers" in sql: return Result(self.triggers)
        return Result([])


def test_registry_and_migration_identity():
    assert MIGRATION_VERSION == 187
    assert MIGRATION_NAME == "create_sync_conflicts"
    assert POSTGRES_MIGRATIONS[-1].version == 187
    assert [m.version for m in POSTGRES_MIGRATIONS] == list(range(100, 188))
    assert migration().version == 187


def test_effective_sqlite_schema_is_preserved():
    assert list(_EXPECTED_COLUMNS) == [
        "id", "school_id", "entity", "client_uuid", "device_id", "client_payload", "server_payload",
        "detected_at", "resolved", "resolved_at", "resolution", "tenant_id", "change_id", "kind",
        "sensitive", "reason", "entity_key", "resolved_by", "method", "path",
    ]
    sql = MIGRATION_SOURCE.lower()
    for fragment in (
        "id bigint generated by default as identity primary key", "school_id integer not null",
        "entity text not null", "client_uuid text not null", "client_payload text not null",
        "server_payload text not null", "detected_at text default current_timestamp",
        "resolved bigint default 0", "sensitive bigint default 0", "tenant_id text,",
        "references schools(id)", "idx_sync_conflicts_school", "(school_id, resolved)",
        "idx_sync_conflicts_change", "(school_id, change_id)",
    ):
        assert fragment in sql
    assert sql.count("references ") == 1 and "unique" not in sql and "check" not in sql and "trigger" not in sql


def test_apply_executes_every_statement_and_validates():
    conn = FakeConnection()
    apply_sync_conflicts(conn)
    executed = [sql for sql, _ in conn.calls]
    for statement in MIGRATION_STATEMENTS:
        assert statement in executed


def test_parent_key_is_checked_before_any_ddl():
    conn = FakeConnection(parent_id_type="bigint")
    with pytest.raises(RuntimeError, match="INTEGER"):
        apply_sync_conflicts(conn)
    assert not any("CREATE TABLE" in sql for sql, _ in conn.calls)


def test_accepts_existing_tenant_stamp_trigger():
    apply_sync_conflicts(FakeConnection(triggers=[{"trigger_name": "trg_sync_conflicts_tenant_stamp_pg"}]))


def test_rejects_wrong_columns():
    with pytest.raises(RuntimeError, match="columns incompatible"):
        apply_sync_conflicts(FakeConnection(columns=[]))


def test_rejects_wrong_defaults():
    for col, bad in (("resolved", None), ("sensitive", None), ("detected_at", None), ("kind", "'x'::text")):
        cols = good_columns()
        for c in cols:
            if c["column_name"] == col:
                c["column_default"] = bad
        with pytest.raises(RuntimeError, match="columns incompatible"):
            apply_sync_conflicts(FakeConnection(columns=cols))


def test_rejects_wrong_nullability():
    cols = good_columns()
    for c in cols:
        if c["column_name"] == "client_payload":
            c["is_nullable"] = "YES"
    with pytest.raises(RuntimeError, match="columns incompatible"):
        apply_sync_conflicts(FakeConnection(columns=cols))


def test_rejects_wrong_foreign_keys():
    with pytest.raises(RuntimeError, match="foreign keys incompatible"):
        apply_sync_conflicts(FakeConnection(fks=[]))
    with pytest.raises(RuntimeError, match="foreign keys incompatible"):
        apply_sync_conflicts(FakeConnection(fks=[{"column_name": "school_id", "foreign_table_name": "users", "foreign_column_name": "id"}]))


def test_rejects_unexpected_unique_constraint():
    with pytest.raises(RuntimeError, match="unique constraints incompatible"):
        apply_sync_conflicts(FakeConnection(uniques=[{"constraint_name": "x"}]))


def test_rejects_unexpected_check_constraint():
    with pytest.raises(RuntimeError, match="CHECK constraints incompatible"):
        apply_sync_conflicts(FakeConnection(checks=[{"conname": "x"}]))


def test_rejects_wrong_indexes():
    with pytest.raises(RuntimeError, match="indexes incompatible"):
        apply_sync_conflicts(FakeConnection(indexes=[]))


def test_rejects_unique_or_wrong_column_order_indexes():
    for name, bad_def in (
        ("idx_sync_conflicts_school", "CREATE UNIQUE INDEX i ON t USING btree (school_id, resolved)"),
        ("idx_sync_conflicts_school", "CREATE INDEX i ON t USING btree (resolved, school_id)"),
        ("idx_sync_conflicts_change", "CREATE INDEX i ON t USING btree (change_id, school_id)"),
    ):
        bad = [dict(i) for i in GOOD_INDEXES]
        for i in bad:
            if i["indexname"] == name:
                i["indexdef"] = bad_def
        with pytest.raises(RuntimeError, match=f"{name} index is incompatible"):
            apply_sync_conflicts(FakeConnection(indexes=bad))


def test_rejects_unexpected_triggers():
    with pytest.raises(RuntimeError, match="triggers incompatible"):
        apply_sync_conflicts(FakeConnection(triggers=[{"trigger_name": "x"}]))
