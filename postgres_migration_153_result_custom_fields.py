"""Standalone PostgreSQL migration 153 for result-sheet custom field definitions.

Ports the effective V104 SQLite table shape and its case-insensitive
school-scoped label uniqueness. The source declares no foreign keys or triggers.
"""
from __future__ import annotations

from postgres_migrations import PostgresMigration

MIGRATION_VERSION = 153
MIGRATION_NAME = "create_result_custom_fields"
MIGRATION_STATEMENTS = (
    """CREATE TABLE IF NOT EXISTS result_custom_fields (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        school_id BIGINT NOT NULL,
        tenant_id TEXT,
        label TEXT NOT NULL,
        field_type TEXT NOT NULL DEFAULT 'text',
        options TEXT,
        sort_order BIGINT NOT NULL DEFAULT 0,
        is_active BIGINT NOT NULL DEFAULT 1,
        show_on_sheet BIGINT NOT NULL DEFAULT 1,
        created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
    )""",
    """CREATE UNIQUE INDEX IF NOT EXISTS ux_result_custom_fields_label
       ON result_custom_fields (school_id, LOWER(label))""",
)
MIGRATION_SOURCE = ";\n\n".join(MIGRATION_STATEMENTS)

_EXPECTED_COLUMNS = {
    "id": ("bigint", True),
    "school_id": ("bigint", True),
    "tenant_id": ("text", False),
    "label": ("text", True),
    "field_type": ("text", True),
    "options": ("text", False),
    "sort_order": ("bigint", True),
    "is_active": ("bigint", True),
    "show_on_sheet": ("bigint", True),
    "created_at": ("timestamp without time zone", False),
}


def apply_result_custom_fields(conn) -> None:
    for statement in MIGRATION_STATEMENTS:
        conn.execute(statement)

    rows = conn.execute(
        "SELECT column_name, data_type, is_nullable FROM information_schema.columns "
        "WHERE table_schema=current_schema() AND table_name=? ORDER BY ordinal_position",
        ("result_custom_fields",),
    ).fetchall()
    actual = {
        str(row["column_name"]): (str(row["data_type"]).lower(), str(row["is_nullable"]).upper() == "NO")
        for row in rows
    }
    missing = sorted(set(_EXPECTED_COLUMNS) - set(actual))
    wrong = {
        name: {"actual": actual[name], "expected": expected}
        for name, expected in _EXPECTED_COLUMNS.items()
        if name in actual and actual[name] != expected
    }
    if missing or wrong or set(actual) != set(_EXPECTED_COLUMNS):
        raise RuntimeError(f"result_custom_fields columns incompatible: missing={missing}, wrong={wrong}")

    index_rows = conn.execute(
        "SELECT indexname, indexdef FROM pg_indexes "
        "WHERE schemaname=current_schema() AND tablename=?",
        ("result_custom_fields",),
    ).fetchall()
    indexes = {str(row["indexname"]): str(row["indexdef"]).lower().replace('"', "") for row in index_rows}
    if set(indexes) != {"result_custom_fields_pkey", "ux_result_custom_fields_label"}:
        raise RuntimeError(f"result_custom_fields indexes incompatible: {sorted(indexes)}")
    label_index = indexes["ux_result_custom_fields_label"]
    if "unique index" not in label_index or "(school_id, lower(label))" not in label_index:
        raise RuntimeError("result_custom_fields school-scoped case-insensitive label index is incompatible")

    constraints = conn.execute(
        "SELECT constraint_type FROM information_schema.table_constraints "
        "WHERE table_schema=current_schema() AND table_name=?",
        ("result_custom_fields",),
    ).fetchall()
    if any(str(row["constraint_type"]).upper() == "FOREIGN KEY" for row in constraints):
        raise RuntimeError("result_custom_fields has unexpected foreign keys")

    triggers = conn.execute(
        "SELECT trigger_name FROM information_schema.triggers "
        "WHERE trigger_schema=current_schema() AND event_object_table=?",
        ("result_custom_fields",),
    ).fetchall()
    if triggers:
        raise RuntimeError("result_custom_fields has unexpected triggers")


def migration() -> PostgresMigration:
    return PostgresMigration(
        version=MIGRATION_VERSION,
        name=MIGRATION_NAME,
        apply=apply_result_custom_fields,
        source=MIGRATION_SOURCE,
    )
