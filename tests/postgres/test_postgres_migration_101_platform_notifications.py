import pytest

from postgres_migration_101_platform_notifications import (
    MIGRATION_NAME, MIGRATION_SOURCE, MIGRATION_VERSION,
    apply_platform_notifications, migration,
)
from postgres_migration_registry import POSTGRES_MIGRATIONS


class Result:
    def __init__(self, rows): self.rows = rows
    def fetchall(self): return self.rows
    def fetchone(self): return self.rows[0] if self.rows else None


class FakeConnection:
    def __init__(self, columns=None, school=True, fk=True, index=None):
        self.columns = columns or [
            {"column_name": n, "data_type": t} for n, t in {
                "id":"bigint", "title":"text", "message":"text",
                "school_id":"bigint", "read_at":"text", "created_at":"text"}.items()]
        self.school, self.fk, self.index = school, fk, index or {
            "indexdef":"CREATE INDEX idx_platform_notifications_created ON public.platform_notifications USING btree (created_at DESC)"}
        self.calls=[]
    def execute(self, sql, params=()):
        self.calls.append((sql, params))
        if "table_name = ? AND column_name = ?" in sql:
            return Result([{"column_name":"id", "data_type":"bigint"}] if self.school else [])
        if "information_schema.columns" in sql:
            return Result(self.columns)
        if "information_schema.table_constraints" in sql:
            return Result([{"foreign_table_name":"schools", "foreign_column_name":"id"}] if self.fk else [])
        if "FROM pg_indexes" in sql:
            return Result([self.index] if self.index else [])
        return Result([])


def test_migration_metadata_and_registry():
    item=migration()
    assert (item.version,item.name,item.source)==(101,MIGRATION_NAME,MIGRATION_SOURCE)
    assert MIGRATION_VERSION==101 and MIGRATION_NAME=="create_platform_notifications"
    assert [m.version for m in POSTGRES_MIGRATIONS]==list(range(100, 188))


def test_creates_table_with_school_fk_and_desc_index():
    conn=FakeConnection(); apply_platform_notifications(conn)
    sql="\n".join(q for q,_ in conn.calls)
    assert "GENERATED BY DEFAULT AS IDENTITY" in sql
    assert "REFERENCES schools(id)" in sql
    assert "created_at DESC" in sql
    assert conn.calls[0][1]==("schools","id")


def test_requires_compatible_schools_primary_key_type():
    with pytest.raises(RuntimeError, match="requires schools.id BIGINT"):
        apply_platform_notifications(FakeConnection(school=False))


def test_rejects_missing_or_wrong_column():
    cols=[dict(c) for c in FakeConnection().columns if c["column_name"]!="read_at"]
    with pytest.raises(RuntimeError, match="missing columns"):
        apply_platform_notifications(FakeConnection(columns=cols))
    cols=[dict(c) for c in FakeConnection().columns]
    cols[1]["data_type"]="character varying"
    with pytest.raises(RuntimeError, match="incompatible types"):
        apply_platform_notifications(FakeConnection(columns=cols))


def test_requires_correct_school_foreign_key():
    with pytest.raises(RuntimeError, match="foreign key is missing"):
        apply_platform_notifications(FakeConnection(fk=False))


def test_requires_correct_created_index():
    with pytest.raises(RuntimeError, match="index has an incompatible"):
        apply_platform_notifications(FakeConnection(index={"indexdef":"CREATE INDEX idx_platform_notifications_created ON public.platform_notifications (school_id)"}))
