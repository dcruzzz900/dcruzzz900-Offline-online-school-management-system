import pytest

from postgres_migration_134_fixed_activities_v2 import (
    MIGRATION_NAME, MIGRATION_SOURCE, MIGRATION_VERSION,
    apply_fixed_activities_v2, migration,
)
from postgres_migration_registry import POSTGRES_MIGRATIONS


class Result:
    def __init__(self, rows): self.rows = rows
    def fetchall(self): return self.rows
    def fetchone(self): return self.rows[0] if self.rows else None


class FakeConnection:
    def __init__(self, columns=None, fks=None, indexes=None, triggers=None, school_id_type="integer"):
        expected = {
            "id": ("bigint", True), "tenant_id": ("text", True), "school_id": ("integer", True),
            "academic_session_id": ("bigint", False), "term_id": ("bigint", False),
            "activity_name": ("text", True), "activity_type": ("text", True),
            "day_id": ("bigint", True), "slot_id": ("bigint", True), "class_id": ("bigint", False),
            "arm_id": ("bigint", False), "teacher_id": ("bigint", False), "room_id": ("bigint", False),
            "is_mandatory": ("bigint", False), "is_immovable": ("bigint", False),
            "client_uuid": ("text", False), "updated_at": ("text", False), "is_deleted": ("bigint", False),
        }
        self.columns = columns if columns is not None else [
            {"column_name": n, "data_type": typ, "is_nullable": "NO" if req else "YES"}
            for n, (typ, req) in expected.items()
        ]
        self.fks = fks if fks is not None else [{"column_name": "school_id", "foreign_table_name": "schools", "foreign_column_name": "id"}]
        self.indexes = indexes if indexes is not None else [
            {"indexname": "fixed_activities_v2_pkey", "indexdef": "CREATE UNIQUE INDEX fixed_activities_v2_pkey ON public.fixed_activities_v2 USING btree (id)"},
            {"indexname": "idx_fixed_activities_v2_client_uuid", "indexdef": "CREATE UNIQUE INDEX idx_fixed_activities_v2_client_uuid ON public.fixed_activities_v2 USING btree (client_uuid) WHERE (client_uuid IS NOT NULL)"},
        ]
        self.triggers = triggers if triggers is not None else [
            {"trigger_name": "trg_fixed_activities_v2_sync_defaults"},
            {"trigger_name": "trg_fixed_activities_v2_sync_touch"},
        ]
        self.school_id_type = school_id_type
        self.calls = []

    def execute(self, sql, params=()):
        self.calls.append((sql, params))
        if "information_schema.columns" in sql and "schools" in params:
            return Result([{"column_name": "id", "data_type": self.school_id_type}])
        if "information_schema.columns" in sql: return Result(self.columns)
        if "information_schema.table_constraints" in sql: return Result(self.fks)
        if "FROM pg_indexes" in sql: return Result(self.indexes)
        if "information_schema.triggers" in sql: return Result(self.triggers)
        return Result([])


def test_registry_and_migration_identity():
    assert MIGRATION_VERSION == 134
    assert MIGRATION_NAME == "create_fixed_activities_v2"
    assert [m.version for m in POSTGRES_MIGRATIONS] == list(range(100, 188))
    assert next(m for m in POSTGRES_MIGRATIONS if m.version == 134).name == MIGRATION_NAME
    assert migration().version == 134


def test_ddl_preserves_table_relationship_index_and_sync_triggers():
    sql = MIGRATION_SOURCE.lower()
    for fragment in (
        "id bigint generated by default as identity primary key", "tenant_id text not null",
        "school_id integer not null", "activity_name text not null", "is_mandatory bigint default 1",
        "is_immovable bigint default 1", "is_deleted bigint default 0",
        "references schools(id)", "where client_uuid is not null", "before insert", "before update",
    ):
        assert fragment in sql


def test_apply_executes_and_validates_migration():
    conn = FakeConnection()
    apply_fixed_activities_v2(conn)
    assert any("CREATE TABLE IF NOT EXISTS fixed_activities_v2" in sql for sql, _ in conn.calls)


def test_rejects_incompatible_school_primary_key_type():
    with pytest.raises(RuntimeError, match="schools.id INTEGER"):
        apply_fixed_activities_v2(FakeConnection(school_id_type="bigint"))


def test_rejects_wrong_columns():
    with pytest.raises(RuntimeError, match="columns incompatible"):
        apply_fixed_activities_v2(FakeConnection(columns=[]))


def test_rejects_wrong_foreign_key():
    with pytest.raises(RuntimeError, match="foreign keys incompatible"):
        apply_fixed_activities_v2(FakeConnection(fks=[]))


def test_rejects_wrong_indexes():
    with pytest.raises(RuntimeError, match="indexes incompatible"):
        apply_fixed_activities_v2(FakeConnection(indexes=[]))


def test_rejects_wrong_triggers():
    with pytest.raises(RuntimeError, match="triggers incompatible"):
        apply_fixed_activities_v2(FakeConnection(triggers=[]))
