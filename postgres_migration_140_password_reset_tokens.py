"""PostgreSQL-native migration 140: password_reset_tokens.

Ports short-lived password-reset token metadata. account_id is intentionally
polymorphic (staff or parent), matching the SQLite source's lack of a foreign
key. This migration remains separate from SQLite startup.
"""
from __future__ import annotations

from postgres_migrations import PostgresMigration

MIGRATION_VERSION = 140
MIGRATION_NAME = "create_password_reset_tokens"

MIGRATION_STATEMENTS = (
    """CREATE TABLE IF NOT EXISTS password_reset_tokens (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        account_type TEXT NOT NULL,
        account_id BIGINT NOT NULL,
        token_hash TEXT NOT NULL,
        created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
        expires_at TEXT NOT NULL,
        used_at TEXT,
        CONSTRAINT password_reset_tokens_account_type_check
            CHECK (account_type IN ('staff', 'parent')),
        CONSTRAINT password_reset_tokens_token_hash_key UNIQUE (token_hash)
    )""",
    "CREATE INDEX IF NOT EXISTS idx_password_reset_tokens_account ON password_reset_tokens(account_type, account_id)",
)
MIGRATION_SOURCE = ";\n\n".join(MIGRATION_STATEMENTS)

_EXPECTED_COLUMNS = {
    "id": ("bigint", True),
    "account_type": ("text", True),
    "account_id": ("bigint", True),
    "token_hash": ("text", True),
    "created_at": ("text", True),
    "expires_at": ("text", True),
    "used_at": ("text", False),
}
_EXPECTED_INDEXES = {
    "password_reset_tokens_pkey",
    "password_reset_tokens_token_hash_key",
    "idx_password_reset_tokens_account",
}


def apply_password_reset_tokens(conn) -> None:
    for statement in MIGRATION_STATEMENTS:
        conn.execute(statement)

    rows = conn.execute(
        "SELECT column_name, data_type, is_nullable FROM information_schema.columns "
        "WHERE table_schema = current_schema() AND table_name = ? ORDER BY ordinal_position",
        ("password_reset_tokens",),
    ).fetchall()
    actual_columns = {
        str(row["column_name"]): (
            str(row["data_type"]).lower(), str(row["is_nullable"]).upper() == "NO"
        )
        for row in rows
    }
    missing = sorted(set(_EXPECTED_COLUMNS) - set(actual_columns))
    wrong = {
        name: {"actual": actual_columns[name], "expected": expected}
        for name, expected in _EXPECTED_COLUMNS.items()
        if name in actual_columns and actual_columns[name] != expected
    }
    if missing or wrong or set(actual_columns) != set(_EXPECTED_COLUMNS):
        raise RuntimeError(
            f"password_reset_tokens columns incompatible: missing={missing}, wrong={wrong}"
        )

    constraint_rows = conn.execute(
        "SELECT conname, contype, pg_get_constraintdef(oid) AS definition "
        "FROM pg_constraint WHERE conrelid = 'password_reset_tokens'::regclass"
    ).fetchall()
    constraints = {str(row["conname"]): (str(row["contype"]), str(row["definition"]).lower()) for row in constraint_rows}
    expected_constraints = {
        "password_reset_tokens_pkey": "p",
        "password_reset_tokens_account_type_check": "c",
        "password_reset_tokens_token_hash_key": "u",
    }
    if {name: value[0] for name, value in constraints.items()} != expected_constraints:
        raise RuntimeError(f"password_reset_tokens constraints incompatible: {constraints}")
    check_definition = constraints["password_reset_tokens_account_type_check"][1]
    if "account_type" not in check_definition or "staff" not in check_definition or "parent" not in check_definition:
        raise RuntimeError("password_reset_tokens account_type CHECK constraint incompatible")

    fk_rows = conn.execute(
        "SELECT constraint_name FROM information_schema.table_constraints "
        "WHERE table_schema = current_schema() AND table_name = ? AND constraint_type = 'FOREIGN KEY'",
        ("password_reset_tokens",),
    ).fetchall()
    if fk_rows:
        raise RuntimeError("password_reset_tokens must not have foreign keys; account_id is polymorphic")

    index_rows = conn.execute(
        "SELECT indexname, indexdef FROM pg_indexes "
        "WHERE schemaname = current_schema() AND tablename = ?",
        ("password_reset_tokens",),
    ).fetchall()
    indexes = {str(row["indexname"]): str(row["indexdef"]).lower().replace('"', "") for row in index_rows}
    if set(indexes) != _EXPECTED_INDEXES:
        raise RuntimeError(f"password_reset_tokens indexes incompatible: {sorted(indexes)}")
    if "(account_type, account_id)" not in indexes["idx_password_reset_tokens_account"]:
        raise RuntimeError("password_reset_tokens account lookup index incompatible")
    if "unique" not in indexes["password_reset_tokens_token_hash_key"] or "(token_hash)" not in indexes["password_reset_tokens_token_hash_key"]:
        raise RuntimeError("password_reset_tokens token_hash unique index incompatible")

    trigger_rows = conn.execute(
        "SELECT trigger_name FROM information_schema.triggers "
        "WHERE trigger_schema = current_schema() AND event_object_table = ?",
        ("password_reset_tokens",),
    ).fetchall()
    if trigger_rows:
        raise RuntimeError("password_reset_tokens must not have triggers")


def migration() -> PostgresMigration:
    return PostgresMigration(
        version=MIGRATION_VERSION,
        name=MIGRATION_NAME,
        apply=apply_password_reset_tokens,
        source=MIGRATION_SOURCE,
    )
