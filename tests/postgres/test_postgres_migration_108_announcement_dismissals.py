from postgres_migration_108_announcement_dismissals import (
    MIGRATION_NAME,
    MIGRATION_SOURCE,
    MIGRATION_VERSION,
    migration,
)
from postgres_migration_registry import POSTGRES_MIGRATIONS


def test_announcement_dismissals_migration_is_registered_in_order():
    assert MIGRATION_VERSION == 108
    assert MIGRATION_NAME == "create_announcement_dismissals"
    assert [item.version for item in POSTGRES_MIGRATIONS] == list(range(100, 188))
    assert next(item for item in POSTGRES_MIGRATIONS if item.version == MIGRATION_VERSION).name == MIGRATION_NAME


def test_announcement_dismissals_ddl_preserves_source_contract():
    sql = MIGRATION_SOURCE.lower()
    for column in ("announcement_id", "actor_type", "actor_id", "dismissed_at"):
        assert column in sql
    assert "bigint generated by default as identity primary key" in sql
    assert "unique (announcement_id, actor_type, actor_id)" in sql
    assert "dismissed_at text default current_timestamp" in sql
    assert "references " not in sql
    assert "create index" not in sql
    assert "create trigger" not in sql


def test_migration_metadata():
    item = migration()
    assert item.version == 108
    assert item.name == MIGRATION_NAME
    assert item.source == MIGRATION_SOURCE
    assert callable(item.apply)
