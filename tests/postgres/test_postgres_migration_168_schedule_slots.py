import pytest

from postgres_migration_168_schedule_slots import (
    MIGRATION_NAME, MIGRATION_SOURCE, MIGRATION_STATEMENTS, MIGRATION_VERSION,
    _EXPECTED_COLUMNS, apply_schedule_slots, migration,
)
from postgres_migration_registry import POSTGRES_MIGRATIONS

GOOD_CHECKS = [
    {"conname": "ck_schedule_slots_slot_type",
     "definition": "CHECK ((slot_type = ANY (ARRAY['TEACHING'::text, 'BREAK'::text, 'ASSEMBLY'::text, 'ACTIVITY'::text, 'OTHER'::text])))"},
    {"conname": "ck_schedule_slots_time_order", "definition": "CHECK ((start_time < end_time))"},
]


class Result:
    def __init__(self, rows): self.rows = rows
    def fetchall(self): return self.rows
    def fetchone(self): return self.rows[0] if self.rows else None


class FakeConnection:
    def __init__(self, columns=None, fks=None, uniques=None, checks=None, indexes=None, triggers=None, parent_types=None):
        self.columns = columns if columns is not None else [
            {"column_name": n, "data_type": typ, "is_nullable": "NO" if req else "YES"}
            for n, (typ, req) in _EXPECTED_COLUMNS.items()
        ]
        self.fks = fks if fks is not None else [
            {"column_name": "school_id", "foreign_table_name": "schools", "foreign_column_name": "id"},
            {"column_name": "day_id", "foreign_table_name": "school_days_v2", "foreign_column_name": "id"},
            {"column_name": "schedule_template_id", "foreign_table_name": "schedule_templates", "foreign_column_name": "id"},
        ]
        self.uniques = uniques if uniques is not None else []
        self.checks = checks if checks is not None else list(GOOD_CHECKS)
        self.indexes = indexes if indexes is not None else [
            {"indexname": "schedule_slots_pkey", "indexdef": "CREATE UNIQUE INDEX schedule_slots_pkey ON public.schedule_slots USING btree (id)"},
            {"indexname": "idx_schedule_slots_client_uuid", "indexdef": "CREATE UNIQUE INDEX idx_schedule_slots_client_uuid ON public.schedule_slots USING btree (client_uuid) WHERE (client_uuid IS NOT NULL)"},
        ]
        self.triggers = triggers if triggers is not None else [
            {"trigger_name": "trg_schedule_slots_sync_defaults"}, {"trigger_name": "trg_schedule_slots_sync_touch"}]
        self.parent_types = {"schools": "integer", "school_days_v2": "bigint", "schedule_templates": "bigint"}
        self.parent_types.update(parent_types or {})
        self.calls = []

    def execute(self, sql, params=()):
        self.calls.append((sql, params))
        if "information_schema.columns" in sql and params and params[0] in self.parent_types:
            return Result([{"column_name": "id", "data_type": self.parent_types[params[0]]}])
        if "information_schema.columns" in sql: return Result(self.columns)
        if "constraint_type = 'FOREIGN KEY'" in sql: return Result(self.fks)
        if "constraint_type = 'UNIQUE'" in sql: return Result(self.uniques)
        if "FROM pg_constraint" in sql: return Result(self.checks)
        if "FROM pg_indexes" in sql: return Result(self.indexes)
        if "information_schema.triggers" in sql: return Result(self.triggers)
        return Result([])


def test_registry_and_migration_identity():
    assert MIGRATION_VERSION == 168
    assert MIGRATION_NAME == "create_schedule_slots"
    assert POSTGRES_MIGRATIONS[-20].version == 168
    assert [m.version for m in POSTGRES_MIGRATIONS] == list(range(100, 188))
    assert migration().version == 168


def test_effective_sqlite_schema_is_preserved():
    assert list(_EXPECTED_COLUMNS) == [
        "id", "tenant_id", "school_id", "academic_session_id", "term_id", "day_id",
        "schedule_template_id", "slot_number", "slot_name", "slot_type", "start_time", "end_time",
        "duration_minutes", "is_active", "is_fixed", "allows_timetable_entry", "created_at",
        "updated_at", "client_uuid", "is_deleted",
    ]
    sql = MIGRATION_SOURCE.lower()
    for fragment in (
        "id bigint generated by default as identity primary key", "school_id integer not null",
        "day_id bigint not null", "schedule_template_id bigint not null", "slot_number bigint not null",
        "slot_name text not null", "slot_type text not null default 'teaching'",
        "start_time text not null", "end_time text not null", "duration_minutes bigint not null default 0",
        "is_active bigint not null default 1", "is_fixed bigint not null default 0",
        "allows_timetable_entry bigint not null default 1", "created_at text default current_timestamp",
        "is_deleted bigint default 0",
        "check (slot_type in ('teaching', 'break', 'assembly', 'activity', 'other'))",
        "check (start_time < end_time)",
        "references schools(id)", "references school_days_v2(id)", "references schedule_templates(id)",
        "where client_uuid is not null", "before insert", "before update",
    ):
        assert fragment in sql
    assert sql.count("references ") == 3


def test_apply_executes_every_statement_and_validates():
    conn = FakeConnection()
    apply_schedule_slots(conn)
    executed = [sql for sql, _ in conn.calls]
    for statement in MIGRATION_STATEMENTS:
        assert statement in executed


@pytest.mark.parametrize("parent,bad_type", [
    ("schools", "bigint"), ("school_days_v2", "integer"), ("schedule_templates", "integer"),
])
def test_rejects_incompatible_parent_key_type(parent, bad_type):
    with pytest.raises(RuntimeError, match=f"{parent}.id"):
        apply_schedule_slots(FakeConnection(parent_types={parent: bad_type}))


def test_rejects_wrong_columns():
    with pytest.raises(RuntimeError, match="columns incompatible"):
        apply_schedule_slots(FakeConnection(columns=[]))


def test_rejects_missing_or_wrong_foreign_keys():
    with pytest.raises(RuntimeError, match="foreign keys incompatible"):
        apply_schedule_slots(FakeConnection(fks=[]))
    partial = [{"column_name": "school_id", "foreign_table_name": "schools", "foreign_column_name": "id"}]
    with pytest.raises(RuntimeError, match="foreign keys incompatible"):
        apply_schedule_slots(FakeConnection(fks=partial))


def test_rejects_unexpected_unique_constraint():
    with pytest.raises(RuntimeError, match="unique constraints incompatible"):
        apply_schedule_slots(FakeConnection(uniques=[{"constraint_name": "x"}]))


def test_rejects_missing_check_constraints():
    with pytest.raises(RuntimeError, match="CHECK constraints incompatible"):
        apply_schedule_slots(FakeConnection(checks=[]))
    with pytest.raises(RuntimeError, match="CHECK constraints incompatible"):
        apply_schedule_slots(FakeConnection(checks=[GOOD_CHECKS[0]]))


def test_rejects_slot_type_check_missing_a_value():
    weak = [{"conname": "ck_schedule_slots_slot_type",
             "definition": "CHECK ((slot_type = ANY (ARRAY['TEACHING'::text, 'BREAK'::text])))"}, GOOD_CHECKS[1]]
    with pytest.raises(RuntimeError, match="CHECK constraints incompatible"):
        apply_schedule_slots(FakeConnection(checks=weak))


def test_rejects_wrong_time_order_check():
    weak = [GOOD_CHECKS[0], {"conname": "ck_schedule_slots_time_order", "definition": "CHECK ((start_time IS NOT NULL))"}]
    with pytest.raises(RuntimeError, match="CHECK constraints incompatible"):
        apply_schedule_slots(FakeConnection(checks=weak))


def test_rejects_wrong_indexes():
    with pytest.raises(RuntimeError, match="indexes incompatible"):
        apply_schedule_slots(FakeConnection(indexes=[]))


def test_rejects_non_partial_client_uuid_index():
    bad = [
        {"indexname": "schedule_slots_pkey", "indexdef": "x"},
        {"indexname": "idx_schedule_slots_client_uuid", "indexdef": "CREATE INDEX i ON t USING btree (client_uuid)"},
    ]
    with pytest.raises(RuntimeError, match="partial index"):
        apply_schedule_slots(FakeConnection(indexes=bad))


def test_rejects_wrong_triggers():
    with pytest.raises(RuntimeError, match="triggers incompatible"):
        apply_schedule_slots(FakeConnection(triggers=[]))
