"""PostgreSQL-native migration 185: sync_log.

Ports the effective SQLite table that logs each offline-sync push/pull
(device, direction, entity and record/conflict/error counts), written by
`record_sync_log()` in `db.py`.

The source has 11 effective columns, not the 10 its `CREATE TABLE` shows:
`migration_051_registration_security_spec()`'s generic `direct=[...]` list
adds a nullable `tenant_id TEXT`. `postgres_tenant_triggers.sql` already
defines `app_stamp_tenant_sync_log()` / `trg_sync_log_tenant_stamp_pg`
(same condition and source column as the source's trigger), so this migration
relies on it rather than re-implementing tenant stamping, the same answer
migrations 182 and 183 gave. Verification therefore accepts that one
trigger being present or absent (the tenant file may be applied before or
after this migration) and rejects any other.

Type choices follow this series: the key `id` is a BIGINT identity; the
integer counters are BIGINT with DEFAULT 0; `school_id` and `user_id` stay
INTEGER to match `schools.id` / `users.id`. The source declares no foreign
key on this table (a log row should not block deleting a school or user), so
none is added. `direction` has only a comment ('push' or 'pull') in the
source, not a CHECK constraint, so none is added and verification asserts no
CHECK exists. `created_at` keeps the source's `TEXT DEFAULT CURRENT_TIMESTAMP`
convention used by the other ported tables. The single index is
`idx_sync_log_school (school_id, created_at)`, non-unique. This migration does
not alter SQLite startup, SQLite migrations, or offline sync.
"""
from __future__ import annotations

from postgres_migrations import PostgresMigration

MIGRATION_VERSION = 185
MIGRATION_NAME = "create_sync_log"

MIGRATION_STATEMENTS = (
    """CREATE TABLE IF NOT EXISTS sync_log (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        school_id INTEGER NOT NULL,
        device_id TEXT NOT NULL,
        user_id INTEGER,
        direction TEXT NOT NULL,
        entity TEXT,
        record_count BIGINT DEFAULT 0,
        conflict_count BIGINT DEFAULT 0,
        error_count BIGINT DEFAULT 0,
        created_at TEXT DEFAULT CURRENT_TIMESTAMP,
        tenant_id TEXT
    )""",
    "CREATE INDEX IF NOT EXISTS idx_sync_log_school ON sync_log (school_id, created_at)",
)
MIGRATION_SOURCE = ";\n\n".join(MIGRATION_STATEMENTS)

# name -> (data_type, not_null, default fragment or None)
_EXPECTED_COLUMNS = {
    "id": ("bigint", True, None), "school_id": ("integer", True, None),
    "device_id": ("text", True, None), "user_id": ("integer", False, None),
    "direction": ("text", True, None), "entity": ("text", False, None),
    "record_count": ("bigint", False, "0"), "conflict_count": ("bigint", False, "0"),
    "error_count": ("bigint", False, "0"), "created_at": ("text", False, "current_timestamp"),
    "tenant_id": ("text", False, None),
}
_ALLOWED_TRIGGERS = {"trg_sync_log_tenant_stamp_pg"}


def apply_sync_log(conn) -> None:
    for statement in MIGRATION_STATEMENTS:
        conn.execute(statement)

    rows = conn.execute(
        "SELECT column_name, data_type, is_nullable, column_default FROM information_schema.columns "
        "WHERE table_schema = current_schema() AND table_name = ? ORDER BY ordinal_position",
        ("sync_log",),
    ).fetchall()
    actual = {}
    for r in rows:
        default = r["column_default"]
        actual[str(r["column_name"])] = (str(r["data_type"]).lower(), str(r["is_nullable"]).upper() == "NO",
                                         None if default is None else str(default).lower())
    missing = sorted(set(_EXPECTED_COLUMNS) - set(actual))
    wrong = {}
    for name, (typ, req, default_fragment) in _EXPECTED_COLUMNS.items():
        if name not in actual:
            continue
        a_typ, a_req, a_default = actual[name]
        if name == "id":
            default_ok = True  # identity columns report no default or a generated one
        elif default_fragment is None:
            default_ok = a_default is None
        else:
            default_ok = a_default is not None and default_fragment in a_default
        if (a_typ, a_req) != (typ, req) or not default_ok:
            wrong[name] = {"actual": actual[name], "expected": (typ, req, default_fragment)}
    if missing or wrong or set(actual) != set(_EXPECTED_COLUMNS):
        raise RuntimeError(f"sync_log columns incompatible: missing={missing}, wrong={wrong}")

    fk_rows = conn.execute(
        "SELECT kcu.column_name FROM information_schema.table_constraints tc "
        "JOIN information_schema.key_column_usage kcu ON tc.constraint_name = kcu.constraint_name AND tc.constraint_schema = kcu.constraint_schema "
        "WHERE tc.constraint_type = 'FOREIGN KEY' AND tc.table_schema = current_schema() AND tc.table_name = ?",
        ("sync_log",),
    ).fetchall()
    if fk_rows:
        raise RuntimeError("sync_log foreign keys incompatible: source declares none")

    unique_rows = conn.execute(
        "SELECT tc.constraint_name FROM information_schema.table_constraints tc "
        "WHERE tc.constraint_type = 'UNIQUE' AND tc.table_schema = current_schema() AND tc.table_name = ?",
        ("sync_log",),
    ).fetchall()
    if unique_rows:
        raise RuntimeError("sync_log unique constraints incompatible: unexpected table-level UNIQUE constraint")

    check_rows = conn.execute(
        "SELECT conname FROM pg_constraint WHERE conrelid = 'sync_log'::regclass AND contype = 'c'"
    ).fetchall()
    if check_rows:
        raise RuntimeError("sync_log CHECK constraints incompatible: unexpected CHECK constraint")

    index_rows = conn.execute(
        "SELECT indexname, indexdef FROM pg_indexes WHERE schemaname = current_schema() AND tablename = ?",
        ("sync_log",),
    ).fetchall()
    indexes = {str(r["indexname"]): str(r["indexdef"]).lower().replace('"', "") for r in index_rows}
    if set(indexes) != {"sync_log_pkey", "idx_sync_log_school"}:
        raise RuntimeError(f"sync_log indexes incompatible: {sorted(indexes)}")
    school_idx = indexes["idx_sync_log_school"]
    if "unique" in school_idx or "(school_id, created_at)" not in school_idx:
        raise RuntimeError("sync_log school lookup index is incompatible")

    trigger_rows = conn.execute(
        "SELECT trigger_name FROM information_schema.triggers WHERE trigger_schema = current_schema() AND event_object_table = ?",
        ("sync_log",),
    ).fetchall()
    unexpected = {str(r["trigger_name"]) for r in trigger_rows} - _ALLOWED_TRIGGERS
    if unexpected:
        raise RuntimeError(f"sync_log triggers incompatible: {sorted(unexpected)}")


def migration() -> PostgresMigration:
    return PostgresMigration(version=MIGRATION_VERSION, name=MIGRATION_NAME,
                             apply=apply_sync_log, source=MIGRATION_SOURCE)
