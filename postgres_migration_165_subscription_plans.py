"""PostgreSQL-native migration 165: subscription_plans.

Ports the effective SQLite table of platform subscription-plan definitions
(trial/basic/standard/premium, each keyed by a stable `code`). The table has
no foreign keys in the SQLite source, and no other table references it by id
-- every join in the application looks plans up by `code` -- so it can be
ported standalone. REAL amount columns map to DOUBLE PRECISION and
boolean-like 0/1 flags map to BIGINT, matching the house conversion used
throughout this migration series. This migration does not alter SQLite
startup, SQLite migrations, or offline sync.
"""
from __future__ import annotations

from postgres_migrations import PostgresMigration

MIGRATION_VERSION = 165
MIGRATION_NAME = "create_subscription_plans"

MIGRATION_STATEMENTS = (
    """CREATE TABLE IF NOT EXISTS subscription_plans (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        code TEXT NOT NULL UNIQUE,
        name TEXT NOT NULL,
        price_ngn DOUBLE PRECISION NOT NULL DEFAULT 0,
        billing_days BIGINT NOT NULL DEFAULT 365,
        max_students BIGINT,
        max_teachers BIGINT,
        max_storage_mb BIGINT,
        features_json TEXT NOT NULL DEFAULT '{}',
        is_active BIGINT NOT NULL DEFAULT 1,
        created_at TEXT DEFAULT CURRENT_TIMESTAMP,
        updated_at TEXT DEFAULT CURRENT_TIMESTAMP
    )""",
    "CREATE INDEX IF NOT EXISTS idx_subscription_plans_active ON subscription_plans (is_active)",
)
MIGRATION_SOURCE = ";\n\n".join(MIGRATION_STATEMENTS)

_EXPECTED_COLUMNS = {
    "id": ("bigint", True), "code": ("text", True), "name": ("text", True),
    "price_ngn": ("double precision", True), "billing_days": ("bigint", True),
    "max_students": ("bigint", False), "max_teachers": ("bigint", False),
    "max_storage_mb": ("bigint", False), "features_json": ("text", True),
    "is_active": ("bigint", True), "created_at": ("text", False),
    "updated_at": ("text", False),
}


def apply_subscription_plans(conn) -> None:
    for statement in MIGRATION_STATEMENTS:
        conn.execute(statement)

    rows = conn.execute(
        "SELECT column_name, data_type, is_nullable FROM information_schema.columns "
        "WHERE table_schema = current_schema() AND table_name = ? ORDER BY ordinal_position",
        ("subscription_plans",),
    ).fetchall()
    actual = {
        str(row["column_name"]): (str(row["data_type"]).lower(), str(row["is_nullable"]).upper() == "NO")
        for row in rows
    }
    missing = sorted(set(_EXPECTED_COLUMNS) - set(actual))
    wrong = {name: {"actual": actual[name], "expected": expected}
             for name, expected in _EXPECTED_COLUMNS.items() if name in actual and actual[name] != expected}
    if missing or wrong or set(actual) != set(_EXPECTED_COLUMNS):
        raise RuntimeError(f"subscription_plans columns incompatible: missing={missing}, wrong={wrong}")

    constraints = conn.execute(
        "SELECT constraint_name, constraint_type FROM information_schema.table_constraints "
        "WHERE table_schema = current_schema() AND table_name = ?", ("subscription_plans",),
    ).fetchall()
    actual_constraints = {str(r["constraint_name"]): str(r["constraint_type"]).upper() for r in constraints}
    expected_constraints = {
        "subscription_plans_pkey": "PRIMARY KEY",
        "subscription_plans_code_key": "UNIQUE",
    }
    if actual_constraints != expected_constraints:
        raise RuntimeError(f"subscription_plans constraints incompatible: {actual_constraints}")

    rows = conn.execute(
        "SELECT indexname, indexdef FROM pg_indexes WHERE schemaname = current_schema() AND tablename = ?",
        ("subscription_plans",),
    ).fetchall()
    indexes = {str(r["indexname"]): str(r["indexdef"]).lower().replace('"', '') for r in rows}
    expected_indexes = {"subscription_plans_pkey", "subscription_plans_code_key", "idx_subscription_plans_active"}
    if set(indexes) != expected_indexes:
        raise RuntimeError(f"subscription_plans indexes incompatible: {sorted(indexes)}")
    if "is_active" not in indexes["idx_subscription_plans_active"]:
        raise RuntimeError("subscription_plans active-flag index is incompatible")

    fk_rows = conn.execute(
        "SELECT constraint_name FROM information_schema.table_constraints "
        "WHERE table_schema = current_schema() AND table_name = ? AND constraint_type = 'FOREIGN KEY'",
        ("subscription_plans",),
    ).fetchall()
    if fk_rows:
        raise RuntimeError("subscription_plans has unexpected foreign keys")

    triggers = conn.execute(
        "SELECT trigger_name FROM information_schema.triggers "
        "WHERE trigger_schema = current_schema() AND event_object_table = ?",
        ("subscription_plans",),
    ).fetchall()
    if triggers:
        raise RuntimeError("subscription_plans has unexpected triggers")


def migration() -> PostgresMigration:
    return PostgresMigration(version=MIGRATION_VERSION, name=MIGRATION_NAME,
                             apply=apply_subscription_plans, source=MIGRATION_SOURCE)
