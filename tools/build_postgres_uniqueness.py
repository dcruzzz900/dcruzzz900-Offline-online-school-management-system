#!/usr/bin/env python3
"""Generate PostgreSQL uniqueness indexes and identity guard triggers.

The unique indexes are the concurrency-safe source of truth. Trigger checks
retain useful legacy error messages for ordinary conflicts. This generator is
fail-closed and never connects to a database.
"""
from __future__ import annotations
import argparse, json, re
from pathlib import Path

IDENT = re.compile(r'^[a-z][a-z0-9_]*$')
EXPECTED = {
    'trg_students_admission_unique_ins', 'trg_students_admission_unique_upd',
    'trg_users_identity_unique_ins', 'trg_users_identity_unique_upd',
    'trg_users_signup_name_lock',
}

def qi(s: str) -> str:
    if not IDENT.fullmatch(s):
        raise ValueError(f'Unsafe SQL identifier: {s!r}')
    return '"' + s + '"'

def validate(plan: dict, snapshot: dict) -> None:
    items = [x for x in plan['triggers'] if x.get('category') == 'cross_row_uniqueness']
    if {x.get('name') for x in items} != EXPECTED or len(items) != 5:
        raise ValueError('Cross-row uniqueness inventory differs from the five reviewed triggers')
    tables = {x['name']: {c['name'] for c in x['columns']} for x in snapshot['tables']}
    required = {'students': {'id','class_id','admission_no'},
                'users': {'id','username','email','staff_id','school_id','signup_name'}}
    for table, cols in required.items():
        if table not in tables or not cols <= tables[table]:
            raise ValueError(f'{table} missing required columns: {sorted(cols - tables.get(table,set()))}')
    for x in items:
        sql = re.sub(r'\s+', ' ', x.get('source_sql','')).lower()
        if x['name'].startswith('trg_students_'):
            for token in ('students','admission_no','class_id','lower(trim('):
                if token not in sql: raise ValueError(f'Unexpected admission trigger SQL: {x["name"]}')
        elif x['name'] in ('trg_users_identity_unique_ins','trg_users_identity_unique_upd'):
            for token in ('users','username','email','staff_id','school_id','lower('):
                if token not in sql: raise ValueError(f'Unexpected user identity trigger SQL: {x["name"]}')
        elif 'signup_name' not in sql or 'permanent identity record' not in sql:
            raise ValueError('Unexpected signup-name lock source SQL')

def generate(plan: dict, snapshot: dict) -> str:
    validate(plan, snapshot)
    q = qi
    out = [
        '-- Generated by tools/build_postgres_uniqueness.py',
        '-- Unique indexes are authoritative and safe under concurrent transactions.',
        '-- Trigger checks preserve legacy-friendly errors for non-racing conflicts.',
        '-- Review POSTGRES_UNIQUENESS.md and resolve preflight duplicates before applying.', '',
        'DO $preflight$', 'BEGIN',
        "  IF EXISTS (SELECT 1 FROM students WHERE class_id IS NOT NULL AND admission_no IS NOT NULL GROUP BY class_id, lower(btrim(admission_no)) HAVING count(*) > 1) THEN",
        "    RAISE EXCEPTION 'Duplicate admission numbers exist within a class; resolve them before creating the unique index';", '  END IF;',
        "  IF EXISTS (SELECT 1 FROM users WHERE username IS NOT NULL GROUP BY lower(username) HAVING count(*) > 1) THEN",
        "    RAISE EXCEPTION 'Duplicate usernames exist; resolve them before creating the unique index';", '  END IF;',
        "  IF EXISTS (SELECT 1 FROM users WHERE email IS NOT NULL AND email <> '' GROUP BY lower(email) HAVING count(*) > 1) THEN",
        "    RAISE EXCEPTION 'Duplicate email addresses exist; resolve them before creating the unique index';", '  END IF;',
        "  IF EXISTS (SELECT 1 FROM users WHERE school_id IS NOT NULL AND staff_id IS NOT NULL AND staff_id <> '' GROUP BY school_id, lower(staff_id) HAVING count(*) > 1) THEN",
        "    RAISE EXCEPTION 'Duplicate staff IDs exist within a school; resolve them before creating the unique index';", '  END IF;',
        'END;', '$preflight$;', '',
        'CREATE UNIQUE INDEX IF NOT EXISTS uq_students_class_admission_ci',
        '  ON students (class_id, lower(btrim(admission_no)))',
        '  WHERE class_id IS NOT NULL AND admission_no IS NOT NULL;',
        'CREATE UNIQUE INDEX IF NOT EXISTS uq_users_username_ci',
        '  ON users (lower(username)) WHERE username IS NOT NULL;',
        "CREATE UNIQUE INDEX IF NOT EXISTS uq_users_email_ci ON users (lower(email)) WHERE email IS NOT NULL AND email <> '';",
        "CREATE UNIQUE INDEX IF NOT EXISTS uq_users_school_staff_id_ci ON users (school_id, lower(staff_id)) WHERE school_id IS NOT NULL AND staff_id IS NOT NULL AND staff_id <> '';", '',
        'CREATE OR REPLACE FUNCTION app_guard_identity_uniqueness()', 'RETURNS trigger', 'LANGUAGE plpgsql', 'AS $function$', 'BEGIN',
        "  IF TG_TABLE_NAME = 'students' THEN",
        "    IF NEW.admission_no IS NOT NULL AND NEW.class_id IS NOT NULL AND EXISTS (SELECT 1 FROM students s WHERE s.class_id = NEW.class_id AND lower(btrim(s.admission_no)) = lower(btrim(NEW.admission_no)) AND (TG_OP = 'INSERT' OR s.id <> OLD.id)) THEN",
        "      RAISE EXCEPTION 'Admission No. / Register No. already exists in this class' USING ERRCODE = '23505';", '    END IF;',
        "  ELSIF TG_TABLE_NAME = 'users' THEN",
        "    IF NEW.email IS NOT NULL AND NEW.email <> '' AND EXISTS (SELECT 1 FROM users u WHERE lower(u.email) = lower(NEW.email) AND (TG_OP = 'INSERT' OR u.id <> OLD.id)) THEN",
        "      RAISE EXCEPTION 'Username, email or Staff ID already exists' USING ERRCODE = '23505';", '    END IF;',
        "    IF NEW.staff_id IS NOT NULL AND NEW.staff_id <> '' AND NEW.school_id IS NOT NULL AND EXISTS (SELECT 1 FROM users u WHERE u.school_id = NEW.school_id AND lower(u.staff_id) = lower(NEW.staff_id) AND (TG_OP = 'INSERT' OR u.id <> OLD.id)) THEN",
        "      RAISE EXCEPTION 'Username, email or Staff ID already exists' USING ERRCODE = '23505';", '    END IF;',
        "    IF NEW.username IS NOT NULL AND EXISTS (SELECT 1 FROM users u WHERE lower(u.username) = lower(NEW.username) AND (TG_OP = 'INSERT' OR u.id <> OLD.id)) THEN",
        "      RAISE EXCEPTION 'Username, email or Staff ID already exists' USING ERRCODE = '23505';", '    END IF;',
        '  END IF;', '  RETURN NEW;', 'END;', '$function$;', '',
        'DROP TRIGGER IF EXISTS trg_students_admission_unique_ins_pg ON students;',
        'CREATE TRIGGER trg_students_admission_unique_ins_pg BEFORE INSERT ON students FOR EACH ROW EXECUTE FUNCTION app_guard_identity_uniqueness();',
        'DROP TRIGGER IF EXISTS trg_students_admission_unique_upd_pg ON students;',
        'CREATE TRIGGER trg_students_admission_unique_upd_pg BEFORE UPDATE OF admission_no, class_id ON students FOR EACH ROW EXECUTE FUNCTION app_guard_identity_uniqueness();',
        'DROP TRIGGER IF EXISTS trg_users_identity_unique_ins_pg ON users;',
        'CREATE TRIGGER trg_users_identity_unique_ins_pg BEFORE INSERT ON users FOR EACH ROW EXECUTE FUNCTION app_guard_identity_uniqueness();',
        'DROP TRIGGER IF EXISTS trg_users_identity_unique_upd_pg ON users;',
        '-- Include school_id: staff identity uniqueness depends on the school as well.',
        'CREATE TRIGGER trg_users_identity_unique_upd_pg BEFORE UPDATE OF username, email, staff_id, school_id ON users FOR EACH ROW EXECUTE FUNCTION app_guard_identity_uniqueness();', '',
        'CREATE OR REPLACE FUNCTION app_guard_signup_name_immutable()', 'RETURNS trigger', 'LANGUAGE plpgsql', 'AS $function$', 'BEGIN',
        "  IF OLD.signup_name IS NOT NULL AND OLD.signup_name <> '' AND NEW.signup_name IS DISTINCT FROM OLD.signup_name THEN",
        "    RAISE EXCEPTION 'The signup name is a permanent identity record' USING ERRCODE = '55000';", '  END IF;',
        '  RETURN NEW;', 'END;', '$function$;', '',
        'DROP TRIGGER IF EXISTS trg_users_signup_name_lock_pg ON users;',
        'CREATE TRIGGER trg_users_signup_name_lock_pg BEFORE UPDATE OF signup_name ON users FOR EACH ROW EXECUTE FUNCTION app_guard_signup_name_immutable();', ''
    ]
    return '\n'.join(out)

def main():
    ap=argparse.ArgumentParser(); ap.add_argument('--inventory',default='postgres_trigger_porting_plan.json'); ap.add_argument('--snapshot',default='postgres_effective_schema_snapshot.json'); ap.add_argument('--output',default='postgres_uniqueness.sql'); a=ap.parse_args()
    sql=generate(json.loads(Path(a.inventory).read_text()),json.loads(Path(a.snapshot).read_text()))
    Path(a.output).write_text(sql); print('Generated 4 concurrency-safe unique indexes and 5 PostgreSQL identity guard triggers.')
if __name__=='__main__': main()
