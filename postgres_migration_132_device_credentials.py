"""PostgreSQL-native migration 132: device_credentials.

Ports device-bound credentials, school/user relationships, lookup indexes,
unique device IDs, and the source tenant-stamping insert trigger. This migration
remains separate from SQLite startup and the existing offline-sync path.
"""
from __future__ import annotations

from postgres_migrations import PostgresMigration

MIGRATION_VERSION = 132
MIGRATION_NAME = "create_device_credentials"

MIGRATION_STATEMENTS = (
    """CREATE TABLE IF NOT EXISTS device_credentials (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        school_id INTEGER NOT NULL,
        tenant_id TEXT,
        user_id INTEGER NOT NULL,
        device_id TEXT NOT NULL,
        device_label TEXT,
        secret_hash TEXT NOT NULL,
        role_snapshot TEXT NOT NULL,
        position_snapshot TEXT,
        issued_at TEXT DEFAULT CURRENT_TIMESTAMP,
        last_verified_at TEXT,
        expires_at TEXT NOT NULL,
        revoked BIGINT DEFAULT 0,
        revoked_reason TEXT,
        CONSTRAINT uq_device_credentials_device_id UNIQUE (device_id),
        CONSTRAINT fk_device_credentials_school FOREIGN KEY (school_id) REFERENCES schools(id),
        CONSTRAINT fk_device_credentials_user FOREIGN KEY (user_id) REFERENCES users(id)
    )""",
    "CREATE INDEX IF NOT EXISTS idx_device_credentials_tenant ON device_credentials (tenant_id)",
    "CREATE INDEX IF NOT EXISTS idx_device_credentials_school ON device_credentials (school_id)",
    "CREATE INDEX IF NOT EXISTS idx_device_credentials_user ON device_credentials (user_id)",
    """CREATE OR REPLACE FUNCTION stamp_device_credentials_tenant()
    RETURNS trigger LANGUAGE plpgsql AS $$
    BEGIN
        IF NEW.tenant_id IS NULL OR NEW.tenant_id = '' THEN
            UPDATE device_credentials
               SET tenant_id = (SELECT tenant_id FROM schools WHERE id = NEW.school_id)
             WHERE id = NEW.id;
        END IF;
        RETURN NEW;
    END;
    $$""",
    "DROP TRIGGER IF EXISTS trg_device_credentials_tenant_stamp ON device_credentials",
    "CREATE TRIGGER trg_device_credentials_tenant_stamp AFTER INSERT ON device_credentials FOR EACH ROW EXECUTE FUNCTION stamp_device_credentials_tenant()",
)
MIGRATION_SOURCE = ";\n\n".join(MIGRATION_STATEMENTS)

_EXPECTED_COLUMNS = {
    "id": ("bigint", True), "school_id": ("integer", True),
    "tenant_id": ("text", False), "user_id": ("integer", True),
    "device_id": ("text", True), "device_label": ("text", False),
    "secret_hash": ("text", True), "role_snapshot": ("text", True),
    "position_snapshot": ("text", False), "issued_at": ("text", False),
    "last_verified_at": ("text", False), "expires_at": ("text", True),
    "revoked": ("bigint", False), "revoked_reason": ("text", False),
}
_EXPECTED_FKS = {
    ("school_id", "schools", "id"),
    ("user_id", "users", "id"),
}
_EXPECTED_TRIGGERS = {"trg_device_credentials_tenant_stamp"}


def apply_device_credentials(conn) -> None:
    for table in ("schools", "users"):
        row = conn.execute(
            "SELECT column_name, data_type FROM information_schema.columns "
            "WHERE table_schema = current_schema() AND table_name = ? AND column_name = ?",
            (table, "id"),
        ).fetchone()
        if row is None or str(row["data_type"]).lower() != "integer":
            raise RuntimeError(f"device_credentials requires {table}.id INTEGER")

    for statement in MIGRATION_STATEMENTS:
        conn.execute(statement)

    rows = conn.execute(
        "SELECT column_name, data_type, is_nullable FROM information_schema.columns "
        "WHERE table_schema = current_schema() AND table_name = ? ORDER BY ordinal_position",
        ("device_credentials",),
    ).fetchall()
    actual = {
        str(r["column_name"]): (str(r["data_type"]).lower(), str(r["is_nullable"]).upper() == "NO")
        for r in rows
    }
    missing = sorted(set(_EXPECTED_COLUMNS) - set(actual))
    wrong = {n: {"actual": actual[n], "expected": e} for n, e in _EXPECTED_COLUMNS.items()
             if n in actual and actual[n] != e}
    if missing or wrong or set(actual) != set(_EXPECTED_COLUMNS):
        raise RuntimeError(f"device_credentials columns incompatible: missing={missing}, wrong={wrong}")

    fk_rows = conn.execute(
        "SELECT kcu.column_name, ccu.table_name AS foreign_table_name, "
        "ccu.column_name AS foreign_column_name "
        "FROM information_schema.table_constraints tc "
        "JOIN information_schema.key_column_usage kcu ON tc.constraint_name = kcu.constraint_name "
        "AND tc.constraint_schema = kcu.constraint_schema "
        "JOIN information_schema.constraint_column_usage ccu ON ccu.constraint_name = tc.constraint_name "
        "AND ccu.constraint_schema = tc.constraint_schema "
        "WHERE tc.constraint_type = 'FOREIGN KEY' AND tc.table_schema = current_schema() "
        "AND tc.table_name = ?", ("device_credentials",),
    ).fetchall()
    actual_fks = {(str(r["column_name"]), str(r["foreign_table_name"]), str(r["foreign_column_name"])) for r in fk_rows}
    if actual_fks != _EXPECTED_FKS:
        raise RuntimeError(f"device_credentials foreign keys incompatible: {sorted(actual_fks)}")

    constraint_rows = conn.execute(
        "SELECT constraint_name, constraint_type FROM information_schema.table_constraints "
        "WHERE table_schema = current_schema() AND table_name = ?", ("device_credentials",),
    ).fetchall()
    constraints = {str(r["constraint_name"]): str(r["constraint_type"]).upper() for r in constraint_rows}
    expected_constraints = {
        "device_credentials_pkey": "PRIMARY KEY",
        "uq_device_credentials_device_id": "UNIQUE",
        "fk_device_credentials_school": "FOREIGN KEY",
        "fk_device_credentials_user": "FOREIGN KEY",
    }
    if constraints != expected_constraints:
        raise RuntimeError(f"device_credentials constraints incompatible: {constraints}")

    index_rows = conn.execute(
        "SELECT indexname, indexdef FROM pg_indexes WHERE schemaname = current_schema() AND tablename = ?",
        ("device_credentials",),
    ).fetchall()
    indexes = {str(r["indexname"]): str(r["indexdef"]).lower().replace('"', "") for r in index_rows}
    expected_indexes = {
        "device_credentials_pkey", "uq_device_credentials_device_id",
        "idx_device_credentials_tenant", "idx_device_credentials_school", "idx_device_credentials_user",
    }
    if set(indexes) != expected_indexes:
        raise RuntimeError(f"device_credentials indexes incompatible: {sorted(indexes)}")
    for name, column in (
        ("idx_device_credentials_tenant", "tenant_id"),
        ("idx_device_credentials_school", "school_id"),
        ("idx_device_credentials_user", "user_id"),
    ):
        if f"({column})" not in indexes[name]:
            raise RuntimeError(f"device_credentials index {name} is incompatible")
    unique_device = indexes["uq_device_credentials_device_id"]
    if "unique index" not in unique_device or "(device_id)" not in unique_device:
        raise RuntimeError("device_credentials device_id unique index is incompatible")

    trigger_rows = conn.execute(
        "SELECT trigger_name FROM information_schema.triggers "
        "WHERE trigger_schema = current_schema() AND event_object_table = ?", ("device_credentials",),
    ).fetchall()
    actual_triggers = {str(r["trigger_name"]) for r in trigger_rows}
    if actual_triggers != _EXPECTED_TRIGGERS:
        raise RuntimeError(f"device_credentials triggers incompatible: {sorted(actual_triggers)}")


def migration() -> PostgresMigration:
    return PostgresMigration(
        version=MIGRATION_VERSION,
        name=MIGRATION_NAME,
        apply=apply_device_credentials,
        source=MIGRATION_SOURCE,
    )
