import pytest

from postgres_migration_135_grading_config_audit import (
    MIGRATION_NAME,
    MIGRATION_SOURCE,
    MIGRATION_VERSION,
    apply_grading_config_audit,
    migration,
)
from postgres_migration_registry import POSTGRES_MIGRATIONS


class Result:
    def __init__(self, rows):
        self.rows = rows

    def fetchall(self):
        return self.rows

    def fetchone(self):
        return self.rows[0] if self.rows else None


class FakeConnection:
    def __init__(self, columns=None, fks=None, indexes=None, triggers=None, school_id_type="integer"):
        expected = {
            "id": ("bigint", True), "school_id": ("integer", True),
            "old_ca1_max": ("double precision", False), "old_ca2_max": ("double precision", False),
            "old_ca3_max": ("double precision", False), "old_exam_max": ("double precision", False),
            "new_ca1_max": ("double precision", False), "new_ca2_max": ("double precision", False),
            "new_ca3_max": ("double precision", False), "new_exam_max": ("double precision", False),
            "affected_count": ("bigint", True), "affected_summary": ("text", False),
            "changed_by": ("bigint", False), "changed_by_name": ("text", False),
            "changed_at": ("text", False),
        }
        self.columns = columns if columns is not None else [
            {"column_name": name, "data_type": data_type, "is_nullable": "NO" if required else "YES"}
            for name, (data_type, required) in expected.items()
        ]
        self.fks = fks if fks is not None else [
            {"column_name": "school_id", "foreign_table_name": "schools", "foreign_column_name": "id"}
        ]
        self.indexes = indexes if indexes is not None else [
            {"indexname": "grading_config_audit_pkey", "indexdef": "CREATE UNIQUE INDEX grading_config_audit_pkey ON public.grading_config_audit USING btree (id)"},
            {"indexname": "idx_grading_config_audit_school", "indexdef": "CREATE INDEX idx_grading_config_audit_school ON public.grading_config_audit USING btree (school_id, changed_at)"},
        ]
        self.triggers = triggers if triggers is not None else []
        self.school_id_type = school_id_type
        self.calls = []

    def execute(self, sql, params=()):
        self.calls.append((sql, params))
        if "information_schema.columns" in sql and "schools" in params:
            return Result([{"column_name": "id", "data_type": self.school_id_type}])
        if "information_schema.columns" in sql:
            return Result(self.columns)
        if "information_schema.table_constraints" in sql:
            return Result(self.fks)
        if "FROM pg_indexes" in sql:
            return Result(self.indexes)
        if "information_schema.triggers" in sql:
            return Result(self.triggers)
        return Result([])


def test_registry_and_migration_identity():
    assert MIGRATION_VERSION == 135
    assert MIGRATION_NAME == "create_grading_config_audit"
    assert [item.version for item in POSTGRES_MIGRATIONS] == list(range(100, 143))
    assert next(item for item in POSTGRES_MIGRATIONS if item.version == 135).name == MIGRATION_NAME
    assert migration().version == 135


def test_ddl_preserves_columns_school_relationship_and_lookup_index():
    sql = MIGRATION_SOURCE.lower()
    for fragment in (
        "id bigint generated by default as identity primary key",
        "school_id integer not null",
        "old_ca1_max double precision",
        "new_exam_max double precision",
        "affected_count bigint not null default 0",
        "changed_at text default current_timestamp",
        "references schools(id)",
        "on grading_config_audit (school_id, changed_at)",
    ):
        assert fragment in sql


def test_apply_executes_and_validates_migration():
    conn = FakeConnection()
    apply_grading_config_audit(conn)
    assert any("CREATE TABLE IF NOT EXISTS grading_config_audit" in sql for sql, _ in conn.calls)
    assert any("CREATE INDEX IF NOT EXISTS idx_grading_config_audit_school" in sql for sql, _ in conn.calls)


def test_rejects_incompatible_school_primary_key_type():
    with pytest.raises(RuntimeError, match="schools.id INTEGER"):
        apply_grading_config_audit(FakeConnection(school_id_type="bigint"))


def test_rejects_wrong_columns():
    with pytest.raises(RuntimeError, match="columns incompatible"):
        apply_grading_config_audit(FakeConnection(columns=[]))


def test_rejects_wrong_foreign_key():
    with pytest.raises(RuntimeError, match="foreign keys incompatible"):
        apply_grading_config_audit(FakeConnection(fks=[]))


def test_rejects_wrong_indexes():
    with pytest.raises(RuntimeError, match="indexes incompatible"):
        apply_grading_config_audit(FakeConnection(indexes=[]))


def test_rejects_unexpected_triggers():
    with pytest.raises(RuntimeError, match="unexpectedly has triggers"):
        apply_grading_config_audit(FakeConnection(triggers=[{"trigger_name": "unexpected_trigger"}]))
