"""PostgreSQL-native migration 109: announcements.

Faithful port of the effective SQLite table definition. The source declares
one non-unique lookup index and no foreign keys or triggers. Timestamp fields
remain TEXT for compatibility with existing application SQL and formatting.
"""
from __future__ import annotations

from postgres_migrations import PostgresMigration

MIGRATION_VERSION = 109
MIGRATION_NAME = "create_announcements"

MIGRATION_STATEMENTS = (
    r'''CREATE TABLE IF NOT EXISTS announcements (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        school_id BIGINT,
        title TEXT NOT NULL,
        message TEXT NOT NULL,
        audience TEXT NOT NULL DEFAULT 'all',
        level TEXT NOT NULL DEFAULT 'info',
        dismissible BIGINT NOT NULL DEFAULT 1,
        starts_at TEXT,
        expires_at TEXT,
        is_active BIGINT NOT NULL DEFAULT 1,
        created_by BIGINT,
        created_by_label TEXT,
        created_at TEXT DEFAULT CURRENT_TIMESTAMP,
        display_seconds BIGINT NOT NULL DEFAULT 0
    )''',
    "CREATE INDEX IF NOT EXISTS idx_announcements_school_expiry ON announcements (school_id, expires_at)",
)
MIGRATION_SOURCE = ";\n\n".join(MIGRATION_STATEMENTS)

_EXPECTED_COLUMNS = {
    "id": ("bigint", True),
    "school_id": ("bigint", False),
    "title": ("text", True),
    "message": ("text", True),
    "audience": ("text", True),
    "level": ("text", True),
    "dismissible": ("bigint", True),
    "starts_at": ("text", False),
    "expires_at": ("text", False),
    "is_active": ("bigint", True),
    "created_by": ("bigint", False),
    "created_by_label": ("text", False),
    "created_at": ("text", False),
    "display_seconds": ("bigint", True),
}


def apply_announcements(conn) -> None:
    for statement in MIGRATION_STATEMENTS:
        conn.execute(statement)

    rows = conn.execute(
        "SELECT column_name, data_type, is_nullable FROM information_schema.columns "
        "WHERE table_schema = current_schema() AND table_name = ? ORDER BY ordinal_position",
        ("announcements",),
    ).fetchall()
    actual = {
        str(row["column_name"]): (str(row["data_type"]).lower(), str(row["is_nullable"]).upper() == "NO")
        for row in rows
    }
    missing = sorted(set(_EXPECTED_COLUMNS) - set(actual))
    wrong = {
        name: {"actual": actual[name], "expected": expected}
        for name, expected in _EXPECTED_COLUMNS.items()
        if name in actual and actual[name] != expected
    }
    if missing or wrong:
        raise RuntimeError(
            "announcements schema is incompatible; "
            f"missing columns={missing}, incompatible columns={wrong}"
        )

    constraints = conn.execute(
        "SELECT constraint_type FROM information_schema.table_constraints "
        "WHERE table_schema = current_schema() AND table_name = ?",
        ("announcements",),
    ).fetchall()
    if any(str(row["constraint_type"]).upper() == "FOREIGN KEY" for row in constraints):
        raise RuntimeError("announcements has unexpected foreign-key constraints")

    index_rows = conn.execute(
        "SELECT indexname, indexdef FROM pg_indexes "
        "WHERE schemaname = current_schema() AND tablename = ?",
        ("announcements",),
    ).fetchall()
    indexes = {str(row["indexname"]): str(row["indexdef"]).lower().replace('"', "") for row in index_rows}
    expected_indexes = {"announcements_pkey", "idx_announcements_school_expiry"}
    if set(indexes) != expected_indexes:
        raise RuntimeError(f"announcements indexes are incompatible: {sorted(indexes)}")
    if "(school_id, expires_at)" not in indexes["idx_announcements_school_expiry"]:
        raise RuntimeError("announcements school/expiry index has an incompatible definition")

    triggers = conn.execute(
        "SELECT trigger_name FROM information_schema.triggers "
        "WHERE trigger_schema = current_schema() AND event_object_table = ?",
        ("announcements",),
    ).fetchall()
    if triggers:
        raise RuntimeError("announcements has unexpected triggers")


def migration() -> PostgresMigration:
    return PostgresMigration(
        version=MIGRATION_VERSION,
        name=MIGRATION_NAME,
        apply=apply_announcements,
        source=MIGRATION_SOURCE,
    )
