#!/usr/bin/env python3
"""Run the application's real SQLite migrations in memory and inventory its final schema.

This is a source-of-truth snapshot for PostgreSQL porting. It does NOT translate
SQLite DDL or generate executable PostgreSQL migrations.
"""
from __future__ import annotations

import argparse
import importlib
import json
import sqlite3
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = ROOT / "postgres_effective_schema_snapshot.json"


def _quote_ident(value: str) -> str:
    return '"' + value.replace('"', '""') + '"'


def snapshot_schema(conn: sqlite3.Connection) -> dict[str, Any]:
    objects = conn.execute(
        "SELECT type, name, tbl_name, sql FROM sqlite_master "
        "WHERE type IN ('table','index','trigger','view') "
        "AND name NOT LIKE 'sqlite_%' AND sql IS NOT NULL "
        "ORDER BY CASE type WHEN 'table' THEN 1 WHEN 'view' THEN 2 "
        "WHEN 'index' THEN 3 ELSE 4 END, name"
    ).fetchall()

    tables: list[dict[str, Any]] = []
    for obj_type, name, table_name, sql in objects:
        if obj_type != "table":
            continue
        qname = _quote_ident(name)
        columns = conn.execute(f"PRAGMA table_info({qname})").fetchall()
        foreign_keys = conn.execute(f"PRAGMA foreign_key_list({qname})").fetchall()
        indexes = conn.execute(f"PRAGMA index_list({qname})").fetchall()
        tables.append({
            "name": name,
            "create_sql": sql,
            "columns": [
                {"cid": c[0], "name": c[1], "type": c[2], "notnull": bool(c[3]),
                 "default": c[4], "primary_key_position": c[5]}
                for c in columns
            ],
            "foreign_keys": [
                {"id": fk[0], "sequence": fk[1], "referenced_table": fk[2],
                 "from_column": fk[3], "to_column": fk[4],
                 "on_update": fk[5], "on_delete": fk[6], "match": fk[7]}
                for fk in foreign_keys
            ],
            "indexes": [
                {"name": ix[1], "unique": bool(ix[2]), "origin": ix[3],
                 "partial": bool(ix[4]) if len(ix) > 4 else False}
                for ix in indexes
            ],
        })

    other_objects = [
        {"type": row[0], "name": row[1], "table": row[2], "sql": row[3]}
        for row in objects if row[0] != "table"
    ]
    counts = {
        "tables": len(tables),
        "views": sum(1 for o in other_objects if o["type"] == "view"),
        "indexes": sum(1 for o in other_objects if o["type"] == "index"),
        "triggers": sum(1 for o in other_objects if o["type"] == "trigger"),
        "columns": sum(len(t["columns"]) for t in tables),
        "foreign_keys": sum(len(t["foreign_keys"]) for t in tables),
    }
    version_row = conn.execute("SELECT version FROM schema_version LIMIT 1").fetchone()
    step_count = conn.execute("SELECT COUNT(*) FROM schema_steps").fetchone()[0]
    return {
        "source_database": "SQLite in-memory database",
        "scope_warning": (
            "This is the final SQLite schema after running the application's real migration "
            "registry. It is an inventory/reference only; SQLite SQL is not PostgreSQL SQL. "
            "No production data is included."
        ),
        "migration_state": {
            "schema_version": int(version_row[0]) if version_row else None,
            "applied_named_steps": int(step_count),
        },
        "counts": counts,
        "tables": tables,
        "other_objects": other_objects,
    }


def build_snapshot(db_module) -> dict[str, Any]:
    conn = sqlite3.connect(":memory:")
    conn.row_factory = sqlite3.Row
    try:
        # Match the application's migration connection setting: migrations
        # themselves explicitly manage commits; foreign-key enforcement is off.
        conn.execute("PRAGMA foreign_keys = OFF")
        db_module.run_migrations(conn)
        return snapshot_schema(conn)
    finally:
        conn.close()


def render_markdown(snapshot: dict[str, Any]) -> str:
    c = snapshot["counts"]
    state = snapshot["migration_state"]
    lines = [
        "# PostgreSQL Porting Reference — Effective v113 SQLite Schema", "",
        "> This document is generated by executing the application's actual SQLite migration "
        "registry against an empty in-memory database. It is a reference for manual PostgreSQL "
        "porting, not executable PostgreSQL DDL. No user data is included.", "",
        "## Snapshot totals", "",
        f"- Schema version high-water mark: **{state['schema_version']}**",
        f"- Applied named migration steps: **{state['applied_named_steps']}**",
        f"- Tables: **{c['tables']}**",
        f"- Columns: **{c['columns']}**",
        f"- Foreign-key declarations: **{c['foreign_keys']}**",
        f"- Explicit indexes: **{c['indexes']}**",
        f"- Triggers: **{c['triggers']}**",
        f"- Views: **{c['views']}**", "",
        "## Table inventory", "",
        "| Table | Columns | Foreign keys | Indexes |", "|---|---:|---:|---:|",
    ]
    for table in snapshot["tables"]:
        lines.append(
            f"| `{table['name']}` | {len(table['columns'])} | "
            f"{len(table['foreign_keys'])} | {len(table['indexes'])} |"
        )
    lines += ["", "## SQLite-specific objects requiring explicit porting", ""]
    for obj_type in ("trigger", "view", "index"):
        selected = [o for o in snapshot["other_objects"] if o["type"] == obj_type]
        lines.append(f"### {obj_type.title()}s ({len(selected)})")
        lines.append("")
        for obj in selected:
            lines.append(f"- `{obj['name']}` on `{obj['table']}`")
        lines.append("")
    lines += [
        "## Porting cautions", "",
        "- Preserve each table's primary keys, uniqueness, nullability, defaults, and foreign keys.",
        "- Review integer-backed booleans, timestamp/text conventions, JSON/BLOB columns, and generated IDs.",
        "- Rewrite trigger bodies as PostgreSQL functions plus triggers; do not copy SQLite trigger SQL.",
        "- Review index predicates and expressions against PostgreSQL semantics.",
        "- Validate tenant isolation and offline-sync invariants with integration tests.",
        "- The snapshot is built from an empty database, so it describes schema only, not migrated customer data.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--markdown", type=Path, default=ROOT / "POSTGRES_EFFECTIVE_SCHEMA.md")
    parser.add_argument("--db-module", default="db", help="Importable application database module")
    args = parser.parse_args()
    db_module = importlib.import_module(args.db_module)
    snapshot = build_snapshot(db_module)
    args.output.write_text(json.dumps(snapshot, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    args.markdown.write_text(render_markdown(snapshot), encoding="utf-8")
    print("Effective SQLite schema snapshot written.")
    print(json.dumps(snapshot["counts"], sort_keys=True))
    print("WARNING: this is an SQLite schema reference, not PostgreSQL DDL.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
