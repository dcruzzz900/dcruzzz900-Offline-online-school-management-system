import pytest
from postgres_migration_102_activation_attempts import (
    MIGRATION_NAME, MIGRATION_SOURCE, MIGRATION_VERSION,
    apply_activation_attempts, migration,
)
from postgres_migration_registry import POSTGRES_MIGRATIONS

class Result:
    def __init__(self, rows): self.rows=rows
    def fetchall(self): return self.rows
    def fetchone(self): return self.rows[0] if self.rows else None

class FakeConnection:
    def __init__(self, columns=None, fk=False, indexes=None):
        expected={"id":"bigint","signup_id":"bigint","user_id":"bigint","school_id":"bigint","tenant_id":"text","attempt_number":"bigint","status":"text","failure_code":"text","failure_message_internal":"text","started_at":"text","completed_at":"text","retry_at":"text","created_at":"text","request_id":"text"}
        required={"id","attempt_number","status"}
        self.columns=columns or [{"column_name":n,"data_type":t,"is_nullable":"NO" if n in required else "YES"} for n,t in expected.items()]
        self.fk=fk
        self.indexes=indexes if indexes is not None else [{"indexname":"activation_attempts_pkey"}]
        self.calls=[]
    def execute(self,sql,params=()):
        self.calls.append((sql,params))
        if "information_schema.columns" in sql: return Result(self.columns)
        if "constraint_type = 'FOREIGN KEY'" in sql: return Result([{"?":1}] if self.fk else [])
        if "FROM pg_indexes" in sql: return Result(self.indexes)
        return Result([])

def test_metadata_and_registry():
    m=migration()
    assert (m.version,m.name,m.source)==(102,MIGRATION_NAME,MIGRATION_SOURCE)
    assert MIGRATION_VERSION==102 and MIGRATION_NAME=="create_activation_attempts"
    assert [x.version for x in POSTGRES_MIGRATIONS]==list(range(100, 188))

def test_creates_reviewed_table_shape():
    c=FakeConnection(); apply_activation_attempts(c)
    sql="\n".join(q for q,_ in c.calls)
    assert "activation_attempts" in sql and "GENERATED BY DEFAULT AS IDENTITY" in sql
    assert "attempt_number BIGINT NOT NULL DEFAULT 1" in sql
    assert "started_at TEXT DEFAULT CURRENT_TIMESTAMP" in sql

def test_rejects_missing_or_wrong_columns():
    cols=[dict(x) for x in FakeConnection().columns if x["column_name"]!="request_id"]
    with pytest.raises(RuntimeError,match="missing columns"):
        apply_activation_attempts(FakeConnection(columns=cols))
    cols=[dict(x) for x in FakeConnection().columns]
    cols[1]["data_type"]="character varying"
    with pytest.raises(RuntimeError,match="incompatible columns"):
        apply_activation_attempts(FakeConnection(columns=cols))

def test_rejects_unexpected_constraints_and_indexes():
    with pytest.raises(RuntimeError,match="unexpected foreign-key"):
        apply_activation_attempts(FakeConnection(fk=True))
    with pytest.raises(RuntimeError,match="unexpected secondary indexes"):
        apply_activation_attempts(FakeConnection(indexes=[{"indexname":"activation_attempts_pkey"},{"indexname":"extra_idx"}]))
