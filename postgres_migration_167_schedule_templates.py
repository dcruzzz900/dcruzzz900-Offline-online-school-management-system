"""PostgreSQL-native migration 167: schedule_templates.

Ports the effective SQLite table of named timetable schedule templates (the
bell-schedule skeleton that `schedule_slots` hangs off; one default template is
created per school by the application). The source declares three foreign keys
-- `school_id` -> `schools.id`, `academic_session_id` -> `sessions.id` and
`term_id` -> `terms.id` -- all to tables already ported, and all INTEGER keys,
so the referencing columns stay INTEGER (the migration refuses to run if a
parent key has a different type). The offline-sync columns that SQLite's
`_make_syncable()` adds later (`client_uuid`, `is_deleted`), the partial unique
client-UUID index, and the sync default/touch triggers are recreated so the
effective table matches the schema snapshot. `created_at`/`updated_at` keep
`TEXT DEFAULT CURRENT_TIMESTAMP`, as in migrations 129 and 165. 0/1 flags map
to BIGINT. The table has no uniqueness beyond its primary key in the source,
and the verification step asserts that. This is the second parent of
`schedule_slots`, which is why it is ported before it. This migration does not
alter SQLite startup, SQLite migrations, or offline sync.
"""
from __future__ import annotations

from postgres_migrations import PostgresMigration

MIGRATION_VERSION = 167
MIGRATION_NAME = "create_schedule_templates"

MIGRATION_STATEMENTS = (
    """CREATE TABLE IF NOT EXISTS schedule_templates (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        tenant_id TEXT NOT NULL,
        school_id INTEGER NOT NULL,
        academic_session_id INTEGER,
        term_id INTEGER,
        name TEXT NOT NULL,
        description TEXT,
        is_default BIGINT NOT NULL DEFAULT 0,
        status TEXT NOT NULL DEFAULT 'active',
        created_at TEXT DEFAULT CURRENT_TIMESTAMP,
        updated_at TEXT DEFAULT CURRENT_TIMESTAMP,
        client_uuid TEXT,
        is_deleted BIGINT DEFAULT 0,
        CONSTRAINT fk_schedule_templates_school FOREIGN KEY (school_id) REFERENCES schools(id),
        CONSTRAINT fk_schedule_templates_session FOREIGN KEY (academic_session_id) REFERENCES sessions(id),
        CONSTRAINT fk_schedule_templates_term FOREIGN KEY (term_id) REFERENCES terms(id)
    )""",
    "CREATE UNIQUE INDEX IF NOT EXISTS idx_schedule_templates_client_uuid "
    "ON schedule_templates (client_uuid) WHERE client_uuid IS NOT NULL",
    """CREATE OR REPLACE FUNCTION sync_schedule_templates_fields()
    RETURNS trigger LANGUAGE plpgsql AS $$
    DECLARE current_stamp TEXT; old_stamp TIMESTAMP;
    BEGIN
        IF TG_OP = 'INSERT' THEN
            IF NEW.client_uuid IS NULL THEN
                NEW.client_uuid := md5(random()::text || clock_timestamp()::text || pg_backend_pid()::text);
            END IF;
            IF NEW.updated_at IS NULL THEN
                NEW.updated_at := to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS');
            END IF;
            RETURN NEW;
        END IF;
        IF NEW.updated_at IS NOT DISTINCT FROM OLD.updated_at THEN
            current_stamp := to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS');
            IF OLD.updated_at IS NULL OR current_stamp > OLD.updated_at THEN
                NEW.updated_at := current_stamp;
            ELSE
                BEGIN
                    old_stamp := OLD.updated_at::timestamp;
                    NEW.updated_at := to_char(old_stamp + INTERVAL '1 second', 'YYYY-MM-DD"T"HH24:MI:SS');
                EXCEPTION WHEN others THEN
                    NEW.updated_at := current_stamp;
                END;
            END IF;
        END IF;
        RETURN NEW;
    END;
    $$""",
    "DROP TRIGGER IF EXISTS trg_schedule_templates_sync_defaults ON schedule_templates",
    "CREATE TRIGGER trg_schedule_templates_sync_defaults BEFORE INSERT ON schedule_templates "
    "FOR EACH ROW EXECUTE FUNCTION sync_schedule_templates_fields()",
    "DROP TRIGGER IF EXISTS trg_schedule_templates_sync_touch ON schedule_templates",
    "CREATE TRIGGER trg_schedule_templates_sync_touch BEFORE UPDATE ON schedule_templates "
    "FOR EACH ROW EXECUTE FUNCTION sync_schedule_templates_fields()",
)
MIGRATION_SOURCE = ";\n\n".join(MIGRATION_STATEMENTS)

_EXPECTED_COLUMNS = {
    "id": ("bigint", True), "tenant_id": ("text", True), "school_id": ("integer", True),
    "academic_session_id": ("integer", False), "term_id": ("integer", False),
    "name": ("text", True), "description": ("text", False), "is_default": ("bigint", True),
    "status": ("text", True), "created_at": ("text", False), "updated_at": ("text", False),
    "client_uuid": ("text", False), "is_deleted": ("bigint", False),
}
_EXPECTED_FOREIGN_KEYS = {
    ("school_id", "schools", "id"),
    ("academic_session_id", "sessions", "id"),
    ("term_id", "terms", "id"),
}
_EXPECTED_TRIGGERS = {"trg_schedule_templates_sync_defaults", "trg_schedule_templates_sync_touch"}


def apply_schedule_templates(conn) -> None:
    for parent in ("schools", "sessions", "terms"):
        row = conn.execute(
            "SELECT column_name, data_type FROM information_schema.columns "
            "WHERE table_schema = current_schema() AND table_name = ? AND column_name = ?",
            (parent, "id"),
        ).fetchone()
        if row is None or str(row["data_type"]).lower() != "integer":
            raise RuntimeError(f"schedule_templates requires {parent}.id INTEGER")

    for statement in MIGRATION_STATEMENTS:
        conn.execute(statement)

    rows = conn.execute(
        "SELECT column_name, data_type, is_nullable FROM information_schema.columns "
        "WHERE table_schema = current_schema() AND table_name = ? ORDER BY ordinal_position",
        ("schedule_templates",),
    ).fetchall()
    actual = {str(r["column_name"]): (str(r["data_type"]).lower(), str(r["is_nullable"]).upper() == "NO") for r in rows}
    missing = sorted(set(_EXPECTED_COLUMNS) - set(actual))
    wrong = {n: {"actual": actual[n], "expected": e} for n, e in _EXPECTED_COLUMNS.items() if n in actual and actual[n] != e}
    if missing or wrong or set(actual) != set(_EXPECTED_COLUMNS):
        raise RuntimeError(f"schedule_templates columns incompatible: missing={missing}, wrong={wrong}")

    fk_rows = conn.execute(
        "SELECT kcu.column_name, ccu.table_name AS foreign_table_name, ccu.column_name AS foreign_column_name "
        "FROM information_schema.table_constraints tc "
        "JOIN information_schema.key_column_usage kcu ON tc.constraint_name = kcu.constraint_name AND tc.constraint_schema = kcu.constraint_schema "
        "JOIN information_schema.constraint_column_usage ccu ON ccu.constraint_name = tc.constraint_name AND ccu.constraint_schema = tc.constraint_schema "
        "WHERE tc.constraint_type = 'FOREIGN KEY' AND tc.table_schema = current_schema() AND tc.table_name = ?",
        ("schedule_templates",),
    ).fetchall()
    actual_fks = {(str(r["column_name"]), str(r["foreign_table_name"]), str(r["foreign_column_name"])) for r in fk_rows}
    if actual_fks != _EXPECTED_FOREIGN_KEYS:
        raise RuntimeError(f"schedule_templates foreign keys incompatible: {sorted(actual_fks)}")

    unique_rows = conn.execute(
        "SELECT tc.constraint_name FROM information_schema.table_constraints tc "
        "WHERE tc.constraint_type = 'UNIQUE' AND tc.table_schema = current_schema() AND tc.table_name = ?",
        ("schedule_templates",),
    ).fetchall()
    if unique_rows:
        raise RuntimeError("schedule_templates unique constraints incompatible: unexpected UNIQUE constraint")

    index_rows = conn.execute(
        "SELECT indexname, indexdef FROM pg_indexes WHERE schemaname = current_schema() AND tablename = ?",
        ("schedule_templates",),
    ).fetchall()
    indexes = {str(r["indexname"]): str(r["indexdef"]).lower().replace('"', "") for r in index_rows}
    if set(indexes) != {"schedule_templates_pkey", "idx_schedule_templates_client_uuid"}:
        raise RuntimeError(f"schedule_templates indexes incompatible: {sorted(indexes)}")
    client_idx = indexes["idx_schedule_templates_client_uuid"]
    if "unique index" not in client_idx or "(client_uuid)" not in client_idx or "where (client_uuid is not null)" not in client_idx:
        raise RuntimeError("schedule_templates client UUID partial index is incompatible")

    trigger_rows = conn.execute(
        "SELECT trigger_name FROM information_schema.triggers WHERE trigger_schema = current_schema() AND event_object_table = ?",
        ("schedule_templates",),
    ).fetchall()
    actual_triggers = {str(r["trigger_name"]) for r in trigger_rows}
    if actual_triggers != _EXPECTED_TRIGGERS:
        raise RuntimeError(f"schedule_templates triggers incompatible: {sorted(actual_triggers)}")


def migration() -> PostgresMigration:
    return PostgresMigration(version=MIGRATION_VERSION, name=MIGRATION_NAME,
                             apply=apply_schedule_templates, source=MIGRATION_SOURCE)
