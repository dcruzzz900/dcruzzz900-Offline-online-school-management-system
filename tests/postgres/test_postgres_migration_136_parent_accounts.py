import pytest

from postgres_migration_136_parent_accounts import (
    MIGRATION_NAME, MIGRATION_SOURCE, MIGRATION_VERSION,
    apply_parent_accounts, migration,
)
from postgres_migration_registry import POSTGRES_MIGRATIONS


class Result:
    def __init__(self, rows): self.rows = rows
    def fetchall(self): return self.rows
    def fetchone(self): return self.rows[0] if self.rows else None


class FakeConnection:
    def __init__(self, columns=None, fks=None, indexes=None, triggers=None, school_id_type="integer"):
        expected = {
            "id": ("bigint", True), "school_id": ("integer", True), "tenant_id": ("text", True),
            "name": ("text", True), "username": ("text", True), "email": ("text", False),
            "phone": ("text", False), "password_hash": ("text", True), "is_active": ("bigint", True),
            "last_notification_seen_id": ("bigint", False), "created_at": ("text", False),
            "account_status": ("text", False), "signup_status": ("text", False),
            "photo_filename": ("text", False), "date_of_birth": ("text", False), "gender": ("text", False),
        }
        self.columns = columns if columns is not None else [
            {"column_name": n, "data_type": typ, "is_nullable": "NO" if req else "YES"}
            for n, (typ, req) in expected.items()
        ]
        self.fks = fks if fks is not None else [
            {"column_name": "school_id", "foreign_table_name": "schools", "foreign_column_name": "id"}
        ]
        self.indexes = indexes if indexes is not None else [
            {"indexname": "parent_accounts_pkey", "indexdef": "CREATE UNIQUE INDEX parent_accounts_pkey ON public.parent_accounts USING btree (id)"},
            {"indexname": "parent_accounts_school_id_username_key", "indexdef": "CREATE UNIQUE INDEX parent_accounts_school_id_username_key ON public.parent_accounts USING btree (school_id, username)"},
        ]
        self.triggers = triggers if triggers is not None else [
            {"trigger_name": "trg_parent_accounts_tenant_stamp_pg"}
        ]
        self.school_id_type = school_id_type
        self.calls = []

    def execute(self, sql, params=()):
        self.calls.append((sql, params))
        if "information_schema.columns" in sql and "schools" in params:
            return Result([{"column_name": "id", "data_type": self.school_id_type}])
        if "information_schema.columns" in sql: return Result(self.columns)
        if "information_schema.table_constraints" in sql: return Result(self.fks)
        if "FROM pg_indexes" in sql: return Result(self.indexes)
        if "information_schema.triggers" in sql: return Result(self.triggers)
        return Result([])


def test_registry_and_migration_identity():
    assert MIGRATION_VERSION == 136
    assert MIGRATION_NAME == "create_parent_accounts"
    assert [m.version for m in POSTGRES_MIGRATIONS] == list(range(100, 188))
    assert next(m for m in POSTGRES_MIGRATIONS if m.version == 136).name == MIGRATION_NAME
    assert migration().version == 136


def test_ddl_preserves_columns_relationship_unique_key_and_tenant_trigger():
    sql = MIGRATION_SOURCE.lower()
    for fragment in (
        "id bigint generated by default as identity primary key", "school_id integer not null",
        "tenant_id text not null", "password_hash text not null", "is_active bigint not null default 1",
        "last_notification_seen_id bigint default 0", "created_at text default current_timestamp",
        "account_status text default 'active'", "signup_status text default 'approved'",
        "unique (school_id, username)", "references schools(id)", "after insert",
        "if new.tenant_id = ''", "set tenant_id = (select tenant_id from schools where id = new.school_id)",
    ):
        assert fragment in sql


def test_apply_executes_and_validates_migration():
    conn = FakeConnection()
    apply_parent_accounts(conn)
    assert any("CREATE TABLE IF NOT EXISTS parent_accounts" in sql for sql, _ in conn.calls)
    assert any("CREATE TRIGGER trg_parent_accounts_tenant_stamp_pg" in sql for sql, _ in conn.calls)


def test_rejects_incompatible_school_primary_key_type():
    with pytest.raises(RuntimeError, match="schools.id INTEGER"):
        apply_parent_accounts(FakeConnection(school_id_type="bigint"))


def test_rejects_wrong_columns():
    with pytest.raises(RuntimeError, match="columns incompatible"):
        apply_parent_accounts(FakeConnection(columns=[]))


def test_rejects_wrong_foreign_key():
    with pytest.raises(RuntimeError, match="foreign keys incompatible"):
        apply_parent_accounts(FakeConnection(fks=[]))


def test_rejects_wrong_indexes():
    with pytest.raises(RuntimeError, match="indexes incompatible"):
        apply_parent_accounts(FakeConnection(indexes=[]))


def test_rejects_wrong_tenant_trigger():
    with pytest.raises(RuntimeError, match="triggers incompatible"):
        apply_parent_accounts(FakeConnection(triggers=[]))
