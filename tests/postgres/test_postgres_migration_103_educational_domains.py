import pytest

from postgres_migration_103_educational_domains import (
    MIGRATION_NAME, MIGRATION_SOURCE, MIGRATION_VERSION,
    apply_educational_domains, migration,
)
from postgres_migration_registry import POSTGRES_MIGRATIONS


class Result:
    def __init__(self, rows): self.rows = rows
    def fetchall(self): return self.rows
    def fetchone(self): return self.rows[0] if self.rows else None


class FakeConnection:
    def __init__(self, columns=None, unique=None, fk=False, indexes=None):
        types = {"id":"bigint", "school_id":"bigint", "tenant_id":"text",
                 "domain_key":"text", "label":"text", "is_active":"bigint", "sort_order":"bigint"}
        required = {"id", "school_id", "domain_key", "label", "is_active", "sort_order"}
        self.columns = columns if columns is not None else [
            {"column_name": n, "data_type": t, "is_nullable": "NO" if n in required else "YES"}
            for n, t in types.items()
        ]
        self.unique = unique if unique is not None else [{"indexdef": "CREATE UNIQUE INDEX uq_educational_domains_school_domain ON public.educational_domains USING btree (school_id, domain_key)"}]
        self.fk = fk
        self.indexes = indexes if indexes is not None else [
            {"indexname":"educational_domains_pkey"},
            {"indexname":"uq_educational_domains_school_domain"},
        ]
        self.calls = []
    def execute(self, sql, params=()):
        self.calls.append((sql, params))
        if "information_schema.columns" in sql: return Result(self.columns)
        if "FROM pg_indexes" in sql and "indexdef" in sql: return Result(self.unique)
        if "constraint_type = 'FOREIGN KEY'" in sql: return Result([{"x":1}] if self.fk else [])
        if "FROM pg_indexes" in sql: return Result(self.indexes)
        return Result([])


def test_metadata_and_registry():
    m = migration()
    assert (m.version, m.name, m.source) == (103, MIGRATION_NAME, MIGRATION_SOURCE)
    assert MIGRATION_VERSION == 103 and MIGRATION_NAME == "create_educational_domains"
    assert [item.version for item in POSTGRES_MIGRATIONS] == list(range(100, 143))


def test_creates_reviewed_shape_and_composite_uniqueness():
    conn = FakeConnection()
    apply_educational_domains(conn)
    sql = "\n".join(statement for statement, _ in conn.calls)
    assert "educational_domains" in sql
    assert "GENERATED BY DEFAULT AS IDENTITY" in sql
    assert "UNIQUE (school_id, domain_key)" in sql
    assert "is_active BIGINT NOT NULL DEFAULT 1" in sql


def test_rejects_missing_or_incompatible_columns():
    columns = [dict(row) for row in FakeConnection().columns if row["column_name"] != "label"]
    with pytest.raises(RuntimeError, match="missing columns"):
        apply_educational_domains(FakeConnection(columns=columns))
    columns = [dict(row) for row in FakeConnection().columns]
    columns[1]["data_type"] = "integer"
    with pytest.raises(RuntimeError, match="incompatible columns"):
        apply_educational_domains(FakeConnection(columns=columns))


def test_rejects_missing_or_incompatible_unique_constraint():
    with pytest.raises(RuntimeError, match="unique constraint is missing"):
        apply_educational_domains(FakeConnection(unique=[]))
    with pytest.raises(RuntimeError, match="unique constraint is incompatible"):
        apply_educational_domains(FakeConnection(unique=[{"indexdef":"CREATE INDEX x ON educational_domains (school_id)"}]))


def test_rejects_unexpected_foreign_keys_and_secondary_indexes():
    with pytest.raises(RuntimeError, match="unexpected foreign-key"):
        apply_educational_domains(FakeConnection(fk=True))
    indexes = FakeConnection().indexes + [{"indexname":"unexpected_idx"}]
    with pytest.raises(RuntimeError, match="unexpected secondary indexes"):
        apply_educational_domains(FakeConnection(indexes=indexes))
