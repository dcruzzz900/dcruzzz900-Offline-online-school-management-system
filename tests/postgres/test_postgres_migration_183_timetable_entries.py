def test_rejects_non_unique_slot_index():
    bad = [
        {"indexname": "timetable_entries_pkey", "indexdef": "x"},
        {"indexname": "idx_timetable_entries_slot", "indexdef": "CREATE INDEX i ON t USING btree (class_id, day_of_week, period_id)"},
        {"indexname": "idx_timetable_entries_teacher", "indexdef": "CREATE INDEX i ON t USING btree (teacher_id, day_of_week)"},
        {"indexname": "idx_timetable_entries_client_uuid", "indexdef": "CREATE UNIQUE INDEX i ON t USING btree (client_uuid) WHERE (client_uuid IS NOT NULL)"},
    ]
    with pytest.raises(RuntimeError, match="slot uniqueness index"):
        apply_timetable_entries(FakeConnection(indexes=bad))


