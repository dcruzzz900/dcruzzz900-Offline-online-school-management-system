import pytest

from postgres_migration_184_sync_tombstones import (
    MIGRATION_NAME, MIGRATION_SOURCE, MIGRATION_STATEMENTS, MIGRATION_VERSION,
    _EXPECTED_COLUMNS, apply_sync_tombstones, migration,
)
from postgres_migration_registry import POSTGRES_MIGRATIONS


class Result:
    def __init__(self, rows): self.rows = rows
    def fetchall(self): return self.rows
    def fetchone(self): return self.rows[0] if self.rows else None


GOOD_INDEXES = [
    {"indexname": "sync_tombstones_pkey", "indexdef": "CREATE UNIQUE INDEX sync_tombstones_pkey ON public.sync_tombstones USING btree (id)"},
    {"indexname": "idx_sync_tombstones_school", "indexdef": "CREATE INDEX idx_sync_tombstones_school ON public.sync_tombstones USING btree (school_id, deleted_at)"},
]


class FakeConnection:
    def __init__(self, columns=None, fks=None, uniques=None, checks=None, indexes=None, triggers=None):
        self.columns = columns if columns is not None else [
            {"column_name": n, "data_type": typ, "is_nullable": "NO" if req else "YES"}
            for n, (typ, req) in _EXPECTED_COLUMNS.items()
        ]
        self.fks = fks or []
        self.uniques = uniques or []
        self.checks = checks or []
        self.indexes = indexes if indexes is not None else GOOD_INDEXES
        self.triggers = triggers or []
        self.calls = []

    def execute(self, sql, params=()):
        self.calls.append((sql, params))
        if "information_schema.columns" in sql: return Result(self.columns)
        if "constraint_type = 'FOREIGN KEY'" in sql: return Result(self.fks)
        if "constraint_type = 'UNIQUE'" in sql: return Result(self.uniques)
        if "FROM pg_constraint" in sql: return Result(self.checks)
        if "FROM pg_indexes" in sql: return Result(self.indexes)
        if "information_schema.triggers" in sql: return Result(self.triggers)
        return Result([])


def test_registry_and_migration_identity():
    assert MIGRATION_VERSION == 184
    assert MIGRATION_NAME == "create_sync_tombstones"
    assert POSTGRES_MIGRATIONS[-4].version == 184
    assert [m.version for m in POSTGRES_MIGRATIONS] == list(range(100, 188))
    assert migration().version == 184


def test_effective_sqlite_schema_is_preserved():
    assert list(_EXPECTED_COLUMNS) == ["id", "school_id", "entity", "client_uuid", "deleted_at"]
    sql = MIGRATION_SOURCE.lower()
    for fragment in (
        "id bigint generated by default as identity primary key", "school_id integer,",
        "entity text not null", "client_uuid text not null", "deleted_at text not null",
        "idx_sync_tombstones_school", "(school_id, deleted_at)",
    ):
        assert fragment in sql
    assert "references" not in sql and "unique" not in sql and "trigger" not in sql


def test_apply_executes_every_statement_and_validates():
    conn = FakeConnection()
    apply_sync_tombstones(conn)
    executed = [sql for sql, _ in conn.calls]
    for statement in MIGRATION_STATEMENTS:
        assert statement in executed


def test_rejects_wrong_columns():
    with pytest.raises(RuntimeError, match="columns incompatible"):
        apply_sync_tombstones(FakeConnection(columns=[]))


def test_rejects_wrong_nullability():
    cols = [{"column_name": n, "data_type": t, "is_nullable": "YES"} for n, (t, _) in _EXPECTED_COLUMNS.items()]
    with pytest.raises(RuntimeError, match="columns incompatible"):
        apply_sync_tombstones(FakeConnection(columns=cols))


def test_rejects_unexpected_foreign_key():
    with pytest.raises(RuntimeError, match="foreign keys incompatible"):
        apply_sync_tombstones(FakeConnection(fks=[{"column_name": "school_id"}]))


def test_rejects_unexpected_unique_constraint():
    with pytest.raises(RuntimeError, match="unique constraints incompatible"):
        apply_sync_tombstones(FakeConnection(uniques=[{"constraint_name": "x"}]))


def test_rejects_unexpected_check_constraint():
    with pytest.raises(RuntimeError, match="CHECK constraints incompatible"):
        apply_sync_tombstones(FakeConnection(checks=[{"conname": "x"}]))


def test_rejects_wrong_indexes():
    with pytest.raises(RuntimeError, match="indexes incompatible"):
        apply_sync_tombstones(FakeConnection(indexes=[]))


def test_rejects_unique_or_wrong_school_index():
    for bad_def in ("CREATE UNIQUE INDEX i ON t USING btree (school_id, deleted_at)",
                    "CREATE INDEX i ON t USING btree (deleted_at, school_id)"):
        bad = [GOOD_INDEXES[0], {"indexname": "idx_sync_tombstones_school", "indexdef": bad_def}]
        with pytest.raises(RuntimeError, match="school lookup index"):
            apply_sync_tombstones(FakeConnection(indexes=bad))


def test_rejects_unexpected_triggers():
    with pytest.raises(RuntimeError, match="triggers incompatible"):
        apply_sync_tombstones(FakeConnection(triggers=[{"trigger_name": "x"}]))
