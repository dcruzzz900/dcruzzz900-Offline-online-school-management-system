"""PostgreSQL-native migration 168: schedule_slots.

Ports the effective SQLite table of timetable time slots (one row per school
day and bell-schedule period: lesson, break, assembly, ...). The source
declares three foreign keys -- `school_id` -> `schools.id`, `day_id` ->
`school_days_v2.id` and `schedule_template_id` -> `schedule_templates.id` --
and two CHECK constraints: `slot_type` must be one of TEACHING, BREAK,
ASSEMBLY, ACTIVITY, OTHER, and `start_time < end_time`. `school_days_v2` and
`schedule_templates` were ported by migrations 166 and 167, which is why this
table could not be ported earlier. Key types follow the parents: `school_id`
stays INTEGER (`schools.id` is INTEGER); `day_id` and `schedule_template_id`
are BIGINT because the identity keys created by migrations 166/167 are BIGINT.
`academic_session_id` and `term_id` have no foreign key in the source and are
BIGINT, as in migration 134. The sync columns SQLite adds through
`_make_syncable()` (`client_uuid`, `is_deleted`), the partial unique
client-UUID index and the sync default/touch triggers are recreated.
`start_time`/`end_time` stay TEXT (the application stores `HH:MM` strings and
the CHECK compares them as text, as SQLite does). The source has no uniqueness
beyond the primary key, and verification asserts that. This migration does not
alter SQLite startup, SQLite migrations, or offline sync.
"""
