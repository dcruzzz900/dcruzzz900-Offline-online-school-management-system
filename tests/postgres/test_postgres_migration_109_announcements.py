from postgres_migration_109_announcements import (
    MIGRATION_NAME,
    MIGRATION_SOURCE,
    MIGRATION_VERSION,
    migration,
)
from postgres_migration_registry import POSTGRES_MIGRATIONS


def test_announcements_migration_is_registered_in_order():
    assert MIGRATION_VERSION == 109
    assert MIGRATION_NAME == "create_announcements"
    assert [item.version for item in POSTGRES_MIGRATIONS] == list(range(100, 143))
    assert next(item for item in POSTGRES_MIGRATIONS if item.version == MIGRATION_VERSION).name == MIGRATION_NAME


def test_announcements_ddl_preserves_reviewed_source_contract():
    sql = MIGRATION_SOURCE.lower()
    for column in (
        "school_id", "title", "message", "audience", "level", "dismissible",
        "starts_at", "expires_at", "is_active", "created_by", "created_by_label",
        "created_at", "display_seconds",
    ):
        assert column in sql
    assert "bigint generated by default as identity primary key" in sql
    assert "audience text not null default 'all'" in sql
    assert "level text not null default 'info'" in sql
    assert "dismissible bigint not null default 1" in sql
    assert "is_active bigint not null default 1" in sql
    assert "display_seconds bigint not null default 0" in sql
    assert "create index if not exists idx_announcements_school_expiry on announcements (school_id, expires_at)" in sql
    assert "references " not in sql
    assert "create trigger" not in sql


def test_migration_metadata():
    item = migration()
    assert item.version == 109
    assert item.name == MIGRATION_NAME
    assert item.source == MIGRATION_SOURCE
    assert callable(item.apply)
