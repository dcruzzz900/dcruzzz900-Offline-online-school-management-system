import pytest

from postgres_migration_138_parent_students import (
    MIGRATION_NAME, MIGRATION_SOURCE, MIGRATION_VERSION,
    apply_parent_students, migration,
)
from postgres_migration_registry import POSTGRES_MIGRATIONS


class Result:
    def __init__(self, rows): self.rows = rows
    def fetchall(self): return self.rows
    def fetchone(self): return self.rows[0] if self.rows else None


class FakeConnection:
    def __init__(self, dependency_types=None, columns=None, fks=None, indexes=None, triggers=None):
        self.dependency_types = dependency_types or {
            "parent_accounts": "bigint", "students": "integer", "schools": "integer"
        }
        expected = {
            "id": ("bigint", True), "parent_id": ("bigint", True),
            "student_id": ("integer", True), "school_id": ("integer", True),
            "tenant_id": ("text", True), "status": ("text", True),
            "verified_at": ("text", False), "verified_by": ("bigint", False),
            "revoked_at": ("text", False), "created_at": ("text", False),
        }
        self.columns = columns if columns is not None else [
            {"column_name": n, "data_type": t, "is_nullable": "NO" if required else "YES"}
            for n, (t, required) in expected.items()
        ]
        self.fks = fks if fks is not None else [
            {"column_name": "parent_id", "foreign_table_name": "parent_accounts", "foreign_column_name": "id"},
            {"column_name": "student_id", "foreign_table_name": "students", "foreign_column_name": "id"},
            {"column_name": "school_id", "foreign_table_name": "schools", "foreign_column_name": "id"},
        ]
        self.indexes = indexes if indexes is not None else [
            {"indexname": "parent_students_pkey", "indexdef": "CREATE UNIQUE INDEX parent_students_pkey ON public.parent_students USING btree (id)"},
            {"indexname": "uq_parent_students_parent_student", "indexdef": "CREATE UNIQUE INDEX uq_parent_students_parent_student ON public.parent_students USING btree (parent_id, student_id)"},
            {"indexname": "idx_parent_students_parent", "indexdef": "CREATE INDEX idx_parent_students_parent ON public.parent_students USING btree (parent_id, school_id)"},
            {"indexname": "idx_parent_students_student", "indexdef": "CREATE INDEX idx_parent_students_student ON public.parent_students USING btree (student_id, school_id)"},
        ]
        self.triggers = triggers if triggers is not None else [{"trigger_name": "trg_parent_students_tenant_stamp_pg"}]
        self.calls = []

    def execute(self, sql, params=()):
        self.calls.append((sql, params))
        if "information_schema.columns" in sql and len(params) == 2 and params[0] in self.dependency_types:
            return Result([{"column_name": "id", "data_type": self.dependency_types[params[0]]}])
        if "information_schema.columns" in sql:
            return Result(self.columns)
        if "information_schema.table_constraints" in sql and "JOIN" in sql:
            return Result(self.fks)
        if "FROM pg_indexes" in sql:
            return Result(self.indexes)
        if "information_schema.triggers" in sql:
            return Result(self.triggers)
        return Result([])


def test_registry_and_migration_identity():
    assert MIGRATION_VERSION == 138
    assert MIGRATION_NAME == "create_parent_students"
    assert [item.version for item in POSTGRES_MIGRATIONS] == list(range(100, 188))
    assert next(item for item in POSTGRES_MIGRATIONS if item.version == 138).name == MIGRATION_NAME
    assert migration().version == 138


def test_ddl_preserves_parent_student_school_relationships_and_indexes():
    sql = MIGRATION_SOURCE.lower()
    for fragment in (
        "id bigint generated by default as identity primary key",
        "parent_id bigint not null", "student_id integer not null", "school_id integer not null",
        "tenant_id text not null", "status text not null default 'pending'",
        "unique (parent_id, student_id)", "references parent_accounts(id) on delete cascade",
        "references students(id) on delete cascade", "references schools(id)",
        "idx_parent_students_parent on parent_students(parent_id, school_id)",
        "idx_parent_students_student on parent_students(student_id, school_id)",
        "after insert on parent_students", "new.tenant_id is null or new.tenant_id = ''",
    ):
        assert fragment in sql


def test_apply_executes_and_validates_migration():
    conn = FakeConnection()
    apply_parent_students(conn)
    assert len([call for call in conn.calls if call[0] in MIGRATION_SOURCE.split(";\n\n")]) == len(MIGRATION_SOURCE.split(";\n\n"))


@pytest.mark.parametrize("dependency,wrong_type", [
    ("parent_accounts", "integer"), ("students", "bigint"), ("schools", "bigint")
])
def test_apply_rejects_incompatible_dependency_key_types(dependency, wrong_type):
    types = {"parent_accounts": "bigint", "students": "integer", "schools": "integer"}
    types[dependency] = wrong_type
    with pytest.raises(RuntimeError, match="requires"):
        apply_parent_students(FakeConnection(dependency_types=types))


def test_apply_rejects_missing_foreign_key():
    with pytest.raises(RuntimeError, match="foreign keys"):
        apply_parent_students(FakeConnection(fks=[]))


def test_apply_rejects_wrong_index_set():
    with pytest.raises(RuntimeError, match="indexes"):
        apply_parent_students(FakeConnection(indexes=[]))


def test_apply_rejects_missing_tenant_trigger():
    with pytest.raises(RuntimeError, match="triggers"):
        apply_parent_students(FakeConnection(triggers=[]))
