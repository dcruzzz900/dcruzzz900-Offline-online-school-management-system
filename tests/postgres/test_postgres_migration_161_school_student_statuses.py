from postgres_migration_161_school_student_statuses import (
    MIGRATION_NAME, MIGRATION_STATEMENTS, MIGRATION_VERSION, _EXPECTED_COLUMNS, migration,
)
from postgres_migration_registry import POSTGRES_MIGRATIONS


def test_migration_identity_and_registry():
    item = migration()
    assert item.version == 161
    assert item.name == "create_school_student_statuses"
    assert MIGRATION_VERSION == 161
    assert POSTGRES_MIGRATIONS[-27].version == 161
    assert [m.version for m in POSTGRES_MIGRATIONS] == list(range(100, 188))


def test_effective_sqlite_schema_shape_is_preserved():
    assert list(_EXPECTED_COLUMNS) == ["id", "school_id", "tenant_id", "name", "keeps_enrolled", "is_active"]
    sql = MIGRATION_STATEMENTS[0]
    assert "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in sql
    assert "school_id BIGINT NOT NULL" in sql
    assert "tenant_id TEXT" in sql
    assert "name TEXT NOT NULL" in sql
    assert "keeps_enrolled BIGINT NOT NULL DEFAULT 0" in sql
    assert "is_active BIGINT NOT NULL DEFAULT 1" in sql
    assert "UNIQUE (school_id, name)" in sql
    assert len(MIGRATION_STATEMENTS) == 1
    assert "FOREIGN KEY" not in sql.upper()
    assert "CREATE TRIGGER" not in sql.upper()
