import pytest

from postgres_migration_181_staff_documents import (
    MIGRATION_NAME, MIGRATION_SOURCE, MIGRATION_STATEMENTS, MIGRATION_VERSION,
    _EXPECTED_COLUMNS, apply_staff_documents, migration,
)
from postgres_migration_registry import POSTGRES_MIGRATIONS


class Result:
    def __init__(self, rows): self.rows = rows
    def fetchall(self): return self.rows
    def fetchone(self): return self.rows[0] if self.rows else None


class FakeConnection:
    def __init__(self, columns=None, fks=None, uniques=None, checks=None, indexes=None, triggers=None):
        self.columns = columns if columns is not None else [
            {"column_name": n, "data_type": typ, "is_nullable": "NO" if req else "YES"}
            for n, (typ, req) in _EXPECTED_COLUMNS.items()
        ]
        self.fks = fks if fks is not None else []
        self.uniques = uniques if uniques is not None else [
            {"constraint_name": "uq_staff_documents_user_stored_filename", "column_name": c, "ordinal_position": i}
            for i, c in enumerate(("user_id", "stored_filename"), 1)
        ]
        self.checks = checks if checks is not None else []
        self.indexes = indexes if indexes is not None else [
            {"indexname": "staff_documents_pkey", "indexdef": "CREATE UNIQUE INDEX staff_documents_pkey ON public.staff_documents USING btree (id)"},
            {"indexname": "uq_staff_documents_user_stored_filename", "indexdef": "CREATE UNIQUE INDEX uq_staff_documents_user_stored_filename ON public.staff_documents USING btree (user_id, stored_filename)"},
            {"indexname": "idx_staff_documents_tenant_user", "indexdef": "CREATE INDEX idx_staff_documents_tenant_user ON public.staff_documents USING btree (tenant_id, school_id, user_id)"},
        ]
        self.triggers = triggers if triggers is not None else []
        self.calls = []

    def execute(self, sql, params=()):
        self.calls.append((sql, params))
        if "information_schema.columns" in sql: return Result(self.columns)
        if "constraint_type = 'FOREIGN KEY'" in sql: return Result(self.fks)
        if "constraint_type = 'UNIQUE'" in sql: return Result(self.uniques)
        if "FROM pg_constraint" in sql: return Result(self.checks)
        if "FROM pg_indexes" in sql: return Result(self.indexes)
        if "information_schema.triggers" in sql: return Result(self.triggers)
        return Result([])


def test_registry_and_migration_identity():
    assert MIGRATION_VERSION == 181
    assert MIGRATION_NAME == "create_staff_documents"
    assert POSTGRES_MIGRATIONS[-7].version == 181
    assert [m.version for m in POSTGRES_MIGRATIONS] == list(range(100, 188))
    assert migration().version == 181


def test_effective_sqlite_schema_is_preserved():
    assert list(_EXPECTED_COLUMNS) == [
        "id", "school_id", "tenant_id", "user_id", "original_filename", "stored_filename",
        "mime_type", "size_bytes", "uploaded_at", "updated_at",
    ]
    sql = MIGRATION_SOURCE.lower()
    for fragment in (
        "id bigint generated by default as identity primary key", "school_id integer not null",
        "tenant_id text not null", "user_id integer not null", "original_filename text not null",
        "stored_filename text not null", "mime_type text,", "size_bytes bigint not null default 0",
        "uploaded_at text default current_timestamp", "updated_at text default current_timestamp",
        "unique (user_id, stored_filename)", "on staff_documents (tenant_id, school_id, user_id)",
    ):
        assert fragment in sql
    assert "references " not in sql
    assert "client_uuid" not in sql and "trigger" not in sql and "check (" not in sql


def test_apply_executes_every_statement_and_validates():
    conn = FakeConnection()
    apply_staff_documents(conn)
    executed = [sql for sql, _ in conn.calls]
    for statement in MIGRATION_STATEMENTS:
        assert statement in executed


def test_rejects_wrong_columns():
    with pytest.raises(RuntimeError, match="columns incompatible"):
        apply_staff_documents(FakeConnection(columns=[]))


def test_rejects_unexpected_foreign_key():
    with pytest.raises(RuntimeError, match="foreign keys incompatible"):
        apply_staff_documents(FakeConnection(fks=[{"constraint_name": "x"}]))


def test_rejects_wrong_unique_constraint():
    with pytest.raises(RuntimeError, match="unique constraints incompatible"):
        apply_staff_documents(FakeConnection(uniques=[]))
    reordered = [{"constraint_name": "uq_x", "column_name": c, "ordinal_position": i}
                 for i, c in enumerate(("stored_filename", "user_id"), 1)]
    with pytest.raises(RuntimeError, match="unique constraints incompatible"):
        apply_staff_documents(FakeConnection(uniques=reordered))


def test_rejects_unexpected_check_constraint():
    with pytest.raises(RuntimeError, match="CHECK constraints incompatible"):
        apply_staff_documents(FakeConnection(checks=[{"conname": "x"}]))


def test_rejects_wrong_indexes():
    with pytest.raises(RuntimeError, match="indexes incompatible"):
        apply_staff_documents(FakeConnection(indexes=[]))


def test_rejects_wrong_lookup_index():
    bad = [
        {"indexname": "staff_documents_pkey", "indexdef": "x"},
        {"indexname": "uq_staff_documents_user_stored_filename", "indexdef": "x"},
        {"indexname": "idx_staff_documents_tenant_user", "indexdef": "CREATE INDEX i ON t USING btree (user_id)"},
    ]
    with pytest.raises(RuntimeError, match="lookup index"):
        apply_staff_documents(FakeConnection(indexes=bad))
    unique = [dict(bad[0]), dict(bad[1]),
              {"indexname": "idx_staff_documents_tenant_user", "indexdef": "CREATE UNIQUE INDEX i ON t USING btree (tenant_id, school_id, user_id)"}]
    with pytest.raises(RuntimeError, match="lookup index"):
        apply_staff_documents(FakeConnection(indexes=unique))


def test_rejects_unexpected_triggers():
    with pytest.raises(RuntimeError, match="triggers incompatible"):
        apply_staff_documents(FakeConnection(triggers=[{"trigger_name": "x"}]))
