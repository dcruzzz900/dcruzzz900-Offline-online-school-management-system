"""PostgreSQL-native migration 183: timetable_entries.

Ports the effective SQLite table of one timetable slot per class/day/period
(subject, teacher, room). This is the second of the two original
(`migration_038`) timetable tables -- `timetable_periods`, its sibling and
one of its foreign-key parents, was ported in migration 182, following the
same approach for the same reasons, repeated here.

Like `timetable_periods`, the source has 12 effective columns, not the 11
`migration_038_timetable()` alone would suggest: `migration_051_registration_
security_spec()`'s generic `direct=[...]` table list adds a 12th, nullable
`tenant_id TEXT`, backfilled from `schools.tenant_id` via `school_id` and kept
current by a SQLite `AFTER INSERT` trigger. This was confirmed directly
against the effective schema snapshot this time, not assumed from the
migration-182 precedent alone. `postgres_tenant_triggers.sql`'s existing
`app_stamp_tenant_timetable_entries()` / `trg_timetable_entries_tenant_stamp_pg`
and `postgres_tombstone_triggers.sql`'s existing `trg_timetable_entries_
tombstone` are both correct for this table (same condition, same source
columns, same as migration 182 found for `timetable_periods`), so this
migration relies on them rather than re-implementing tenant-stamp or
tombstone logic itself -- the same answer migration 182 gave to Stage 110's
"decide the trigger-overlap question" item, now applied to the second of the
two tables it named.

The source declares five foreign keys: `school_id` -> `schools.id`,
`class_id` -> `classes.id`, `period_id` -> `timetable_periods.id`,
`subject_id` -> `subjects.id`, `teacher_id` -> `users.id`. Key types follow
the parents: `school_id`, `class_id`, `subject_id` and `teacher_id` stay
INTEGER (`schools.id`, `classes.id`, `subjects.id` and `users.id` are all
INTEGER in `postgres_schema_base.sql`); `period_id` is BIGINT because
migration 182's `timetable_periods.id` is a BIGINT identity column. Two
indexes carry real constraints and are recreated exactly: the UNIQUE
`(class_id, day_of_week, period_id)` one-slot-per-class/day/period rule
(`idx_timetable_entries_slot`, a plain CREATE UNIQUE INDEX in the source, not
a table-level UNIQUE constraint) and the non-unique `(teacher_id,
day_of_week)` lookup index (`idx_timetable_entries_teacher`). The usual
partial unique client-UUID index and client_uuid/updated_at sync
default/touch triggers are also recreated, following migration 182's
pattern. There are no CHECK constraints in the source; verification asserts
none exist. This migration does not alter SQLite startup, SQLite migrations,
or offline sync.
"""
from __future__ import annotations

from postgres_migrations import PostgresMigration

MIGRATION_VERSION = 183
MIGRATION_NAME = "create_timetable_entries"

MIGRATION_STATEMENTS = (
    """CREATE TABLE IF NOT EXISTS timetable_entries (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        school_id INTEGER NOT NULL,
        class_id INTEGER NOT NULL,
        day_of_week BIGINT NOT NULL,
        period_id BIGINT NOT NULL,
        subject_id INTEGER,
        teacher_id INTEGER,
        room TEXT,
        client_uuid TEXT,
        updated_at TEXT,
        is_deleted BIGINT DEFAULT 0,
        tenant_id TEXT,
        CONSTRAINT fk_timetable_entries_school FOREIGN KEY (school_id) REFERENCES schools(id),
        CONSTRAINT fk_timetable_entries_class FOREIGN KEY (class_id) REFERENCES classes(id),
        CONSTRAINT fk_timetable_entries_period FOREIGN KEY (period_id) REFERENCES timetable_periods(id),
        CONSTRAINT fk_timetable_entries_subject FOREIGN KEY (subject_id) REFERENCES subjects(id),
        CONSTRAINT fk_timetable_entries_teacher FOREIGN KEY (teacher_id) REFERENCES users(id)
    )""",
    "CREATE UNIQUE INDEX IF NOT EXISTS idx_timetable_entries_slot "
    "ON timetable_entries (class_id, day_of_week, period_id)",
    "CREATE INDEX IF NOT EXISTS idx_timetable_entries_teacher "
    "ON timetable_entries (teacher_id, day_of_week)",
    "CREATE UNIQUE INDEX IF NOT EXISTS idx_timetable_entries_client_uuid "
    "ON timetable_entries (client_uuid) WHERE client_uuid IS NOT NULL",
    """CREATE OR REPLACE FUNCTION sync_timetable_entries_fields()
    RETURNS trigger LANGUAGE plpgsql AS $$
    DECLARE current_stamp TEXT; old_stamp TIMESTAMP;
    BEGIN
        IF TG_OP = 'INSERT' THEN
            IF NEW.client_uuid IS NULL THEN
                NEW.client_uuid := md5(random()::text || clock_timestamp()::text || pg_backend_pid()::text);
            END IF;
            IF NEW.updated_at IS NULL THEN
                NEW.updated_at := to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS');
            END IF;
            RETURN NEW;
        END IF;
        IF NEW.updated_at IS NOT DISTINCT FROM OLD.updated_at THEN
            current_stamp := to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS');
            IF OLD.updated_at IS NULL OR current_stamp > OLD.updated_at THEN
                NEW.updated_at := current_stamp;
            ELSE
                BEGIN
                    old_stamp := OLD.updated_at::timestamp;
                    NEW.updated_at := to_char(old_stamp + INTERVAL '1 second', 'YYYY-MM-DD"T"HH24:MI:SS');
                EXCEPTION WHEN others THEN
                    NEW.updated_at := current_stamp;
                END;
            END IF;
        END IF;
        RETURN NEW;
    END;
    $$""",
    "DROP TRIGGER IF EXISTS trg_timetable_entries_sync_defaults ON timetable_entries",
    "CREATE TRIGGER trg_timetable_entries_sync_defaults BEFORE INSERT ON timetable_entries "
    "FOR EACH ROW EXECUTE FUNCTION sync_timetable_entries_fields()",
    "DROP TRIGGER IF EXISTS trg_timetable_entries_sync_touch ON timetable_entries",
    "CREATE TRIGGER trg_timetable_entries_sync_touch BEFORE UPDATE ON timetable_entries "
    "FOR EACH ROW EXECUTE FUNCTION sync_timetable_entries_fields()",
)
MIGRATION_SOURCE = ";\n\n".join(MIGRATION_STATEMENTS)

_EXPECTED_COLUMNS = {
    "id": ("bigint", True), "school_id": ("integer", True), "class_id": ("integer", True),
    "day_of_week": ("bigint", True), "period_id": ("bigint", True), "subject_id": ("integer", False),
    "teacher_id": ("integer", False), "room": ("text", False), "client_uuid": ("text", False),
    "updated_at": ("text", False), "is_deleted": ("bigint", False), "tenant_id": ("text", False),
}
_EXPECTED_FKS = {
    ("school_id", "schools", "id"), ("class_id", "classes", "id"),
    ("period_id", "timetable_periods", "id"), ("subject_id", "subjects", "id"),
    ("teacher_id", "users", "id"),
}
_EXPECTED_TRIGGERS = {"trg_timetable_entries_sync_defaults", "trg_timetable_entries_sync_touch"}


def apply_timetable_entries(conn) -> None:
    for table, column in (("schools", "id"), ("classes", "id"), ("subjects", "id"), ("users", "id")):
        row = conn.execute(
            "SELECT column_name, data_type FROM information_schema.columns "
            "WHERE table_schema = current_schema() AND table_name = ? AND column_name = ?",
            (table, column),
        ).fetchone()
        if row is None or str(row["data_type"]).lower() != "integer":
            raise RuntimeError(f"timetable_entries requires {table}.{column} INTEGER")

    for statement in MIGRATION_STATEMENTS:
        conn.execute(statement)

    rows = conn.execute(
        "SELECT column_name, data_type, is_nullable FROM information_schema.columns "
        "WHERE table_schema = current_schema() AND table_name = ? ORDER BY ordinal_position",
        ("timetable_entries",),
    ).fetchall()
    actual = {str(r["column_name"]): (str(r["data_type"]).lower(), str(r["is_nullable"]).upper() == "NO") for r in rows}
    missing = sorted(set(_EXPECTED_COLUMNS) - set(actual))
    wrong = {n: {"actual": actual[n], "expected": e} for n, e in _EXPECTED_COLUMNS.items() if n in actual and actual[n] != e}
    if missing or wrong or set(actual) != set(_EXPECTED_COLUMNS):
        raise RuntimeError(f"timetable_entries columns incompatible: missing={missing}, wrong={wrong}")

    fk_rows = conn.execute(
        "SELECT kcu.column_name, ccu.table_name AS foreign_table_name, ccu.column_name AS foreign_column_name "
        "FROM information_schema.table_constraints tc "
        "JOIN information_schema.key_column_usage kcu ON tc.constraint_name = kcu.constraint_name AND tc.constraint_schema = kcu.constraint_schema "
        "JOIN information_schema.constraint_column_usage ccu ON ccu.constraint_name = tc.constraint_name AND ccu.constraint_schema = tc.constraint_schema "
        "WHERE tc.constraint_type = 'FOREIGN KEY' AND tc.table_schema = current_schema() AND tc.table_name = ?",
        ("timetable_entries",),
    ).fetchall()
    actual_fks = {(str(r["column_name"]), str(r["foreign_table_name"]), str(r["foreign_column_name"])) for r in fk_rows}
    if actual_fks != _EXPECTED_FKS:
        raise RuntimeError(f"timetable_entries foreign keys incompatible: {sorted(actual_fks)}")

    unique_rows = conn.execute(
        "SELECT tc.constraint_name, kcu.column_name, kcu.ordinal_position "
        "FROM information_schema.table_constraints tc "
        "JOIN information_schema.key_column_usage kcu ON tc.constraint_name = kcu.constraint_name AND tc.constraint_schema = kcu.constraint_schema "
        "WHERE tc.constraint_type = 'UNIQUE' AND tc.table_schema = current_schema() AND tc.table_name = ? "
        "ORDER BY tc.constraint_name, kcu.ordinal_position",
        ("timetable_entries",),
    ).fetchall()
    if unique_rows:
        raise RuntimeError("timetable_entries unique constraints incompatible: unexpected table-level UNIQUE constraint")

    check_rows = conn.execute(
        "SELECT conname FROM pg_constraint WHERE conrelid = 'timetable_entries'::regclass AND contype = 'c'"
    ).fetchall()
    if check_rows:
        raise RuntimeError("timetable_entries CHECK constraints incompatible: unexpected CHECK constraint")

    index_rows = conn.execute(
        "SELECT indexname, indexdef FROM pg_indexes WHERE schemaname = current_schema() AND tablename = ?",
        ("timetable_entries",),
    ).fetchall()
    indexes = {str(r["indexname"]): str(r["indexdef"]).lower().replace('"', "") for r in index_rows}
    expected_indexes = {
        "timetable_entries_pkey", "idx_timetable_entries_slot",
        "idx_timetable_entries_teacher", "idx_timetable_entries_client_uuid",
    }
    if set(indexes) != expected_indexes:
        raise RuntimeError(f"timetable_entries indexes incompatible: {sorted(indexes)}")
    slot_idx = indexes["idx_timetable_entries_slot"]
    if "unique" not in slot_idx or "(class_id, day_of_week, period_id)" not in slot_idx:
        raise RuntimeError("timetable_entries slot uniqueness index is incompatible")
    teacher_idx = indexes["idx_timetable_entries_teacher"]
    if "unique" in teacher_idx or "(teacher_id, day_of_week)" not in teacher_idx:
        raise RuntimeError("timetable_entries teacher lookup index is incompatible")
    client_idx = indexes["idx_timetable_entries_client_uuid"]
    if "unique index" not in client_idx or "(client_uuid)" not in client_idx or "where (client_uuid is not null)" not in client_idx:
        raise RuntimeError("timetable_entries client UUID partial index is incompatible")

    trigger_rows = conn.execute(
        "SELECT trigger_name FROM information_schema.triggers WHERE trigger_schema = current_schema() AND event_object_table = ?",
        ("timetable_entries",),
    ).fetchall()
    actual_triggers = {str(r["trigger_name"]) for r in trigger_rows}
    if actual_triggers != _EXPECTED_TRIGGERS:
        raise RuntimeError(f"timetable_entries triggers incompatible: {sorted(actual_triggers)}")


def migration() -> PostgresMigration:
    return PostgresMigration(version=MIGRATION_VERSION, name=MIGRATION_NAME,
                             apply=apply_timetable_entries, source=MIGRATION_SOURCE)
