#!/usr/bin/env python3
"""Generate PostgreSQL DELETE tombstone triggers from reviewed SQLite inventory.

Fail-closed generator: only known OLD-row school-scope expressions are accepted.
It emits SQL and never connects to or modifies a database.
"""
from __future__ import annotations
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PLAN = ROOT / "postgres_trigger_porting_plan.json"
SCHEMA = ROOT / "postgres_effective_schema_snapshot.json"
OUTPUT = ROOT / "postgres_tombstone_triggers.sql"
DOC = ROOT / "POSTGRES_TOMBSTONE_TRIGGERS.md"
CATEGORY = "soft_delete_or_sync_tombstone"
IDENT = re.compile(r"^[a-z][a-z0-9_]*$")

# These expressions are taken from db.py's _TOMBSTONE_SCHOOL_EXPR and the
# later student_skill_ratings migration. No arbitrary SQL from the inventory
# is interpolated into the generated PostgreSQL source.
SCHOOL_SCOPE = {
    "attendance_records": "SELECT school_id FROM classes WHERE id = OLD.class_id",
    "class_subjects": "SELECT school_id FROM classes WHERE id = OLD.class_id",
    "classes": "OLD.school_id",
    "enrollments": "SELECT school_id FROM classes WHERE id = OLD.class_id",
    "grade_scale": "OLD.school_id",
    "grading_config": "OLD.school_id",
    "materials": "OLD.school_id",
    "scores": "SELECT c.school_id FROM students s JOIN classes c ON c.id = s.class_id WHERE s.id = OLD.student_id",
    "sessions": "OLD.school_id",
    "staff_attendance": "OLD.school_id",
    "student_skill_ratings": "SELECT c.school_id FROM students s JOIN classes c ON c.id = s.class_id WHERE s.id = OLD.student_id",
    "student_term_info": "SELECT c.school_id FROM students s JOIN classes c ON c.id = s.class_id WHERE s.id = OLD.student_id",
    "students": "SELECT school_id FROM classes WHERE id = OLD.class_id",
    "subjects": "OLD.school_id",
    "terms": "SELECT school_id FROM sessions WHERE id = OLD.session_id",
    "timetable_entries": "OLD.school_id",
    "timetable_periods": "OLD.school_id",
    "users": "OLD.school_id",
}


def load_inputs():
    plan = json.loads(PLAN.read_text())
    schema = json.loads(SCHEMA.read_text())
    triggers = [x for x in plan["triggers"] if x.get("category") == CATEGORY]
    if len(triggers) != 18:
        raise ValueError(f"Expected 18 tombstone triggers; found {len(triggers)}")
    return triggers, schema


def validate(triggers, schema):
    tables = {t["name"]: {c["name"] for c in t["columns"]} for t in schema["tables"]}
    if "sync_tombstones" not in tables:
        raise ValueError("sync_tombstones table missing from effective schema")
    required_tombstone_cols = {"school_id", "entity", "client_uuid", "deleted_at"}
    if not required_tombstone_cols <= tables["sync_tombstones"]:
        raise ValueError("sync_tombstones is missing required columns")
    seen = set()
    for item in triggers:
        name, table = item.get("name", ""), item.get("table", "")
        if not IDENT.fullmatch(name) or not IDENT.fullmatch(table):
            raise ValueError(f"Unsafe identifier: {name!r}/{table!r}")
        if name != f"trg_{table}_tombstone" or table in seen:
            raise ValueError(f"Unexpected or duplicate tombstone trigger: {name}")
        seen.add(table)
        if item.get("event") != "DELETE" or item.get("timing") != "AFTER":
            raise ValueError(f"Unexpected timing/event for {name}")
        if table not in tables or not {"client_uuid"} <= tables[table]:
            raise ValueError(f"{table} lacks required client_uuid column")
        if table not in SCHOOL_SCOPE:
            raise ValueError(f"No reviewed school-scope mapping for {table}")
        sql = re.sub(r"\s+", " ", item.get("source_sql", "")).strip()
        required = ["AFTER DELETE ON", table, "WHEN OLD.client_uuid IS NOT NULL",
                    f"'{table}'", "OLD.client_uuid", "sync_tombstones"]
        if any(token not in sql for token in required):
            raise ValueError(f"Unexpected source trigger structure for {name}")
        if "strftime('%Y-%m-%dT%H:%M:%S','now')" not in sql:
            raise ValueError(f"Unexpected tombstone timestamp format for {name}")
    if seen != set(SCHOOL_SCOPE):
        raise ValueError(f"Inventory/mapping mismatch: missing={sorted(set(SCHOOL_SCOPE)-seen)}, extra={sorted(seen-set(SCHOOL_SCOPE))}")
    return sorted(seen)


def generate(tables):
    out = [
        "-- Generated by tools/build_postgres_tombstone_triggers.py",
        "-- Ports 18 SQLite AFTER DELETE tombstone triggers.",
        "-- Review POSTGRES_TOMBSTONE_TRIGGERS.md before applying.", "",
        "CREATE OR REPLACE FUNCTION app_record_sync_tombstone()",
        "RETURNS trigger", "LANGUAGE plpgsql", "AS $$", "DECLARE",
        "    v_school_id integer;",
        "    v_deleted_at text := to_char(date_trunc('second', clock_timestamp() AT TIME ZONE 'UTC'),",
        "                                'YYYY-MM-DD\"T\"HH24:MI:SS');",
        "BEGIN", "    IF OLD.client_uuid IS NULL THEN", "        RETURN OLD;", "    END IF;", "",
        "    CASE TG_TABLE_NAME",
    ]
    for table in tables:
        expr = SCHOOL_SCOPE[table]
        out.append(f"        WHEN '{table}' THEN")
        if expr.startswith("OLD."):
            out.append(f"            v_school_id := {expr};")
        else:
            out.append(f"            {expr} INTO v_school_id;")
    out += [
        "        ELSE", "            RAISE EXCEPTION 'No tombstone school-scope mapping for table %', TG_TABLE_NAME",
        "                USING ERRCODE = '22023';", "    END CASE;", "",
        "    INSERT INTO sync_tombstones (school_id, entity, client_uuid, deleted_at)",
        "    VALUES (v_school_id, TG_TABLE_NAME, OLD.client_uuid, v_deleted_at);",
        "    RETURN OLD;", "END;", "$$;", "",
    ]
    for table in tables:
        out += [
            f"DROP TRIGGER IF EXISTS trg_{table}_tombstone ON {table};",
            f"CREATE TRIGGER trg_{table}_tombstone", f"AFTER DELETE ON {table}",
            "FOR EACH ROW", "WHEN (OLD.client_uuid IS NOT NULL)",
            "EXECUTE FUNCTION app_record_sync_tombstone();", "",
        ]
    return "\n".join(out)


def main():
    triggers, schema = load_inputs()
    tables = validate(triggers, schema)
    OUTPUT.write_text(generate(tables))
    DOC.write_text(f'''# PostgreSQL sync tombstone triggers (Stage 15)\n\n## Scope\n\nThis stage ports all **18 SQLite AFTER DELETE tombstone triggers** across **{len(tables)} tables**. The generated SQL is in `postgres_tombstone_triggers.sql`.\n\n## Preserved behavior\n\n- A tombstone is written only when the deleted row has a non-NULL `client_uuid`.\n- One tombstone is written per deleted row, in the same transaction as the DELETE.\n- `entity` is the originating table name and `client_uuid` is copied from `OLD`.\n- `school_id` uses the reviewed source mapping: direct `OLD.school_id` or the same class/student/session parent lookup used by SQLite. A missing parent yields NULL, matching the original scalar-subquery behavior and avoiding cross-school delivery.\n- `deleted_at` remains UTC text in `YYYY-MM-DDTHH:MM:SS` seconds-resolution format.\n- A failed tombstone insert aborts the DELETE transaction, preserving atomicity.\n\n## Safety notes\n\n- The generator accepts only the 18 inventoried table names and known source school-scope mappings; unknown shapes fail closed.\n- The trigger function does not issue another DELETE or UPDATE, so it introduces no recursive trigger behavior.\n- `sync_tombstones.school_id` is nullable in the inspected effective schema; NULL remains NULL when a parent lookup returns no row.\n- This SQL is generated only; it has not been applied to a live PostgreSQL server.\n- No changes are made to SQLite local installations or IndexedDB/browser offline behavior.\n\n## Staging validation\n\nTest deletes for each table with NULL and non-NULL client UUIDs, direct and parent-derived school IDs, missing parent rows, multiple-row DELETE statements, and transaction rollback when tombstone insertion fails. Verify the sync pull endpoint filters tombstones by school and advances its cursor correctly.\n''')
    print(f"Generated {len(tables)} PostgreSQL tombstone triggers from {len(triggers)} SQLite triggers")

if __name__ == "__main__":
    main()
