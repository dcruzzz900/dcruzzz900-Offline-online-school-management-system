"""Standalone PostgreSQL migration 148 for immutable subscription history."""
from __future__ import annotations

from postgres_migrations import PostgresMigration

MIGRATION_VERSION = 148
MIGRATION_NAME = "create_subscription_history"
MIGRATION_STATEMENTS = (
    """CREATE TABLE IF NOT EXISTS subscription_history (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        school_id BIGINT NOT NULL, tenant_id TEXT,
        action TEXT NOT NULL,
        previous_status TEXT, new_status TEXT, previous_plan TEXT, new_plan TEXT,
        previous_ends_at TEXT, new_ends_at TEXT, note TEXT,
        actor_id BIGINT, actor_name TEXT, created_at TEXT DEFAULT CURRENT_TIMESTAMP
    )""",
    "CREATE INDEX IF NOT EXISTS idx_subscription_history_school ON subscription_history (school_id, id)",
    "DROP TRIGGER IF EXISTS trg_subscription_history_no_update ON subscription_history",
    "CREATE TRIGGER trg_subscription_history_no_update BEFORE UPDATE ON subscription_history FOR EACH ROW EXECUTE FUNCTION app_reject_immutable_row('Subscription history is append-only')",
    "DROP TRIGGER IF EXISTS trg_subscription_history_no_delete ON subscription_history",
    "CREATE TRIGGER trg_subscription_history_no_delete BEFORE DELETE ON subscription_history FOR EACH ROW EXECUTE FUNCTION app_reject_immutable_row('Subscription history is append-only')",
)
MIGRATION_SOURCE = ";\n\n".join(MIGRATION_STATEMENTS)

_EXPECTED_COLUMNS = {
    "id": ("bigint", True), "school_id": ("bigint", True), "tenant_id": ("text", False),
    "action": ("text", True), "previous_status": ("text", False), "new_status": ("text", False),
    "previous_plan": ("text", False), "new_plan": ("text", False),
    "previous_ends_at": ("text", False), "new_ends_at": ("text", False), "note": ("text", False),
    "actor_id": ("bigint", False), "actor_name": ("text", False), "created_at": ("text", False),
}
_EXPECTED_INDEXES = {"subscription_history_pkey", "idx_subscription_history_school"}
_EXPECTED_TRIGGERS = {"trg_subscription_history_no_update", "trg_subscription_history_no_delete"}


def apply_subscription_history(conn) -> None:
    for statement in MIGRATION_STATEMENTS:
        conn.execute(statement)
    rows = conn.execute(
        "SELECT column_name, data_type, is_nullable FROM information_schema.columns "
        "WHERE table_schema=current_schema() AND table_name=? ORDER BY ordinal_position",
        ("subscription_history",),
    ).fetchall()
    actual = {str(r["column_name"]): (str(r["data_type"]).lower(), str(r["is_nullable"]).upper() == "NO") for r in rows}
    missing = sorted(set(_EXPECTED_COLUMNS) - set(actual))
    wrong = {name: {"actual": actual[name], "expected": expected}
             for name, expected in _EXPECTED_COLUMNS.items() if name in actual and actual[name] != expected}
    if missing or wrong or set(actual) != set(_EXPECTED_COLUMNS):
        raise RuntimeError(f"subscription_history columns incompatible: missing={missing}, wrong={wrong}")
    constraints = conn.execute("SELECT conname, contype FROM pg_constraint WHERE conrelid='subscription_history'::regclass").fetchall()
    if {str(r["conname"]): str(r["contype"]) for r in constraints} != {"subscription_history_pkey": "p"}:
        raise RuntimeError("subscription_history constraints incompatible")
    rows = conn.execute("SELECT indexname FROM pg_indexes WHERE schemaname=current_schema() AND tablename=?", ("subscription_history",)).fetchall()
    if {str(r["indexname"]) for r in rows} != _EXPECTED_INDEXES:
        raise RuntimeError("subscription_history indexes incompatible")
    rows = conn.execute("SELECT trigger_name FROM information_schema.triggers WHERE trigger_schema=current_schema() AND event_object_table=?", ("subscription_history",)).fetchall()
    if {str(r["trigger_name"]) for r in rows} != _EXPECTED_TRIGGERS:
        raise RuntimeError("subscription_history append-only triggers incompatible")


def migration() -> PostgresMigration:
    return PostgresMigration(version=MIGRATION_VERSION, name=MIGRATION_NAME, apply=apply_subscription_history, source=MIGRATION_SOURCE)
