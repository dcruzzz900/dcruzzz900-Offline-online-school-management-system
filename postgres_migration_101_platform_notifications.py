"""PostgreSQL-native migration 101: platform_notifications.

Ported from the effective SQLite schema. Depends on the baseline schools table.
This migration is registered only with the standalone PostgreSQL migration
runner; Flask/SQLite startup remains unchanged.
"""
from __future__ import annotations

from postgres_migrations import PostgresMigration

MIGRATION_VERSION = 101
MIGRATION_NAME = "create_platform_notifications"

MIGRATION_STATEMENTS = (
    r'''CREATE TABLE IF NOT EXISTS platform_notifications (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        title TEXT NOT NULL,
        message TEXT NOT NULL,
        school_id BIGINT,
        read_at TEXT,
        created_at TEXT DEFAULT CURRENT_TIMESTAMP,
        CONSTRAINT fk_platform_notifications_school
            FOREIGN KEY (school_id) REFERENCES schools(id)
    )''',
    "CREATE INDEX IF NOT EXISTS idx_platform_notifications_created ON platform_notifications (created_at DESC)",
)
MIGRATION_SOURCE = ";\n\n".join(MIGRATION_STATEMENTS)

_EXPECTED_COLUMNS = {
    "id": "bigint", "title": "text", "message": "text",
    "school_id": "bigint", "read_at": "text", "created_at": "text",
}


def apply_platform_notifications(conn) -> None:
    """Create the table and verify its columns, school FK and created index."""
    school = conn.execute(
        "SELECT column_name, data_type FROM information_schema.columns "
        "WHERE table_schema = current_schema() AND table_name = ? AND column_name = ?",
        ("schools", "id"),
    ).fetchone()
    if school is None or str(school["data_type"]).lower() != "bigint":
        raise RuntimeError("platform_notifications requires schools.id BIGINT in the current schema")

    for statement in MIGRATION_STATEMENTS:
        conn.execute(statement)

    rows = conn.execute(
        "SELECT column_name, data_type FROM information_schema.columns "
        "WHERE table_schema = current_schema() AND table_name = ? ORDER BY ordinal_position",
        ("platform_notifications",),
    ).fetchall()
    actual = {str(row["column_name"]): str(row["data_type"]).lower() for row in rows}
    missing = sorted(set(_EXPECTED_COLUMNS) - set(actual))
    wrong = {name: {"actual": actual[name], "expected": expected}
             for name, expected in _EXPECTED_COLUMNS.items()
             if name in actual and actual[name] != expected}
    if missing or wrong:
        raise RuntimeError(
            "platform_notifications schema is incompatible; "
            f"missing columns={missing}, incompatible types={wrong}"
        )

    fk = conn.execute(
        "SELECT tc.constraint_name, kcu.column_name, ccu.table_name AS foreign_table_name, "
        "ccu.column_name AS foreign_column_name "
        "FROM information_schema.table_constraints tc "
        "JOIN information_schema.key_column_usage kcu ON tc.constraint_name = kcu.constraint_name "
        "AND tc.constraint_schema = kcu.constraint_schema "
        "JOIN information_schema.constraint_column_usage ccu ON ccu.constraint_name = tc.constraint_name "
        "AND ccu.constraint_schema = tc.constraint_schema "
        "WHERE tc.constraint_type = 'FOREIGN KEY' AND tc.table_schema = current_schema() "
        "AND tc.table_name = ? AND kcu.column_name = ?",
        ("platform_notifications", "school_id"),
    ).fetchone()
    if fk is None or (fk["foreign_table_name"], fk["foreign_column_name"]) != ("schools", "id"):
        raise RuntimeError("platform_notifications school_id foreign key is missing or incompatible")

    index = conn.execute(
        "SELECT indexdef FROM pg_indexes WHERE schemaname = current_schema() AND indexname = ?",
        ("idx_platform_notifications_created",),
    ).fetchone()
    if index is None:
        raise RuntimeError("platform_notifications created_at index was not created")
    definition = str(index["indexdef"]).lower().replace('"', "")
    if "unique index" in definition or "(created_at desc)" not in definition:
        raise RuntimeError("platform_notifications created_at index has an incompatible definition")


def migration() -> PostgresMigration:
    return PostgresMigration(version=MIGRATION_VERSION, name=MIGRATION_NAME,
                             apply=apply_platform_notifications, source=MIGRATION_SOURCE)
