#!/usr/bin/env python3
"""Build a conservative PostgreSQL draft from the application's baseline schema.sql.

This intentionally handles only the narrow, reviewed syntax used by schema.sql.
It does not translate db.py's later SQLite migrations or triggers.
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "schema.sql"
DEFAULT_OUTPUT = ROOT / "postgres_schema_base.sql"

AUTOINCREMENT_RE = re.compile(
    r"\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b", re.IGNORECASE
)


def build_postgres_baseline(source_sql: str) -> str:
    """Translate the known baseline schema constructs; reject unknown SQLite syntax."""
    if not isinstance(source_sql, str) or not source_sql.strip():
        raise ValueError("Baseline schema source is empty")

    # Keep the current INTEGER width so existing INTEGER foreign-key columns
    # remain type-compatible with generated identity primary keys.
    translated, identities = AUTOINCREMENT_RE.subn(
        "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", source_sql
    )
    if identities == 0:
        raise ValueError("No AUTOINCREMENT primary keys found; source may not be schema.sql")

    forbidden = {
        "AUTOINCREMENT": r"\bAUTOINCREMENT\b",
        "SQLite PRAGMA": r"\bPRAGMA\b",
        "SQLite conflict clause": r"\bINSERT\s+OR\s+(?:IGNORE|REPLACE)\b",
        "SQLite rowid": r"\browid\b",
        "SQLite WITHOUT ROWID": r"\bWITHOUT\s+ROWID\b",
    }
    remaining = [name for name, pattern in forbidden.items() if re.search(pattern, translated, re.I)]
    if remaining:
        raise ValueError("Unsupported SQLite syntax remains: " + ", ".join(remaining))

    # The baseline currently uses only PostgreSQL-compatible CREATE TABLE,
    # CREATE [UNIQUE] INDEX, CHECK, UNIQUE, FOREIGN KEY and partial-index forms.
    table_count = len(re.findall(r"\bCREATE\s+TABLE\s+IF\s+NOT\s+EXISTS\b", translated, re.I))
    if table_count < 1:
        raise ValueError("No CREATE TABLE IF NOT EXISTS statements found")

    header = (
        "-- GENERATED from schema.sql by tools/build_postgres_base_schema.py\n"
        "-- Baseline only: does NOT include db.py's subsequent versioned migrations,\n"
        "-- dynamic tables, triggers, tenant backfills, or later schema changes.\n"
        "-- Review and apply only as part of a complete PostgreSQL migration plan.\n\n"
    )
    return header + translated.rstrip() + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=SOURCE)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()

    result = build_postgres_baseline(args.source.read_text(encoding="utf-8"))
    args.output.write_text(result, encoding="utf-8")
    tables = len(re.findall(r"\bCREATE\s+TABLE\s+IF\s+NOT\s+EXISTS\b", result, re.I))
    identities = len(re.findall(r"\bGENERATED\s+BY\s+DEFAULT\s+AS\s+IDENTITY\b", result, re.I))
    print(f"Wrote {args.output}; baseline tables={tables}; identity columns={identities}")
    print("WARNING: this is only the schema.sql baseline, not the full v113 schema.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
